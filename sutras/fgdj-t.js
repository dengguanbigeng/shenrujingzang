複次。舍利弗。南方去此度十萬億佛刹。有世界名曰真珠。其國有佛。號日月燈明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞日月燈明如來名者。持諷誦念。歡喜踴躍。至心信樂而無有疑。如來言教實為快善。無數千人淨心敬信。悲喜情踴為之雨淚。此眾生輩自當憶知。吾等往昔為曾值見此諸佛已。若有女人。其有得聞日月燈明如來名者。歡喜信樂。從是已後所生之處。止更不受女人之身。十方世界其有得聞斯佛名者。皆當得立不退轉地。必成正覺。於諸欲中意常清淨。不為欲垢之所纏縛。此佛刹人及與他方諸眾生類。聞此如來名號者。計其功德不可限量。不以言辭所可稱說。能盡其德。魔王官屬終不堪任毀壞其人無上道心。

佛語舍利弗。魔王常欲索此經便欲斷絕之。所以者何。為諸欲聚之所纏縛。雖爾。舍利弗。斯之伴黨最為後世時。會當信樂斯尊經法而不謗毀其信樂者。斯之正士如優曇花。在於世間宜受一切三界供養。

舍利弗言。惟。天中天。最後末世凶愚暴惡。幾所眾生有能信持日月燈明如來名者。及諸世尊。如來名號歡喜信者。

佛言。我今現在諦觀察之。比丘僧中終不見有。被白衣者最後末世亦複如是。信樂斯經諷誦之者。亦複少有。百萬之中若一若兩。

舍利弗言。設有聽受信斯經者。所得功德為幾許。

佛言。諸如來於無數劫遊於五道。拔濟眾生三塗之厄。滿具一切弘誓之願。興出於世。廣為眾生敷陳妙法。實為難值。用說正法故。多所利益。一切眾生其有聞者歡喜信樂。斯等皆當疾能解了我之智慧。卻生死罪百劫在後。其聞此法不信樂者。斯之等輩我悉見之。

舍利弗言。惟。天中天。有幾所人謗毀斯經。所得罪報受幾時苦。

佛言。斯眾生輩六十億歲於地獄中具受眾罪。為以謗毀諸如來等正覺法故。舍利弗。斯法興盛幾時之間。在所之處。愚癡之人於中造立地獄之行。用謗諸佛。如來之故。是故。舍利弗。夫黠慧者。若族姓子族姓女。最後末世聞此妙法。信不誹謗。宜當自慶。歡喜踴躍。作是思惟。我等不謗如來之法。身之所受惡行苦報吾已得脫。

佛告舍利弗。最後世時。大千世界滿中七寶持用佈施。猶尚易得。聞有讚歎斯眾功德。實難得值——值此法者皆為如來之所護持。

複次舍利弗。南方去此真珠世界。度萬佛刹。有世界名裁光。其國有佛。號曰須彌如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞須彌如來名號者。持諷誦念。歡喜信樂。長跪叉手。當為作禮。當得無比功德之報。魔王不能毀壞其人無上道心。猶須彌山堅住不動。功德甚多。日日增益。不可限量。

複次舍利弗。南方去此裁光世界。度萬四千佛刹。有世界名曰音響。其國有佛。號大須彌如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大須彌如來名。盡心信樂持諷誦念。若至夢中。斯等之人終不更起恚亂之意向諸快士。得不退轉當成正覺。斯諸正士當解妙慧。了一切法猶若如夢。卻八十劫生死之罪。

複次舍利弗。南方去此音響世界。度五千佛刹。有世界名紫磨金。其國有佛。號阿提彌留須彌如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞阿提彌留如來名者。盡心信樂。持諷誦念。所得功德。設使有人持閻浮檀金。布於三千大千世界悉令彌滿持用佈施。其人得福寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人持諷誦念阿提彌留如來名者。淨心信樂。所得功德過出施上百倍有餘。無以為比。若有常念此如來名。卻生死罪十劫在後。

複次舍利弗。南方去此紫磨金界。度二萬佛刹。有世界名色像光。其國有佛。號喻如須彌如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞喻如須彌如來名者。淨心信樂。持諷誦念。以膝著地。長跪叉手。而為作禮。如斯人等當得智慧猶若大海。悉能奉持諸佛之法。疾得成就正覺之道。

複次。舍利弗。南方去此色像光世界。度萬八千佛刹。有世界名過珠光。其國有佛。號曰香像如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞香像如來名號者。彈指之頃恭敬淨意。念斯如來所得功德。假令有人持閻浮檀金。布三千大千世界。悉令彌滿持用佈施。其人得福寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人。口中諷誦香像如來名號者。如彈指頃功德殊特。過出施上百倍有餘。所以者何。一反唱聲稱斯佛名。獲大盈利。何況目覩如來色像。作禮恭敬。及泥曰後入於廟寺。瞻覲形像。禮拜虔恭。所得功德寧可稱乎。

複次舍利弗。南方去此珠光世界。度無數千佛刹。有世界名曰得勇力。其國有佛。號三曼陀揵提香熏如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。舍利弗。其佛。如來本求大乘。為菩薩時作是誓願。我設先世供養諸佛。及複供養彌嘉揵尼如來正覺。燒名好香。丸如芥子。自誓願言。願我今日持此功德成作佛時。身諸毛孔悉出妙香。熏遍十方恒沙世界。猶若雲起。皆令彌滿他方佛國無量世界。一切眾生得具戒香。聞我名者。斯等一切成作佛時。我諸毛孔亦出斯香遍無量國。三曼陀揵提如來。亦自滿具一切諸願。若使有人讚歎。廣說如來名德。若族姓子。族姓女七日之中饑不獲食。故當往聽。歎說如來功德之法。所以者何。聞斯佛名所得功德不可限量。

舍利弗言。如是。世尊。其有得聞三曼陀揵提如來名。所得功德不可稱量。甚多乃爾。最後世時。若族姓子。族姓女聞斯功德歡喜踴躍。及複得聞諸佛名號功德法者。魔王不能毀壞其人無上道心。所以者何。諸佛。世尊皆共擁護此等眾生。是故魔王不能得壞其人道心。

佛言。設我讚歎斯佛功德。眾生聞者。或能惑亂。所以爾者。此等之類福德淺薄。無黠所致不能信持。若有信者。舍利弗。皆當歡喜。踴躍自慶。此等必當成最正覺。而於此中所得功德。我當為汝引少譬喻。諸佛大慈皆欲使人入其法中。十方世界滿中七寶持用佈施。所得功德寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人得聞三曼陀揵提如來名者。得福甚多。過出施上百倍有餘。加複作禮。五體投地。得其福德不可思議。卻生死罪百劫在後。

複次。舍利弗。南方去此得勇力界。度十億佛刹。有世界名曰雲厚無垢光。其國有佛。號曰淨光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞淨光如來名號者。歡喜信樂。持諷誦念。彈指之頃發大慈心。其人至心慕樂斯佛已。自作是言。今我得聞斯佛名號。彈指之頃發大慈心。持此功德。願使十方一切眾生得解如來微妙之慧。當知。舍利弗。斯等眾生發弘誓願。於中所得功德之福。如恒邊沙諸佛國土。滿中七寶持用佈施。其所得福寧為多不。

舍利弗言。甚多。甚多。世尊。不可稱量。

佛言。不如有人誦持淨光如來名者。歡喜踴躍。彈指之頃發大慈心。興弘誓願。所得功德比於佈施過上百倍。諸正士等欲佈施時。當作法施。斯之功德疾得成就正覺之道。卻八十劫生死之罪。

複次舍利弗。南方去此雲厚無垢光界。度萬佛刹。有世界名曰法界。其國有佛。號曰法最如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞法最如來名號者。歡喜信樂持諷誦念。長跪叉手頭面作禮。斯等皆當而能護持諸佛之法。於佛法中所得大利。目見如是。以是之故。皆當信樂持斯佛名。加廣宣傳。闡揚佛德。發尊覺意。不當起心作輕慢行。向於如來敬信之者。悉能滅除三塗之苦。皆由斯德。諸佛。世尊無數劫中。聚眾德本。具如來行實為謙苦久遠難量。乃得成就如來法身。暢達正覺。一切之智實為甚難。以是之故不當生慢。皆當興立敬信之心向於如來。一切世界設滿中水。水上有板而板有孔。有一盲龜。於百歲中乃一舉頭。欲值於孔。斯亦甚難。求索人身甚難。甚難。於此欲得除去八難之患。若有得聞斯經法者。眾難。惡道皆悉永絕。以是之故。當發大願求解最尊無比之法。若一發意於如來者喜心信樂。斯等疾近正覺之道。卻二十劫生死之罪。

複次。舍利弗。南方去此法界。度五萬五千佛刹。有世界名曰星自在王。其國有佛。號香自在王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞香自在王如來名者。歡喜信樂持諷誦念。長跪叉手。自作是言。我今禮香自在王如來。至真。等正覺。當發大慈持功德聚。使諸如來及諸弟子長受天樂。亦受法樂。一切眾生皆亦如是。若使有人不慕泥洹。斯等皆當住不退轉。疾成正覺。三千世界滿中七寶。持用佈施滿千歲中。所得功德寧為多不。

舍利弗言。甚多。世尊。

佛言。不如有人持斯佛名發大慈心得福甚多。比於施德過上百倍。卻三十劫生死之罪。

複次。舍利弗。南方去此星自在王世界。度萬佛刹。有世界名曰正真。其國有佛。號大集如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大集如來名號者。歡喜信樂。持諷誦念。如此人等與諸佛法常共合偶。亦不起意樂入泥洹。

複次。舍利弗。南方去此正真世界。度八千佛刹。有世界名曰廣博。其國有佛。號香光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞香光明如來名號者。歡喜信樂。持諷誦念。斯等皆當得不退轉。成最正覺。所以者何。香光明如來本遊菩薩徑路之時。作是誓願。我作佛時。一切眾生聞我名者得不退轉。疾成正覺。在於三塗恐怖之中。疾得解脫。

複次。舍利弗。南方去此廣博世界。度二萬佛刹。有世界名曰廣遠。其國有佛。號曰火光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞火光如來名號者。歡喜信樂。持諷誦者。斯等皆得無限之福。其有謗毀而不信者。獲無量罪。

複次。舍利弗。南方去此廣遠世界。度萬五千佛刹。有世界名曰無崖際。其國有佛。號無量光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無量光如來名者。盡心淨意。歡喜信樂。斯等眾生。為此如來光明威神之所護持。卻生死罪十劫在後。其有謗毀而不信者。當二十劫在波多畔泥犁中。

複次。舍利弗。南方去此無崖際界。度二萬佛刹。有世界名曰堅固。其國有佛。號曰開光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞開光如來名號者。歡喜信樂。持諷誦者。魔王眾兵不能毀壞其人道心。

複次。舍利弗。南方去此堅固世界。度二千五百佛刹。有世界名曰馬瑙。其國有佛。號月燈光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞斯佛名者。持諷誦念。斯等皆當為世作導。應當得受世之供養。斯其人等為持天上之牢杖也。當知。舍利弗。此諸佛名在於郡縣。丘聚。村落。諸國邑則神塔也。所以者何。舍利弗。最後末世。斯諸快士。正覺之名甚難得值。其有聞者皆當歡喜。一心信樂。

複次。舍利弗。南方去此馬瑙世界。度八千佛刹。有世界名曰妙香。其國有佛。號日月光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞月光如來名號者。歡喜信樂。持諷誦念。若於夢中若聞。若說展轉相語。此輩皆當歡喜踴躍。當得無量功德之報。道心堅固如須彌山。不可傾動。一切魔王不能毀壞。

複次。舍利弗。南方去此妙香世界。度萬佛刹。有世界名曰為日。其國有佛。號日月光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其佛國土無有四路。何等為四。無有地獄。餓鬼。畜生。貧窮下賤。其佛。世尊本求道時。作是誓願。設我成佛。若泥洹後。其有眾生聞我名者。皆當得住不退轉地。疾成無上正真之道。亦使此等成立國土。無上道田所願具足。亦當如我眾願悉滿。舍利弗。若有得聞月光明如來名者。歡喜信樂。持諷誦念。此等眾生亦當具滿無上道願。如此世尊。

複次。舍利弗。南方去此日世界。度萬八千佛刹。有世界名曰金珠光明。其國有佛。號曰火光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞火光如來名號者。信樂歡喜。持諷誦念。斯等已持智慧之炬。越度一切生死之海。當各精進。一心信行。晝夜常念。莫得疑懈。當廣宣化。設於法施。一切魔王不能毀壞其人道心。況於外道能毀呰耶。

複次舍利弗。南方去此金珠光明世界。度萬六千佛刹。有世界名曰眾色像逆鏡。其國有佛。號曰集音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有眾生生彼佛刹。甫當生者。現已生者。此等正士過逾一切人。天像貌。眾相嚴容。端正姝妙光明巍巍。非天。世人所受之體。其有得聞集音如來名號者。歡喜信樂。持諷誦念。後生之處常得端政。顏容妙好。心常歡喜。信樂諸佛。

複次舍利弗。南方去此眾色像界。度萬三千佛刹。有世界名曰眾聚。其國有佛。號最威儀如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞最威儀如來名者。歡喜信樂。持諷誦念。其人為得世間最尊。天。龍。鬼神之所敬仰。卻二十劫生死之罪。

複次舍利弗。南方去此眾聚世界。度十萬佛刹。有世界名曰勝戰超度無極。其國有佛。號光明尊如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞光明尊如來名者。歡喜信樂。持諷誦念。若天若人。閱叉。鬼神斯眾生因此功德。會得成就正覺之道。卻三十劫生死之罪。若有輕謗而不信者。滿八萬歲在於大泥犁具受眾苦。

複次。舍利弗。南方去此勝戰超度無極世界。度五千佛刹。有世界名一切音響。其國有佛。號蓮花軍如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞蓮花軍如來名者。歡喜信樂。持諷誦念。若使有人大千刹土。滿中珍寶持用佈施。其人得福寧為多不。

舍利弗言。甚多。甚多。世尊。不可稱量。

佛言。不如有人持諷誦念蓮花軍如來名者。所得功德過於佈施功德者上。常與諸佛。世尊共會。卿舍利弗。汝曹不能都盡堪任聽此功德。斯佛。世尊從久已來。於諸禪中具諸德本。其有信持此佛名者。其人皆當超過三界。猶若蓮花從水踴出。

複次。舍利弗。南方去此音響世界。度二萬佛刹。有世界名曰月光。其國有佛。號蓮花響如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。舍利弗。此如來尊何故名曰號蓮花響。初升道場。坐蓮花上成最正覺。無數諸天在虛空中。異口同音共唱聲言。蓮花響佛今出於世。其音遍聞大千刹土。以是之故號蓮花響。其有得聞斯佛名者歡喜信樂。長跪叉手。自作是言。我今禮蓮花響如來。至真。等正覺。斯等終不墮於惡道。遊諸恐難疾得解脫。惟除五逆惡罪行者。

複次。舍利弗。南方去此月光世界。度三萬佛刹。有世界名天自在。其國有佛。號曰多寶如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。舍利弗。其佛。世尊何故名曰為多寶乎。本遊菩薩徑路之時。有不可計聲聞之眾。悉來從其啟受經法。異口同音共作是言。斯之正士乃能有此深妙法寶。因號名曰為多寶也。若族姓子。族姓女。其有得聞斯佛名者。歡喜信樂。長跪叉手。三反稱言。我今禮多寶如來。至真。等正覺。其人所生在諸佛刹。心常解了一切諸法。所以者何。斯佛世尊為菩薩時發是誓願。如此人者自成法寶。以寶為徒從。

複次。舍利弗。南方去此天自在界。度二萬佛刹。有世界名曰蓮花。其國有佛。號師子吼如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞師子吼如來名者。歡喜信樂。長跪叉手。三舉聲言。我今禮此師子吼如來。至真。等正覺。斯其人等所生之處皆當悉能作師子吼。聲揚法音遍於三千。化度無量眾生之類。卻五十劫生死之罪。

複次。舍利弗。南方去此蓮花世界。度萬佛刹。有世界名曰明星。其國有佛。號師子音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐度人無量。其有得聞師子音如來名者。歡喜信樂。持諷誦念。斯其人等後生之處。得無量音。及得如來淨光之音。所以者何。若散花香於虛空中。稱南無佛。得福無量。況覩靈廟如來形像。至心禮敬。散花香者。斯等在世猶若好花。莫不鮮澤。

複次舍利弗。南方去此明星世界。度萬五千佛刹。有世界名曰無憂。其國有佛。號精進軍如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞精進軍如來名者歡喜信樂。持諷誦念。一心奉信無憂刹土。以清淨心盡誠敬信於此如來。斯等皆當成等正覺。能為眾生廣轉法輪。所以者何。其如來尊本求道時興此誓願。吾成正覺。一切眾生聞我名者。其人皆當生我刹土。悉當具滿如來之慧。舍利弗。若有謗毀。輕慢。不信。更相調戲。持用作笑。此輩億歲在地獄中具受罪報。

複次。舍利弗。南方去此無憂世界。度萬佛刹。有世界名金剛聚。其國有佛。號金剛踴躍如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞金剛踴躍如來名者。一心信樂。持諷誦念。若於夢中聞斯佛名。其人皆能破壞三毒。消散諸欲。得不退轉於諸佛法。

複次舍利弗。南方去此金剛聚世界。度千億佛刹。有世界名曰恐明珠。其國有佛。號度一切禪絕眾疑如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞度一切禪絕眾疑如來名者。歡喜信樂至心諷誦念其如來。若複有人說斯佛名。其有聽者當以質直。無諛諂意宣傳之者。真正說之。斯等皆能壞眾魔兵及諸外道倒見之徒。悉能決散一切疑結。必得成就正覺之道。

複次。舍利弗。南方去此恐明珠世界。度千八百佛刹。有世界名曰花香。其國有佛。號寶大侍從如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。舍利弗。若有得聞寶大侍從如來名者。歡喜踴躍。一心信樂。持諷誦念。斯其人等能為世間作大珍寶。當轉無上正法之輪。如是。舍利弗。聞斯佛名信樂之者。得大利益。功德乃爾。其有畏惡生死之難。傾其心意著在聲聞。緣覺之道。此等徒類小誓淺智。志存下劣。不能堪任尊妙之道。放舍如來廣大之慧。斯之等輩不能信解此深妙義。其有眾生求廣妙慧。傾於眾德著最特妙乘。於此法中。但當求索無盡之藏。除去慳心褊狹局意。發無蓋哀。但欲充滿眾生之願。作是施與。於如來田得無盡報。會當解了正覺之慧。能以財寶施與眾生。令使一切各得快樂。願此眾德著於無上正真道中。舍利弗。其有得聞斯佛名者。及諸如來功德名號。加廣宣傳稱揚說時。若有不信謗毀之者。四十億歲在加羅秀領泥犁之中具受眾苦。

複次。舍利弗。南方去此花香世界。度六千佛刹。有世界名曰喜起。其國有佛。號曰無憂如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞。無憂如來名號者。發歡喜心。信樂諷誦。斯諸人等於眾欲中無所污染。不為諸欲之所拘礙。心如蓮花不著塵水。得不退轉。悉能安隱一切眾生。後成正覺。若有眾生聞其名號。至心諷誦。歡喜信樂。若存在世。若泥曰後。斯等亦得最特妙乘。為世導師。皆當逮得無量功德。所生之處。其人未曾不值佛時。

複次。舍利弗。南方去此喜起世界。度二萬佛刹。有世界名曰哀色。其國有佛號地力持踴如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞地力持踴如來名者。淨心歡喜。持諷誦念。五體投地而為作禮。念其如來一日一夜。斯人當得立不退轉。難動如地。一切眾魔不能毀壞其人道心。得無量慧猶若大海。斷生死路。卻二十劫生死之罪。

複次。舍利弗。南方去此哀色世界。度十四佛刹。有世界名曰為天。其國有佛。號最踴躍如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞最踴躍如來名者。歡喜踴躍。持諷誦念。長跪叉手而為作禮。當作是言。我今禮最踴躍如來。至真。等正覺。此等眾生當為最特殊妙大乘之所捉持。亦能饒益一切眾生。三塗。八難悉為永除。

複次。舍利弗。南方去此天世界。度八千佛刹。有世界名栴檀光。其國有佛。號曰自在王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞。自在王如來名者。益加信樂。若更相勸持此佛名。斯皆當得無量之福。舍利弗。若有說此如來名時。若天。若人。龍及閱叉。一切非人。其有聞此如來名者。此等皆當得不退轉於正真道。

複次。舍利弗。南方去此栴檀光世界。度二十億佛刹。有世界名一切伎樂震動。其國有佛。號無量音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞。無量音如來名者。歡喜信樂如來功德。當發此願。以此功德。使我解了如來智慧。斯皆當住不退轉地。必成無上正真之道。所以者何。此如來尊為菩薩時。興大弘誓。立此願故。若有不信誹謗之者。於地獄中長受眾苦。罪畢得出。所生之處常不遇值諸佛之世。舍利弗。其佛世界何故名曰伎樂震動。無量音佛本從兜術降神之時。始發一切伎樂之音聲。普震動揚其樂音聲。天上。世間乃至非人一切伎樂所不能及。其佛住壽在世之時。說法教化至於泥曰。其佛國土伎樂之音聲續美暢。震於十方二十佛刹。以是之故。號無量音。

複次。舍利弗。南方去此一切伎樂震動世界。度三百億佛刹。有世界名集光明。其國有佛。號曰錠光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。舍利弗。其如來尊停住光明。照他佛國。十萬億刹常以大明。以是之故名曰錠光。其有得聞斯佛名者。一心信樂。歡喜踴躍。無諛諂意。斯等當為如來光明之所護持。

複次舍利弗。南方去此集光明世界。度八萬佛刹。有世界名一切香。其國有佛。號寶光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶光明如來名者歡喜信樂。持諷誦念。斯等皆當為於世間作大珍寶。住不退轉於正真道。所生之處常值佛世。初不曾生無佛之處。遊於菩薩徑路之時。卻五十劫生死之罪。是故。舍利弗。不當起於瞋恚。忿亂向諸菩薩及諸弟子。惟當興立大慈之心而奉敬之。當求如來廣妙之慧。發弘誓願趣至大乘。舍利弗。如是其人。疾近無上正真之道。廣演如來深妙之法。若使有人未入泥洹。在菩薩之境界者。不信佛法。亦不信有行菩薩道。言佛道難得。如是之人。滿於千歲在地獄中具受眾罪。是故。舍利弗。不當起瞋恚之意向於蟲䗍。況持惡意向諸快士。癡蓋所覆。無慚愧者。於中謗毀益牢地獄諸罪之行。舍利弗。諸佛興世甚難。甚難。百億之數發意求道。至時得者若一。若兩。當知。舍利弗。如來興世如優曇花。時時乃有。不可見也。其求大乘。發弘誓願。已有發者。甫當發者。今現發者。起勇猛意。不沈疑者。當如所願疾成不久。廣施法食。具正覺道。如是南方諸佛之等不可稱計。今現康常廣說經法。其有聞者。廣演。興顯。歎揚如來無量功德。當向南方五體投地。念諸如來。稱其名號而為作禮。其人得福不可計量。
