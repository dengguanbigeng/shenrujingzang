複次。舍利弗。西方去此度十萬億佛刹。有世界名曰安樂。其國有佛號阿彌陀如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。若有得聞無量壽如來名者一心信樂。持諷誦念。當起廣遠無量歡喜安立其意。令使真諦十萬億信心念斯如來。其人當得無量之福。永當遠離三塗之厄。命終之後皆當往生彼佛刹土。命欲終時一心信樂。念不忘舍阿彌陀佛。將諸眾僧住其人前。魔終不能毀壞斯等正覺之心。所以者何。其佛。世尊興立大悲。誓度一切無量眾生。亦複護持十方世界一切眾生。其有得生安樂世界。當於其中具滿如來正覺之慧。舍利弗。其佛。世尊本求誓願。其有求於第一之乘。於其世界具滿如來諸佛之法。具正覺分。求聲聞乘。於彼佛刹得阿羅漢。其有往生彼佛刹者。從其所願大。小之乘。於彼畢滿。其有最後聞阿彌陀如來名號。贊說之者信不狐疑。當起敬心至意念之。如念父母。作如是意。斯等普當於彼佛國具滿眾願。其有不信讚歎。稱揚阿彌陀佛名號。功德而謗毀者。五劫之中當墮地獄。具受眾苦。

複次。舍利弗。西方去此十萬佛刹。有世界名破一切魔。其國有佛。號曰殊勝如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞殊勝如來名號者歡喜信樂。持諷誦念。此等皆能降伏眾魔。裂壞羅網。卻六十劫生死之罪。

複次。舍利弗。西方去此十萬佛刹。有世界名曰伏一切魔。其國有佛。號曰集音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞集音如來名號者。歡喜信樂。持諷誦念。其人當得一切如來諸佛音聲。於大眾中廣說法處。於中特尊。退卻眾魔。降之以德。卻八十劫生死之罪。

於是阿逸菩薩長跪叉手。前白佛言。寧有一事。菩薩摩訶薩於此事中具大乘願。住不退轉。疾成無上正真道不。

佛言。有。阿逸。北方有世界名曰豐嚴。其國有佛。號德內豐嚴王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞斯佛名者。歡喜信樂。持諷誦念而為作禮。其人皆當得不退轉。疾成無上正真之道。卻一億劫生死之罪。其有供養五千佛者。此輩。阿逸。爾乃得聞德內豐嚴王如來名號。其聞名者。從是以後所生之處常得天眼。未曾不得天眼之時。常能徹聽。未曾不得天耳之時。常能飛行。無有不得神足之時。乃至泥曰。常得端政。未曾受於醜惡之形乃至泥曰。常當尊貴。未曾生於下劣之處。乃至泥曰。悉能除壞眾欲之縛。其人六情眼。耳。鼻。口及於身。意終無有疾。乃至泥曰。初未曾生無佛之處。聽大尊法。未曾有礙不得聽時。未曾有礙不見僧時。亦複不生八難之處。戒常具足。無有缺時。識心清淨。無有忿亂時。當知。阿逸。其有得聞此佛名者。淨心信樂於最正覺。如渴欲飲。發信敬心向如來者。此等。阿逸。悉能捉持諸佛世界最特之利。其人皆當獲於殊妙奇特功德。是故。阿逸。並當專精持此佛名。若族姓子。族姓女欲得殊特妙淨刹者。當急聽此諸尊佛名。稱其名號當為作禮。自作是言。我今禮於德內豐嚴王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。

阿逸白佛言。惟。天中天。其佛刹土為在何所。去此遠近。成佛以來為幾時也。

佛告阿逸。設使縱廣百由延中一大埠沙。取一沙著一佛刹。如是悉著諸佛刹中悉令沙盡。如是沙數諸佛刹土悉滿中沙。複取諸佛刹土中沙。複以一沙。著一佛刹。如是諸國刹中沙悉使令盡。取此沙數。諸佛刹土悉破為塵。複取一塵著一佛刹悉令塵盡。是諸佛國塵數刹土猶尚未至。餘未到者。過此百倍。其佛刹土去此極遠。不可稱量。其佛。世尊在彼豐嚴刹土之中。而今現。在與無央數諸開士等。不可稱計諸比丘眾。前後圍繞而為說法。我於此坐。遙用肉眼。見其如來於大眾中廣說經法。彼佛。世尊於彼刹土在高座上。亦用肉眼觀此世界。亦複見我在於座上於大眾中而說經法。阿逸當知。若有眾生信諸如來肉眼所見。而歡喜者。此必成就正覺之道。斯等皆諸佛。如來之所護持。令使信樂而不狐疑。斯等皆當捉持如來深妙之慧。得不退轉於最正覺。是故。阿逸。其有欲求此大福者。若使三千大千世界滿其中火。故當入中聽斯佛名智慧之法。

阿逸菩薩複白佛言。寧有一法得不退轉。疾成無上正真道不。

佛言。有。阿逸。北方去此不可計數諸佛刹土。有世界。名曰金剛堅固。其國有佛。號金剛堅強消伏壞散如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞金剛堅強消伏壞散如來名者。歡喜信樂持諷誦念。盡心供養。斯等皆當住不退轉。疾成無上正真之道。卻於十萬億那術劫生死之罪。超然在後。其佛。如來功德無量弘誓乃爾。我自過去無數劫前。錠光如來興出於世。於彼佛所而得聞此金剛堅強消伏壞散如來名號。得超十萬億那術劫生死之罪。阿逸當知。若我不從錠光聞斯佛名者。我今故未得成正覺。其佛何故名曰金剛堅強消伏壞散。譬如金剛所在墮處。若山。若崖。瓦石。土壘。牆壁。樹木。若遙擬向所墮之處。莫不消滅破碎。壞散。如是。阿逸。其有得聞此佛名者持諷誦念。一切諸欲皆疾消散。一切聲聞。辟支佛心褊狹之意皆悉消滅。疾得成就正覺之道。是故號曰金剛堅強消伏壞散如來。其佛。世尊。一切眾願具滿如是。

複次。阿逸。北方去此度十萬億諸佛刹土。有世界名摩尼光。其國有佛。號曰寶火如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶火如來名號者。歡喜信樂。持諷誦念。其有未入泥洹界者。斯等一切皆當得立不退轉地。疾成無上正真之道。其佛刹土一切人民。供養寶火如來者。悉一大乘而得度脫。無有聲聞。緣覺之名。

佛告長老大迦葉。當知諸佛。如來之德不可思議。北方去此五十萬佛刹。有世界名阿竭流香。其國有佛。號寶月光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。迦葉。若族姓子。族姓女。其有得聞寶月光明如來名者。歡喜信樂。持諷誦念。此等後世所生之處。得不中止三昧正定。若三昧時。自見諸佛轉尊法輪。悉能總持諸佛之法。在所生處常為眾生闡揚大法。辯才清妙。於眾特尊。諸所欲求。從願悉得。所以者何。其佛。世尊本求道時。興此誓願。吾成正覺聞我名者。令使得此三昧定意。從初發意至於成道。於其中間常得此定。未曾中失。

於是世尊而歎頌曰。

度五十萬諸佛刹。有世界名阿竭流。
其國有佛號寶月。光明晃昱甚巍巍。
其有得聞此尊名。便為已得所依仰。
後生之處則得禪。精進智慧無中止。
名聲普達光圍繞。其人見佛在刹土。
為諸眾生廣興演。諸佛導師所說法。
一切諸事無堅固。觀諸法中無所起。
普當慈哀於一切。於諸禪中得自在。
已能發行如是意。都了三塗無恚忿。
審諦解了無吾我。無所有者非無有。
諦了諸事無所得。於此中間所興法。
如是法者無所住。求了表識無表識。
此二俱空亦無性。興顯如是無我法。
無表識者是空義。當審諦說此妙法。
表識可了不可了。此二俱轉於癡慧。
諦觀此二俱清淨。亦不復見諸法垢。
所說法者無所猗。都了無依波羅蜜。
譬如月行於空中。其所說法無所猗。
如此妙法興是間。於三界中無所著。
菩薩法中無所依。解如是者一切智。
解了此法為人說。若能解達無猗法。
審諦分別如是者。其人則為近大智。
慧者得聞無依句。終無複有狐疑計。
其人解了如是者。於世獨達無所諮。
暢達如是大智慧。號曰特尊無上士。

複次迦葉。北方去此六萬佛刹。有世界名長歡樂。其國有佛。號曰賢最如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞賢最如來名號之者歡喜信樂。持諷誦念。所生之處。當為一切之所敬愛。哀見信用。其所言教。莫不承奉。其人皆當獲斯功德。得無礙辯。所說經法。眾生聞者。歡喜信解。莫不履行。

於是世尊而歎頌曰。

度於六萬諸佛刹。有界名曰長歡樂。
慈哀度法賢最尊。其大導師在世界。
最尊無比無與等。世世濟度諸眾生。
其聞名者作法師。言奉信用莫不歡。
此一切智大法王。無量黎庶斯依仰。
若有女人聞其名。疾得舍離女人形。
穢惡甚深無崖際。非離世者不能入。
其無所有所可入。是為審諦諦不諦。
了此二事俱無性。其已寂滅無有性。
其有盡者以為滅。甫當興者亦無性。

複次迦葉。北方去此八千佛刹。有世界名曰現入。其國有佛。號寶蓮華步如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。若族姓子。族姓女。其有得聞寶蓮花步如來名者。歡喜信樂。持諷誦念。後生之處。顏貌端政。殊妙無比。眾共敬愛。自識宿命無數劫中事。皆悉了知。生所從來。所作善惡悉皆識知。其所生處。所說言教一切信奉。莫不承用。迦葉。若族姓子。族姓女得聞斯等諸如來尊。正覺名號。功德之行。若有愛樂女人身者。如是女人在於女中未得解脫。若厭女人身。不貪樂者。持諷誦念諸佛名者。盡可得斯等德。

迦葉白佛。當複雲何得此功德。

佛言。絕諸名色。盡諸欲垢。斯等疾逮無量功德。當疾遠離女人之身。當得具受男子之形。求為女者。所生之處。續受女人之身。都悉污穢一切世界。是故當棄女人之身。當得無比諸善知識。功德日生。亦自受福。複利他人多所饒益。一切男女於眾苦中疾得拔濟。譬若毒樹所在之處。蔓莚生長多所傷害。若能斷截諸毒樹者。爾使一切普得快樂。女人之身譬若毒樹。增長諸欲。毒害精神。廣諸惡行。受無量苦。皆由女人。若能斷棄女人身者。則為斷絕眾生無量諸苦。壞眾惡行。閉絕三塗。開泥洹門。普使一切而得快樂。斯等疾入諸佛徑路。

迦葉白佛。雲何得除女人之身。

佛言。當自觀身。觀他人身。解此二事俱不可得。不可得中無有徑路。若於男子及女人中觀其處所。男女相貌亦不可得。若了二事亦不可得。無處所者。當於其中願得清淨。若以清淨則無取捨。以無取捨便無識心。諦推覓之。亦不可得無有處所。意自思惟。無處所中。為求男子成女人乎。諦求索之。意不可得。若解意性。了無男女不可見者。爾乃得近如來之道。其欲發心疾欲除去女人之身。諦觀男子。女人之身。了無異同。增減之二。當受女人作女人形。如其所說以理推之。六性分中亦不可得有男有女。其如是者。則為求索如來之道。其欲求解如此事者。複有諦了知此法者。是二輩人過去佛時。曾得聞此諸佛名號。當知其人過去世時。於諸佛所造大功德。今乃聞此諸佛名號。世所依仰為自在者。其奉持此諸尊號者獲無量福。其有聞者。若有學者。我普見之。有欲急求。得此經者。斯等已為見我無異。若有輕慢其人。說言此非佛語。作是言者。此等便為謗佛。毀經。謗斯經已為造大惡。緣此惡行當入地獄。受眾苦報無央數劫。地獄罪畢所生之處。常當聾瘂不能言語。諸情閉塞常不完具。常當愚癡而有癲狂。其有嬈固諸菩薩者。薄德醜陋。言無威勢常生下賤。常生惡道。所生之處常不聞法。如來正覺所說經法。終不能解說深妙義。愚癡之人與經共諍廣受罪報。增益其意毀斯經法。此眾生輩生常愚癡。諸佛正覺常為世間而作大明。我重慇懃誡囑汝等諸比丘及比丘尼。清信士清信女。其有謗毀罵經法者實受重罪。諸佛。世尊現在十方。無量世界為作法師。所說經法實難得聞。如來慈湣重誡汝等。若有信樂諸佛名號功德法者。於諸善法自然合偶。其有學持諷誦念者。其人疾得見諸如來。智慧轉增。得無礙慧。其有勸人讀諸佛名。所生之處。遊四方域。獨言只步而無所畏。其有好樂盡心敬奉此諸佛名。當知其人去正覺道終不復遠。其有好憙諸佛功德。加益勸人學斯佛名。其人所在於諸如來所遊行處。於諸欲中無所畏難。當知。迦葉。若有比丘具四事法。乃能信此諸佛尊名。何等為四。過去世時於諸佛所得聞深法。憙樂靜寞清淨之處。世世值遇諸善知識。不於法中作危難行。當知。迦葉。是為四事。若有比丘以能具此。於諸如來正覺法中而無疑難。其人得聞如來功德。爾乃一心能信樂之。

