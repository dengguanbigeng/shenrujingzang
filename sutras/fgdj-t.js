南無本師釋迦牟尼佛

開經偈
無上甚深微妙法。百千萬劫難遭遇。
我今見聞得受持。願解如來真實義。

佛說稱揚諸佛功德經卷上
元魏天竺三藏吉迦夜譯

聞如是。
一時佛在羅閱祇靈鷲山中。與大比丘眾千二百五十人俱。爾時耆年舍利弗便從座起。偏袒右肩。更整法服。在佛右面。右膝著地。長跪叉手。前白佛言。唯。天中天。今日現在諸佛。世尊進止康常。今說法者。其數幾何。

時舍利弗發是問已。爾時世尊告舍利弗。所問甚快。多所饒益普利一切。諦聽。諦聽。善著心中。吾當為汝具分別說。

於是舍利弗聞佛許可。歡喜踴躍。叉手白言。諾。當善聽。願樂欲聞。

佛告舍利弗。東方去此千萬億諸佛刹土。有世界名曰天神。其國有佛。名曰寶海如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。若族姓子。族姓女其有得聞寶海如來名號者。執持諷誦歡喜信樂。其人當得七覺意寶。皆當得立不退轉地。疾成無上正真之道。卻六十劫生死之罪。

複次。舍利弗。東方有世界名曰寶集。其國有佛。號曰寶英如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶英如來名號者執持諷誦。歡喜信樂。五體投地而為作禮。若使三千大千佛刹滿中七寶。持用佈施滿百歲中。所得功德寧多不乎。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人得聞寶英如來名號。持諷誦者作禮之德。十萬億倍過出佈施功德者上。

複次。舍利弗。東方去此寶集世界。度八百佛刹。有世界名曰寶最。其國有佛。號曰寶成如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶成如來名號者執持諷誦。以清淨心歡喜信樂。卻五百劫生死之罪。

複次。舍利弗。東方去此寶最世界。度千佛刹。有世界名曰光明。其國有佛。號寶光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐度人無量。其有得聞寶光明如來名號。執持諷誦。歡喜信樂。於三塗中悉得解脫。

複次。舍利弗。東方去此光明世界。度千五百佛刹。有世界名曰幢幡。其國有佛。號曰寶幢幡如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶幢幡如來名號者。持諷誦念。歡喜信樂。其人則為成法珍寶。

複次舍利弗。東方去此幢幡世界。度二千佛刹。有世界名曰一切眾德光明。其國有佛。號寶光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶光明如來名者。持諷誦讀。歡喜信樂。五體投地而為作禮。卻二十萬劫生死之罪。

複次。舍利弗。東方去此眾德世界。度千佛刹。有世界名曰妙樂。其國有佛。號曰阿閦如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐度人無量。其有得聞阿閦如來名號者。捉持諷誦。歎說其德。複勸他人令學諷誦。

爾時波旬將四種兵來詣佛所。而作是語。寧使捉持餘千佛名。亦勸他人令使學之。不使捉持阿閦佛名。其有捉持阿閦如來名號者。我終不能毀壞其人無上道心。我亦當能毀壞斯等無上道心。

佛告魔言。汝能毀壞誰之道心。魔言。其求大乘。捉持阿閦如來名者。我心則生愁憂。熱惱。如我今日複得熱惱。用聞阿閦如來名故。魔言。亦複有眾生。其數甚多。捉持餘佛名號者。我或當能毀壞其人正覺道心。

佛告魔言。汝莫愁憂懷於惱結。汝終不能毀壞此等無上道心。

魔波旬言。有何因緣。

佛告魔言。汝為隱蔽歸命諸佛功德之行。所以者何。阿閦如來自當觀視擁護其人。

時舍利弗即白佛言。波旬今日於如來前。雲何欲作師子之吼。欲破眾生正覺道心。其有眾生捉持阿閦如來名者。及餘一切諸佛名號。魔審當能毀壞其人正覺心乎。

佛告舍利弗。我今觀覩諸眾生。其有捉持諸佛名者。若有呵罵誹謗之者。斯人則為造大惡行致無量罪。入阿鼻獄具受眾苦。

舍利弗言。有誹謗經者。其數幾許。

佛言。十方諸佛為諸眾生廣說法時。皆先讚歎阿閦如來名號功德。眾生聽聞其功德者。終無厭足。若有眾生得見如來。聞其功德。未曾有能謗此經者。諸佛。如來不於五濁弊惡之時興出於世。如我今者於此忍界下劣叢殘諸眾生中而作佛也。阿閦佛國嚴淨最好。終不爾也。當知。舍利弗。斯尊法輪隨次分佈丘聚國邑。若族姓子。若族姓女一心信行。當廣宣傳此諸經法。當知。舍利弗。聞此經者。誹謗輕毀所受之報。汝今諦聽。

舍利弗言。諾。當善聽。

佛言。犍陀梨國謗此經者滿百千人。造斯惡行。當墮阿鼻大泥犁中。次複北方國名罽賓。其國經法興盛久住。而此國中五百千人謗此經法。此眾生輩死墮阿鼻大泥犁中。舍利弗。於眾聚中當有共謗此經者。有八萬人墮阿鼻大泥犁中。東方少有信斯經者多造阿鼻泥犁行。有百千人死入阿鼻大泥犁中。南方二百千人當謗此經。死入阿鼻大泥犁中。西方有百萬人當謗斯經。死墮阿鼻大泥犁中。當知。舍利弗。緣覺智慧不能度量如來之智。況諸聲聞及諸眾生未成道果。為生死水所漂流者。欲度如來智慧功德。未之有也。夫黠慧者當自思惟。諸佛功德不可限量。諸佛智慧不可思議。諸佛已成一切種智三達無閡。而我癡冥無有是智。諸佛已成一切智者。自當知之我所不了。若我不了。不當謗毀四句一偈。何況謗毀斯大尊經。造斯大罪。眾惡行聚無央數劫。當在阿鼻大泥犁中於彼止宿。是故。舍利弗。若族姓子。族姓女當作是意。我今乃聞此大尊經而不誹謗。乃卻阿鼻一劫之罪。我等今當自慶歡喜。興大踴躍。緣此之故。無央數劫常當與此大法共俱。

複次。舍利弗。東方去此妙樂世界。度萬佛刹。有世界名曰無量。其國有佛。號大光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐度人無量。其有得聞大光明如來名者。執持諷誦。歡喜信樂。其人所生未曾不值諸佛。世尊。住不退轉。必得成就最上正覺。

複次。舍利弗。東方去此無量世界。度六萬佛刹。有世界名曰眾華。其國有佛。號無量音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無量音如來名者。淨心信樂。三反稱言。我今一心禮無量音如來。其人當得無量音聲。及得如來淨光之音。

複次舍利弗。東方去此眾華世界。度萬四千佛刹。有世界名無塵垢。其國有佛。號無量音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無量音如來名者。歡喜信樂。持諷誦念。卻十二劫生死之罪。

複次舍利弗。東方去此無塵垢世界。度二萬佛刹。有世界名莫能勝。其國有佛。號大名稱如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大名稱如來名者。淨心信樂。諷誦不忘。長跪叉手而作是言。我今禮大名稱如來。作七寶阜如須彌山。持用佈施滿百歲中。所得功德寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人持大名稱如來名號作禮之者。得其功德巨億萬倍。過出佈施功德者上。不得為比。

複次。舍利弗。東方去此莫能勝世界。度三千佛刹。有世界名光明。其國有佛。號寶光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞寶光明如來名者。盡心信樂。持諷誦者。當卻十劫生死之罪。住不退轉。必成無上正真之道。其有誹謗。其不信者。當在阿鼻大泥犁中壽命一劫。

複次。舍利弗。東方去此光明世界。度萬五千佛刹。有世界名曰多光。其國有佛。號得大安隱如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大安隱如來名者。歡喜信樂。諷誦不忘。當作是念。持此功德。普使一切無量眾生而得安隱。其人則受無量功德。便能安隱一切眾生。

複次。舍利弗。東方去此多光世界。度七千佛刹。有世界名摩尼光。其國有佛。號大光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大光明如來名號者。歡喜信樂。持諷誦讀。其人當得如來十力。

複次。舍利弗。東方去此珠光世界。度八千佛刹。有世界名曰正直。其國有佛。號正音聲如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞正音聲如來名號者。淨心信樂。持諷誦讀。其人當得如來四諦平等之法。

複次。舍利弗。東方去此正直世界。度二萬佛刹。有世界名光明尊。其國有佛。號無限淨如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無限淨如來名者。歡喜信樂。持諷誦者。大千世界滿中七寶持用佈施。所得功德寧多不乎。

舍利弗言。甚多。甚多。天中天。

佛言。不如捉持無限淨如來名者。所得功德百千萬倍。過出佈施功德者上。無以為比。少功德人不得聞此如來名號。於千佛所造立德本。爾乃得聞此尊佛名。卻生死罪四十八劫。

複次。舍利弗。東方去此光明尊世界。度九千佛刹。有世界名曰音響。其國有佛。號月音如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞月音如來名號者。盡心信樂。持諷誦念。其人所得清淨功德。成具畢滿如月盛明。立不退轉。當成無上正真之道。

複次。舍利弗。東方去此音響世界。度萬二千佛刹。有世界名曰安隱。其國有佛。號無限名稱如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無限名稱如來名者。一心信樂而諷誦者。長跪叉手自作是言。今我禮無限名稱如來。至真。等正覺。計於其人所得功德。若積七寶如須彌山。持用佈施滿百歲中。所得功德寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如得聞無限名稱如來名者。持其名號歡喜作禮。其福甚多。比於佈施過出百倍。無以為比。

複次舍利弗。東方去此安隱世界。度千五百佛刹。有世界名曰為日。其國有佛。號日月光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞日月光如來名號者。歡喜敬心。兩膝著地。長跪叉手。自作是言。我今禮日月光如來。至真。等正覺。其人疾得成就無上正真之道。

複次。舍利弗。東方去此日世界。度三十佛刹。有世界。名曰清淨。其國有佛。號無垢光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無垢光如來名者。若天。若人。龍及閱叉。若諸非人。歡喜信樂。一心敬禮。斯等皆得立不退轉。成無上最正覺道。終不畏墮三塗之中。

複次。舍利弗。東方去此清淨世界。度半大千佛刹。有世界名曰琉璃光。其國有佛。號曰淨光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞淨光如來名號者。誦其名號。歡喜作禮。若天。若龍。閱叉及與非人。此等壽終當生天上及與人中。未曾失於天人之路。常當得值法之盈利。貪心。瞋恚。愚癡之意疾得清淨。若有謗毀而不信者。六萬歲中在於盧獵泥犁受罪。

複次。舍利弗。東方去此琉璃光世界。度三百佛刹。有世界名得大豐。其國有佛。號日光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞斯佛名者。歡喜信樂。念其如來。斯等之類。譬若日輪。皆悉具滿白淨之法。降伏眾魔及諸外道。卻四十劫生死之罪。

複次。舍利弗。東方去此大豐世界。度萬佛刹。有世界名曰得立正覺侍從。其國有佛。號無量寶如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無量寶如來名號。歡心信樂。持諷誦者。斯輩皆當得七覺寶。能立眾生於最寶中。眾德之聚日日增長。

複次。舍利弗。東方去此立正覺世界。度五千佛刹。有世界名蓮花光。其國有佛。號蓮花最尊如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞蓮花最尊如來名號。歡喜信樂。持諷誦者。猶若妙花在尊法室。功德智慧日日增長。譬如蓮花從水湧出。卻五十劫生死之罪。

複次。舍利弗。東方去此蓮花光世界。度十萬億佛刹。有世界名普度眾難。其國有佛。號曰身尊如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞身尊如來名號者。盡心信樂。持諷誦者。其人。疾度生死之海。能除眾生諸欲饑渴。當作快士。為於世間而作福田。能受三界一切供養。其有目見此如來者。歡喜信樂。當為世間作大法師。得金剛力。立不退轉。當成無上正真之道。其有女人聞此身尊如來名者。盡心淨意。歡喜信樂。無諛諂者。厭汙女身。從是以後更止不受女人之身。卻六十劫生死之罪。

如是舍利弗。其有得聞身尊如來名號者。斯等為獲無極之德。是故當求正覺之道。普救一切令離眾苦。

複次舍利弗。東方去此度眾難世界。度二十佛刹。有世界名曰堅固。其國有佛。號曰金光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞金光如來名號者。歡喜信樂。持諷誦念。斯等皆當為佛光明之所護持。成佛之時於諸如來光明廣遠而得自在。悉得如來一切眾德。是故至心普當信樂諸佛尊號。悉得無礙辯才之慧。終不諮受下劣之法。諸願之行當疾成滿。其有聞此諸如來名。當自勸發起於尊意。發金剛志。求無上道。此等皆當卻十二劫生死之罪。

複次。舍利弗。東方去此堅固世界。度十佛刹。有世界名曰無際。其國有佛。號梵自在王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞梵自在王如來名者。歡喜信樂。持諷誦念。叉手作禮。其人必當得見其佛。作轉輪王。立不退轉。當成無上正真之道。

複次。舍利弗。東方去此無際世界。度二千佛刹。有世界名曰為月。其國有佛。號金光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞金光明如來名者。歡喜信樂。持諷誦念。此等後生。常為眾生廣說經法。雖為分別一切如夢。如水中月。幻化之法。用寤眾生。從是以往終不復墮惡道之中。當與大德眾聚共會。而常歡喜。能使眾生而得快樂。後作佛時。以大乘法興顯於世。無有二道。

複次舍利弗。東方去此月世界。度千佛刹。有世界名曰火光。其國有佛。號曰金海如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞金海如來名號者。盡心信樂。持諷誦者。得不退轉。必成正覺。所以者何。其佛。如來本行菩薩道時。作是誓願。若使有人生我國者。及在他方諸佛國土。聞我名號。斯等當住不退轉地。成最正覺。我當盡為滿具如來無上之願。

複次舍利弗。東方去此火光世界。度十八佛刹。有世界名曰正覺。其國有佛。號龍自在王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞龍自在王如來名者。盡心信樂。持諷誦者。若使郡縣。村落之中雨。雹。霜時。以右膝著地。叉手作禮。而作是言。龍自在王如來本行菩薩道時。無數諸龍於厄難中悉度脫之。由此功德自致成佛。作是誓言。若我刹中及諸佛土。若我在世般泥洹後。若有諸龍雷。電。雹。霜恐怖眾生。以龍自在王如來威神功德智力。至誠誓願。口作是言頭面作禮。疾得度脫。當知。舍利弗。如是厄難疾得解脫。唯除宿罪不能得免。一切諸龍若在厄難聞此佛名。於眾厄中疾得解脫。其有執持斯佛名者。複勸他人令使誦持增益功德。必當得往生此佛國。求最正覺。立不退轉。疾成不久。

複次舍利弗。東方去此正覺世界。度十億佛刹。有世界名曰喻月。其國有佛。號一切花香自在王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞一切花香自在王如來名者。淨心信樂。持諷誦者。斯其人等所生之處。當得恒沙戒香具足。一切妙香香氣遍熏。諸佛刹土眾戒具滿。常能奉持未曾缺犯。

舍利弗言。本何因緣乃能如是。

佛言。其佛本行菩薩道時作是誓願。我若在世般泥洹後。若有眾生持我名字一心信樂。皆悉當得如是戒香。是故。舍利弗。常當興立大敬信心於諸如來。如是諸佛擁護其人。使得功德不可計量。若有持此諸佛名者。從其所願得之。皆悉當得諸佛智慧而令備滿。得不退轉。長跪叉手。自作是言。我今禮此一切花香自在王如來。常念不忘。卻十四劫生死之罪。

複次。舍利弗。東方去此喻月世界。度二千一億佛刹。有世界名曰星王。其國有佛。號曰樹王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞樹王如來名號者歡喜信樂。持諷誦者。斯輩皆當得諸法樂。壞諸魔兵。裂破羅網。若聞此經。輕慢誹謗。用相調戲。滿六萬歲於僧迦泥犁受其罪報。若有言。我不信此經。於七萬歲常在餓鬼。不聞飲食。水。穀之名。

複次舍利弗。東方去此星王世界。度五十五佛刹有世界。其國有佛。號曰勇猛執持牢杖棄舍鬪戰如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞勇猛執持牢杖棄舍鬪戰如來名者。歡喜信樂。持諷誦者。乃至夢中。此等眾生。譬如金剛伏眾魔兵。以諸智慧消伏諸欲。其有得聞此佛名號一心信者。審諦自知。我等前世以為曾見此佛。世尊遊於菩薩徑路之時。而不疑也。我等當發弘誓之願。莫從大乘而得退轉。但當自慶。歡喜踴踴。進大法路。得聞如來種姓名號。諸佛普利益於一切。不舍一人而取滅度。諸佛大慈。普湣眾生。雨於法雨。其有得持此如來名者。歡喜信樂。所得功德。我當為汝取少譬喻。如恒邊沙諸佛國土。滿中七寶持用佈施。所得功德寧多不乎。

舍利弗言。甚多。甚多。不可思議。

佛言。分大海水一渧為一分。佈施功德猶若一渧。持佛名者所得功德。如大海水。不可為喻。少功德人不能堪任聽斯經典。若使有人久殖德本。得聞斯法。信而不疑。若使地獄。畜生。餓鬼及長壽天聞此經者尚得大福。況複有人已種德本。聞斯經法所得功德寧可喻乎。

複次舍利弗。東方去此佛土。度二十佛刹。有世界名曰豐饒。其國有佛號內豐珠光如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞內豐珠光如來名者。一心信樂。持諷誦念。斯等皆當獲大功德。終不畏墮三塗之難。所發弘誓如意。得滿大乘之願。若今現在般泥洹後。其有得聞內豐珠光如來名者。信樂誦念。斯等皆當得大乘法樂而以自娛。及受天上。人中快樂。常當得生清淨佛土。於諸佛國具滿眾願。從意所欲。於三乘法而得滅度。於其中間從此佛所。獲功德聚甚大弘廣。恒沙劫中所作眾罪。悉當棄舍不受。唯除逆罪。起瞋恚意向諸快士。此等之類於久長世。地獄之中受斯罪畢。因得聞此佛名功德所致。其後如願於三乘中而取滅度。當知。舍利弗。眾惡之行慎莫造作。如我於此經中上章所說。不可起恚向於焦柱。何況懷惡向於眾生。已立信心向成道者。況起瞋恚。懷於誹謗向諸如來無量慧等。如此之人於無數劫在地獄中。具受無量苦惱之罪。爾乃得出。我為斯等求於大乘信解者故。而說斯法。其有毀壞大乘法者。實當具受無量大苦。信樂之者。自果當立不退轉地。必成正覺。

複次。舍利弗。東方去此豐饒世界。度八十佛刹。有世界名最香熏。其國有佛。號無量香光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞無量香光明如來名者。持諷誦念一心信樂。最後念之。斯等皆當得不退轉地。成最正覺。成正覺已。諸毛孔中出眾妙香。遍至十方猶若雲起。非是下劣少智之士。學淺法者。而解斯經。吾亦道眼觀覩斯等諸眾生類。其有信樂斯經法者。過去世間無數劫中。於諸佛所集諸慧法造眾德本。今乃得聞此尊妙法。最後末世聞斯典教。信而奉持。未曾生意而懷誹謗。初未曾有不解法時。卻四十劫生死之罪。其人功德如月欲滿。為於世間而作快士。應當得受一切恭敬。而為眾生作良福田。

複次。舍利弗。東方去此香熏世界。度五十佛刹。有世界名龍珠觀。其國有佛。號師子響如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞師子響如來名者。持諷誦讀。一心信樂。念於戒行。斯等皆當立不退轉。成最正覺。作眾德輪。入白淨法。於中旋轉過出於世。卻二十劫生死之罪。若族姓子。族姓女。若人。非人。其諸厄難疾得解脫。現在於世有得聞斯佛名者。於諸世間猶若尊塔。

複次舍利弗。東方去此龍珠觀世界。度三十佛刹。有世界名曰修行。其國有佛。號大強精進勇力如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞大強精進勇力如來名者。盡心信樂。持諷誦念。右膝著地。叉手作禮。自作是言。我今禮大強精進勇力如來。至真。等正覺。斯其人等。遊生死中多所饒益。得大戰力。退卻眾魔。伏諸外道。卻二十五劫生死之罪。

複次舍利弗。東方去此修行世界。度四十佛刹。有世界名曰堅住。其國有佛。號過出堅住如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞過出堅住如來名者。淨心信樂。持諷誦念。此等皆當堅住大乘。於諸尊法得堅固財。加得大福。晝夜日日增益功德。

複次舍利弗。東方去此堅住世界。度三十六佛刹。有世界名曰光明。其國有佛。號鼓音王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞鼓音王如來名者。盡心信樂。持諷誦念。長跪叉手自作是言。我今禮鼓音王如來。至真。等正覺。所得功德。三千大千一切世界滿中珍寶持用佈施。得其功德寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人持此佛名功德甚多。過出施上百千萬倍。

複次舍利弗。東方去此光明世界。度百五十佛刹。有世界名眾德室。其國有佛。號曰月英如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞月英如來名者。盡心信樂。若天。若人。龍及非人。聞此佛名。持諷誦念。斯等皆當得入清淨。猶若蓮花不著塵水。於眾惡中悉無所犯。若有女人。得聞月英如來名者。淨心信樂無有諛諂。從是以後更止不受女人之身。若有不信輕慢謗毀。當二十劫在於阿鼻大泥犁中具受眾苦。若使有人盡心信樂。懷大恭敬。卻二十一劫生死之罪。

複次。舍利弗。東方去此眾德世界。度十萬億佛刹。有世界名住栴檀地。其國有佛。號超出眾花如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。佛告舍利弗。其佛本行菩薩道時。自作是言。我成正覺興出世時。其刹土中無有八難。用是誓願自淨佛國。若有得聞超出眾花如來名者。盡心信樂。持諷誦念。斯等大士於諸世間。多所利益。如大藥王。

複次舍利弗。東方去此栴檀世界。度二十億佛刹。有世界名曰善住。其國有佛。號世燈明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞世燈明如來名者。盡心信樂持諷誦念。斯等皆當脫三塗厄。唯除逆罪。起瞋恚向諸快士。其有持此如來名者。為得此尊妙法之寶。卻二十劫生死之罪。

複次。舍利弗。東方去此善住世界。度八十億佛刹。有世界名曰光明。其國有佛。號休多易寧如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。所以世界名光明者。其國佛土地平如掌。以眾蓮花佈滿世界。其土如來光明晃晃。猶若大火晝夜常照。其佛國土光明巍巍最尊第一。常於大眾轉尊法輪。若使有人三千世界以金布地。複以妙衣莊飾其地。悉令彌滿三千世界持用佈施。得其功德寧為多不。

舍利弗言。甚多。甚多。天中天。

佛言。不如有人聞休多易寧如來名者。盡心信樂。持諷誦念。其人得福過出佈施功德者上數百千倍。斯等眾生自恣發願。如意得之。卻六十劫生死之罪。後成無上正真道時。其佛國土嚴淨快樂。尊貴無比。

複次。舍利弗。東方去此光明世界。複有刹土名圍繞月。其國有佛。號曰寶輪如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。今現在說法。

複次。舍利弗。東方去此圍繞世界。有刹土。名曰度覺。其國有佛。號常滅度如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。而今現在轉不退轉無上法輪。

複次。舍利弗。東方去此度覺世界。有刹土。名須彌脇。其國有佛。號曰淨覺如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。而今現在廣說經法。

複次。舍利弗。東方去此過須彌脇世界。有刹土。名曰名稱。其國有佛。號無量寶花光明如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。而今現在廣說妙法。

複次。舍利弗。東方過此名稱世界有刹土。名曰妙軟。其國有佛號須彌步如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。而今現在於大眾中廣說經法。

複次。舍利弗。東方過此妙軟世界。有刹土名曰豐養。其國有佛。號寶蓮花如來至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。現在大眾廣說經法。

複次舍利弗。東方過此豐養世界。有刹土名蓮花踴出。其國有佛。號一切眾寶普集如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。現在說法。

複次。舍利弗。東方去此蓮花踴出世界。有刹土名曰金光。其國有佛。號樹王豐長如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。現在說法。

複次。舍利弗。東方過此金光世界。有刹土名曰清淨。其國有佛。號轉不退轉法輪眾寶普集豐盈如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。與諸菩薩無央數眾前後圍繞。轉不退轉無上法輪。

複次。舍利弗。東方過此清淨世界。有世界名曰淨住。其國有佛。號圍繞特尊得淨如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。斯諸如來。至真。等正覺現在東方。其有宣揚諸如來名。廣分別說。令人受持。複有餘者不可計數。今悉現在說無上法。其有得聞斯諸佛名。盡心信樂。以膝著地長跪叉手。普為東方諸佛作禮。持諸佛名。三作是言。我今普禮東方一切諸佛。世尊。其人得福不可限量。
