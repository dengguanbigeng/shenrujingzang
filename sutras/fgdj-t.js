回向偈
抄經功德殊勝行。無邊勝福皆回向。
普願沉溺諸眾生。速往無量光佛刹。
十方三世一切佛。一切菩薩摩訶薩。
摩訶般若波羅蜜。

回向偈
願以此功德。莊嚴佛淨土。
上報四重恩。下濟三途苦。
若有見聞者。悉發菩提心。
盡此一報身。同生極樂國。

