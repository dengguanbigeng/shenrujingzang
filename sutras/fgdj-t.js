複次。迦葉。上方有刹名曰星宿。其國有佛。號寶德步如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。今現在說法。

複次。迦葉。上方有刹名無量德豐。其國有佛。號最清淨德寶住如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。今現在說法。

複次迦葉。上方有刹。名曰聲所不至。其國有佛。號度寶光明塔如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。今現在說法。

複次。迦葉。上方有刹名無際眼。其國有佛。號無量慚愧金最豐如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。今現在說法。

於是世尊而歎頌曰。

德如月滿其如來。諸天最上為尊雄。
此諸大尊德中王。能為眾生除諸殃。
持諸佛名功德成。能淨諸刹為肅清。
其難得值此尊經。少有眾生聞其名。
若有信行而供養。得大智慧勇力強。
解了諸法無有量。當成一切正覺王。
正覺之法甚深微。不當於中起狐疑。
當善信奉諸導師。歡喜敬禮慎莫疑。

複次。迦葉。上方有刹名寶蓮花莊嚴。其國有佛。號蓮花尊豐如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞蓮花尊豐如來名者。三惡之道為已閉塞。為已得成如來之花。於諸正覺一切法中。便為得成無上道花。卻生死罪三十六劫。

於是世尊而歎頌曰。

上方有刹寶莊嚴。眾花茂盛普大千。
光色晃昱甚可觀。譬如天上難檀桓。
蓮花尊佛在其刹。說法無比慧通達。
光普照耀大千界。眾相端嚴聖中最。
若有女人聞其名。斷絕惡道遭諸聖。
卻三十劫生死罪。必成正覺不退轉。
不見身哃道清淨。世世智慧功德成。
緣念諸佛得善友。怨家消滅除罪苦。
當普禮此是諸佛。今悉現在於異刹。
其人快當受供養。用禮諸佛大法王。
此等不當疑我言。必當成佛德無邊。
常當共諸妙法會。後成正覺慧獨達。

複次迦葉。上方有刹名曰寶鐙。其國有佛。號淨寶興豐如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞淨寶興豐如來名者。歡喜信樂。持諷誦念。其人得七覺意寶。卻三十劫生死之罪。

於是世尊而歎頌曰。

上方有界號寶明。淨寶最尊在其刹。
其有得聞名號者。斯等當得七覺禪。
三十大劫生死苦。超越過去無因緣。
得無比力住不動。常當遭值諸天尊。

複次迦葉。上方有刹名曰電光。其國有佛。號電鐙幡王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞電鐙幡王如來名者。歡喜信樂。持諷誦念。斯其人等悉當遠離八難之處。終不復生下劣之家。

於是世尊而歎頌曰。

上方有界名電光。大尊號曰電鐙王。
其有聞此快士名。八難永斷不復生。
智慧解了生死根。種種功德隨次成。
興隆道化度眾生。智慧獨達無比聖。

複次。迦葉。上方有刹名虛空致。其國有佛。號法空鐙如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞法空鐙如來名者。歡喜信樂。持諷誦念。卻六十劫生死之罪。得不退轉於最正覺。常得與諸佛共會。現世得見其佛。世尊。亦於夢中見此如來。當知。迦葉。其人今世五體投地。一心恭敬向於如來。其人則種無量功德。諸善根栽悉得具滿。常當得值諸善知識。常與諸人共相敬愛。如是。迦葉。是為現世獲諸善報。其佛。如來一切功德普集如是。

於是世尊而歎頌曰。

有虛空致大世界。其佛號曰法空鐙。
名稱普達其世尊。光明極大踰虛空。
其有得聞此尊名。超六十劫生死罪。
必當遭值見諸佛。於如來前講妙法。
精進現世見諸佛。當五體禮其如來。
夢中得見其世尊。其佛導師光圍繞。
念其如來致斯德。常當得見諸大哀。
生常得值諸法王。其人現世見諸佛。
其佛導師德無量。智慧普達為法王。
其有勤求眾德者。盡心敬意禮其佛。

複次。迦葉。上方有刹名審諦分。其國有佛。號一切眾德成如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐度人無量。何故此界名審諦分。當知。迦葉。其彼世界皆為八分。眾花分。栴檀樹分。金多羅樹寶致分。其佛刹土出眾名香。遍其世界。於彼刹土在虛空中。成為香蓋普覆佛刹。其佛。如來趣於法座莊嚴大會。其有得聞一切眾德成如來名者。六情端政常得清淨。解了諸佛妙法之分。卻八十劫生死之罪。

於是世尊而歎頌曰。

審諦世界有八種。多羅寶樹香莊嚴。
出妙名香遍其刹。普覆虛空香雲蓋。
大智正覺在其刹。名聲普達號眾德。
色像端嚴妙甚姝。法王獨步無畏懼。
其有得聞此尊名。端正奇妙功德成。
節解圓滿而方正。視之無厭莫不敬。
功德極尊無與等。歡喜踴躍遊諸刹。
精進勇猛甚超越。卻八十劫生死罪。
於正覺道終不轉。廣能演說佛尊法。
逮得一切諸快樂。後生之處常尊貴。
逮得清淨無差特。思念如來眾功德。
思惟智慧諸法義。增進功德成諸智。

複次迦葉。上方有刹名日月英。其國有佛。號賢幡幢王如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其有得聞賢幡幢王如來名者。歡喜信樂。持諷誦念。其人當得立不退轉。成最正覺。卻五十劫生死之罪。

於是世尊而歎頌曰。

上方界名日月英。其佛號曰賢幢王。
法王大仙在其刹。相好盛明如滿月。
其有得聞此尊名。遊生死路諸根明。
於諸法中常增長。審諦得住如來種。
至心念佛而敬禮。卻五十劫生死罪。

複次。迦葉。上方有刹名曰寶種。其國有佛。號一切寶致色持如來。至真。等正覺。明行成為。善逝。世間解。無上士。道法禦。天人師。號曰眾祐。度人無量。其刹何故名曰寶種。當知。迦葉。其佛世界一切眾生悉求無上正真之道。其國菩薩神足勇猛。無數菩薩俱共同時如彈指頃。以神足力飛到十方。供養無量恒沙諸佛悉皆周遍。悉能成就一切眾生。說是諸佛功德處時。若有聞者。則為到此諸佛國已。誰能發起大精進行。有菩薩摩訶薩其有捉持此名號者。其名曰師子戲菩薩。師子奮迅菩薩。師子幡菩薩。師子作菩薩。堅勇精進菩薩。擊金剛慧菩薩。其有得聞一切寶致色持如來名號及諸菩薩大士名者。皆悉當得如來十力。十八不共特異之法。常能轉於不退法輪。卻六百劫生死之罪。

於是世尊而歎頌曰。

我今已說諸法王。今悉現在康常者。
無師自覺大導師。得泥洹樂為最尊。
如來名號性清淨。諸法威儀行清淨。
其有最後聞諸名。興大歡喜懷恭敬。
不當狐疑於如來。至誠奉信莫言無。
汝當知是舍利弗。斯等先世已供我。
若有供養於諸佛。其人最後恐怖世。
得聞此等諸尊經。一心信樂無疑生。
諸佛大智所遊路。無此最上慧通達。
於是法中多所成。雲何於中疑此經。
若值妙珠無疑寶。愚者不識嫌不好。
貧者猶豫意未了。既無重價致此寶。
是法出生等正覺。此皆大士之所聞。
智慧淺者無慧眼。斯等何從而能信。
其有富者積眾寶。聞如意珠大歡喜。
歎譽甚多益眾寶。我當買取自莊嚴。
其有福慧合聚者。聞諸佛名大歡喜。
鄭重讚歎欲得聞。得正覺珠自莊嚴。
行惡之法求惡者。其有諛諂及反戾。
福德智慧薄少者。終不堪任聞此法。
短促倒覆及愚癡。慳悋甚多成穢意。
貪婬瞋恚惑亂者。此輩不任聞此法。
學尠懈慢憍自輕。弊惡親友意未成。
真卷自舉外如清。斯眾不任聞此經。
無數天人時唱言。巍巍正覺無上尊。
快哉妙法甚難聞。當聽無比道之珍。
聞諸如來名號中。所得盈利叵數陳。
諸天在上虛空中。而散花香鼓樂音。
諸天妙香而遍熏。大千世界結香雲。
光明普照諸十方。一切刹土六反震。

爾時世尊說諸如來名號之時。諸在會者悉於座上。遙見此等諸佛。世尊各在其國大眾之中而說經法。悉從坐起。禮諸世尊。莫不歡喜。踴躍無量。於時會中無數千人已。有得道。未得道者。悉發無上正真道意。十方世界諸菩薩等各如恒沙。皆來詣此禮釋迦文。於其會中一億比丘得阿羅漢。比丘比。丘尼複有十萬人得法眼淨。複有十萬人悉得法忍。五百優婆塞。四百優婆夷同時從坐起整衣服供養如來。盡發無上正真道意。

於是舍利弗。長跪叉手。前白佛言。此名何經。雲何奉持。佛言。此經名曰稱揚諸佛功德法品。亦複名曰集諸佛花。當奉行之。

爾時世尊說此經竟。舍利弗及諸比丘。諸天。人民。龍。阿須倫一切大會。皆大歡喜。前為佛作禮而去。
