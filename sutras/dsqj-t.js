大隨求陀羅尼經序品第一
如是我聞。一時婆伽梵。住大金剛須彌盧峯樓閣。安住大金剛三摩地。以大金剛莊嚴劫樹於大金剛池寶蓮花光照。金剛沙而布於地。於大金剛加持。金剛道場天帝釋宮殿。以俱胝那庾多百千莊嚴大金剛師子之座。說法神通處。一切如來神力之所加持。入一切法平等出生薩婆若智。與八十四俱胝那庾多菩薩眾俱。皆是一生補處。於阿耨多羅三藐三菩提得不退轉。皆得大勢。皆悉示現大金剛解脫三摩地佛刹神通。於刹那間隨入一切有情心行。成就種種美妙廣大甚深巧說諸法。辯才無礙得大神通。悉能供養無量佛世界如來。大供養雲海解脫三摩地自在神通。不共覺分道支一切地波羅蜜。善巧四攝慈悲喜舍力遠離清淨心相續中。其名曰。

金剛藏菩薩摩訶薩。金剛眼菩薩摩訶薩。金剛身菩薩摩訶薩。金剛慧菩薩摩訶薩。金剛手菩薩摩訶薩。金剛相擊菩薩摩訶薩金剛那羅延菩薩摩訶薩。金剛遊戲菩薩摩訶薩。金剛積菩薩摩訶薩。金剛髻菩薩摩訶薩。金剛妙菩薩摩訶薩。金剛幢菩薩摩訶薩。

如是上首菩薩摩訶薩眾俱。

複與大聲聞眾皆大阿羅漢。斷除有結盡一切漏。得善正知。心善解脫。悉能現不思議神通力。神境通遊戲。皆得大勢。於見無著。離一切垢。焚燒習氣種。其名曰具壽舍利子。具壽滿慈子。具壽劫賓那。具壽須菩提。具壽迦葉波。具壽大迦葉波。具壽優樓頻螺迦葉波。與如是等上首大聲聞眾俱。複有大自在天子為上首。與無量無邊不可說阿僧祇淨居天子眾俱。

複有娑訶世界主大梵天王為上首。與梵眾天子俱。

複有蘇夜摩天子化樂天子他化自在天子。及天帝釋各與諸天子以為眷屬俱。

複有毘摩質多羅阿蘇羅王。末離阿蘇羅王。令歡喜阿蘇羅王。照曜阿蘇羅王。羅睺阿蘇羅王。如是上首阿蘇羅王。與無量無邊阿蘇羅王以為眷屬俱。

複有娑伽羅龍王。德叉迦龍王。嚩蘇枳龍王。商佉波羅龍王。羯句吒迦龍王。蓮華龍王。大蓮華龍王。如是等上首龍王。與無量無邊阿僧祇龍王眾俱。

複有樹緊那羅王。與無量緊那羅王眷屬俱。

複有一切義成就持明仙王。與無量持明仙王眷屬俱。

複有五髻乾闥婆王。與無量乾闥婆王眷屬俱。

複有金銀蘖路茶王。與無量蘖路茶王眷屬俱。

複有多聞藥叉王。寶賢藥叉王。滿賢藥叉王。半支迦藥叉王。與無量無邊藥叉王眷屬俱。

複有訶利帝母。與五百子以為眷屬俱。複有七護世母天。七大羅刹母。遊虛空七仙天。九執曜天。方隅地天。辯才天女名與眷屬俱。

複有作障者毘那夜迦。並畢隷多。部多。一切皆是大威德者。各與眷屬俱。

複有一切山王。一切海王及護世王水天。並持國天王。增長天王。惡目天王。持棒羅刹主七風天伊舍那天並及其後。與千俱胝那庾多眷屬俱。

複有那羅延天。與眷屬俱。

複有捺多迦那麼迦。嚕賀迦。大伽那缽底。彌瞿羅迦如是等毘那夜迦王。與無量無邊毘那夜迦以為眷屬俱。

複有六十遊行諸城堡王與眷屬俱。

複有四姊妹女天並兄。以為眷屬俱。

複有金剛商羯羅女。與六十四金剛女以為眷屬俱。

複有金剛軍童子。蘇摩呼童子。頂行童子。與無量金剛族以為眷屬俱。

複有淨信佛法僧。天龍藥叉乾闥婆阿蘇羅蘖路茶。緊那羅摩戶羅伽部多。畢舍遮。阿缽娑麼囉。嗢摩那娑𠆙娑。呬裏迦。烏薩多羅迦並日月天子。晨朝天。日午天。黃昏天。中夜天。及一切時天。與無量無邊阿僧祇眷屬俱。於是世尊善轉法輪佛事已終。福德智慧究竟圓滿。善攝受一切智大菩提。獲得熾盛地波羅蜜。以三十二大丈夫相莊嚴法身。八十四隨好莊嚴一切支分。一切有情無所觀頂相。超勝一切魔羅。通達一切智智。具足五眼。一切相成就。一切智智成就。一切佛法成就。摧一切魔異論。高顯名稱大雄猛師子吼。壞無明黑闇。以無量無邊阿僧祇百千俱胝那庾多劫之所積集。施戒忍勤勇靜慮般若方便願力智波羅蜜難行苦行。轉得三十二大人相八十四隨好莊嚴。其身坐大寶金剛蓮華藏師子之座。其座以無量金剛寶珠羅網莊嚴。微風搖擊出妙音聲。以無量金剛界安住神足。以無量金剛寶莊嚴。摩竭口吐於赤珠。複含在口。以無量寶嚴飾蓮花蕊。虎珀大虎珀。帝青大帝青。補沙羅伽。莊嚴光網普遍端嚴。以無量金剛寶莊嚴幰蓋柄。以無量俱胝那庾多百千劫樹。蔭影莊嚴。其座廣博大如須彌。猶如金山。吉祥熾盛光明莊嚴。照過千日。其地圓滿猶如淨月。令諸有情深所樂見如來之法。如大劫樹其花開敷。所說妙法初中後善。其義深遠其語巧妙。清淨潔白純一無雜。

爾時。世尊從頂毫相。放大光明，其光名曰現一切如來光網。由此光明。普照三千大千世界乃至如恒河沙數佛世界。於彼世界所有如來。於大莊嚴樓閣無量寶莊嚴師子座上說法。並一切菩薩及大聲聞苾芻苾芻尼淨信男淨信女。天龍藥叉乾闥婆阿蘇羅蘖路茶緊那羅摩戶羅伽。悉皆照曜顯現分明。爾時世尊普為一切說伽陀曰。

我今說隨求。湣念諸有情。此大陀羅尼。能摧難調者。
諸極惡重罪。若得才聞此。隨求陀羅尼。一切罪消滅。
安樂諸有情。解脫一切病。大悲眾生故。是故世尊說。
為獲解脫故。遠離諸惡趣。若入修羅宮。藥叉羅刹宮。
步多龍鬼神。如是諸宮殿。隨意悉能入。皆用此大明。
而作於加護。鬥戰危險處。不被怨沮壞。並諸鬼魅等。
由稱陀羅尼。諸魅悉壞滅。娑謇嗢未那。畢舍拏吉你。
猛惡吸精氣。常害有情類。彼皆悉殄滅。由隨求滅德。
他敵皆滅壞。所作劇厭禱。咒詛法無效。定業不受報。
不被蠱毒中。水火及刀杖。雷電與霜雹。黑風惡暴雨。
諸難皆得脫。冤敵悉降伏。若人持此明。或帶於頸臂。
所求願悉成。一切所希願。悉皆得如意。天王皆加護。
及諸大龍王。菩薩大勤勇。緣覺及聲聞。一切諸如來。
明妃大威德。悉皆而擁護。受持隨求者。金剛秘密主。
護世四天王。於彼持誦人。晝夜常加護。帝釋忉利眾。
梵王毘紐天。及摩醯首羅。眾生俱摩羅。大黑喜自在。
一切天母眾。及餘諸魔眾。苦行威德仙。及餘密語天。
皆悉來擁護。持此隨求者。大威德菩薩。明妃大悲尊。
勇猛具神力。摩摩毘俱胝。多羅央俱屍。及餘金剛鎖。
白衣及太白。聖摩訶迦離。使者金剛使。妙索金剛索。
執輪大力者。金剛鬘大明。甘露軍吒利。無能勝明妃。
黑耳吉祥天。大福威德尊。蓮花軍吒利。花齒及珠髻。
金髮賓蘖羅。大威德吉祥。及電莊嚴天。一髻大羅刹。
及佛地護尊。迦波利明女。楞伽自在尊。及餘多類眾。
彼等皆擁護。由大明在手。訶利帝及子。半支迦大將。
商棄尼積齒。吉祥及辯才。由持此密言。晝夜常隨逐。
若有諸女人。持此陀羅尼。彼皆悉成就。男女在其胎。
安隱胎增長。產生皆安樂。一切病悉除。諸罪皆消滅。
福力常具足。穀麥及財寶。悉皆得增長。出言令樂聞。
所至獲恭敬。男子及女人。清淨能受持。常懷慈悲心。
拔濟諸有情。皆願獲安樂。令彼離疾病。國王並後宮。
皆生恭敬心。吉祥常熾盛。福聚皆增長。一切真言法。
皆悉得成就。成入一切壇。得成三昧耶。如來誠實說。
