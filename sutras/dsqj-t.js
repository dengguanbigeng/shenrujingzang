複次大梵。其天帝釋共阿蘇羅鬥戰之時。帝釋常以此陀羅尼。置於頂髻珠中帶持。帝釋天眾不被傷損。而常得勝安隱還宮。初發心菩薩乃至究竟地菩薩。帶持能離種種障難魔業故。若有人帶此陀羅尼。一切如來之所加持。一切菩薩之所護念。一切人天國王王子大臣婆羅門長者。常恒恭敬禮拜承事。一切天龍阿蘇羅蘗路茶緊那羅摩睺羅伽人非人等。皆供養彼帶持者。彼等天龍八部皆言。彼人是大丈夫。如來複言彼善男子善女人。能摧一切魔障。離一切疾病。離一切災橫。除一切憂惱。恒為一切天龍之所守護。

佛告大梵。複有四陀羅尼。是無能勝妃大心真言。若有書寫帶佩於身。常應誦持深心思惟觀行。能除惡夢不祥之事。一切安樂皆得成就。

