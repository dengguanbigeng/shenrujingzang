佛告大梵。若有人以如來身明陀羅尼句作加持救濟攝受加護。能作息災作吉祥法。遮止謫罰成大加護。若人壽命欲盡。誦此真言複得延命增壽。久久命存常獲安樂得大念持。若以金剛杵才念誦加持。或有非命患大疾者。皆得解脫。一切疾病皆得除滅。長患病者誦此真言。加持袈裟角拂彼病人便即除差。日日誦持者。得大聰慧威力大勤勇辯才成就。一切罪障定受業報悉皆消滅。一切佛菩薩並天龍藥叉等。於受持陀羅尼者。當令精氣入身增加威力。身心常得喜悅。大梵此大明王大護陀羅尼。若有乃至傍生禽獸耳根所聞。彼等悉皆於無上菩提永不退轉。何況淨信善男子善女人。苾芻苾芻尼鄔波索迦鄔波斯迦。國王王子婆羅門刹利及諸餘類。一聞此大隨求大護陀羅尼。聞已深心淨信恭敬書寫讀誦。生殷重心修習。為他廣演流布。大梵悉皆遠離八種非命。彼人身中不生疾病。不被火毒刀杖蠱毒壓禱咒詛諸惡藥法之所損害。不被身痛頭痛。及諸瘧病一日二日三日四日乃至七日。及癲癇病悉不能為患。正念睡眠正念覺悟。證大涅槃。現世得大富貴自在。所生之處於彼彼處常得宿命。一切人天皆悉愛敬容儀端正。一切地獄餓鬼傍生皆得解脫。猶如日輪以光明照曜一切有情。譬如月輪以甘露灌灑一切有情身。得適悅其人。以法甘露遍入一切有情心相續中。皆令滋澤歡喜。一切諸惡藥叉羅刹。步多。畢㘑多。畢舍遮。癲癇鬼。拏枳寧諸魅。毘那也迦等悉皆以此大隨求大護威力不能侵惱。若來逼近。憶念此大護明王。則一切噁心之類。於持誦之人發生歡喜受教而去。由此大隨求大護明王威力。終無怨敵怖畏。是諸怨敵不能淩突。或若有人於國王大臣婆羅門長者處。所犯愆過罪合當死殺者。持刀劍臨刑之時。若才憶念此大護明王。其刀片片斷壞猶如微塵。其人當彼之時。得悟一切法平等。獲大念力。爾時如來說伽陀曰。

此大護加持。清淨滅諸罪。能作慧吉祥。增長諸功德。
能滿諸吉慶。除滅不吉祥。能見妙好夢。能淨諸惡夢。
