能開諸天趣。安樂悉成就。智慧皆圓滿。諸佛及菩薩。
常安慰其人。身常受快樂。驍勇有大力。如來誠言說。
當獲轉輪位。安慰人天眾。驚怖噁心者。修此陀羅尼。
不久當獲得。不被刀所傷。毒藥反水火。悉皆不能害。
非命及夭壽。諸罪皆遠離。見聞及觸身。於一切時處。
鬼魅及鬥諍。諸怖皆消滅。惡蟲及毒蛇。囚閉悉解脫。
種種疾大病。悉皆盡除滅。由修持此明。於諸摩羅眾。
無礙得通達。能於一切處。而獲大供養。人中得最勝。
加護修真言。

修行菩薩隨求大護大明王陀羅尼品第二
爾時世尊告大梵說伽他曰。

我今為宣說。修行持明者。說加護儀則。湣念諸有情。
由此擁護故。獲得大成就。所居諸方處。用此作加持。
獲得無障礙。決定心無疑。無怖無熱惱。除滅一切魅。
隨順於宿曜。能斷業鉤鎖。惡食惡跳驀。厭書悉消滅。
一切諸怨家。不被淩逼傷。惡視及壓禱。咒藥並蠱毒。
於他敵險處。大怖怨敵處。一切悉消融。由大隨求力。
諸佛皆擁護。一切智菩薩。悉皆作加護。緣覺及聲聞。
及餘多種類。大威德天龍。皆當而擁護。誦此密言者。
由才聞此故。明王最勝尊。一切處無畏。牟尼作是說。
惡夢及惡作。極惡諸逼迫。疾病以纏身。瘦病銷骨肉。
及餘多種病。丁瘡諸毒腫。惡疰及災禍。齧嚼諸有情。
為損有情故。大害極恐怖。悉皆得除滅。由加護大明。
以此明加護。合死得解脫。若以黑索羂。將至閻魔宮。
命複倍增壽。由書帶大護。若有壽盡者。七日後當死。
才書帶此明。無上大加護。或若才聞故。依法加持者。
處處獲安隱。隨意受安樂。六十八俱胝。一百那庾多。
三十三諸天。輔翼於帝釋。來護於此人。隨逐作加護。
四大護世王。金剛手大力。一百明族眾。常加護彼人。
日天及月天。梵王與毘紐。自在夜摩天。寶賢及力天。
滿賢大勇猛。訶利帝及子。半遮羅半支。俱摩羅眾主。
吉祥大明妃。多聞及辯才。商棄尼華齒。一髻大威德。
如是大藥叉。常當而擁護。石女生子息。胎孕鹹增長。
常加護彼人。乃至壽命存。丈夫常得勝。恐怖鬥戰處。
由此滿諸願。由依淨信天。諸罪悉消滅。由書此大明。
諸佛常觀察。大威德菩薩。彼名稱增長。福壽亦複然。
財穀皆豐盛。獲得悉無疑。睡眠及覺悟。悉皆得安樂。
怨家及鬼神。皆不能沮壞。當於鬥戰時。常皆獲得勝。
若修密言時。此護最為勝。安樂修諸明。悉得無障礙。
一切密言教。悉皆得成就。成入一切壇。速成三昧耶。
乃至於來世。諸佛皆委寄。由持此大護。諸吉祥皆滿。
意願悉成就。由才書此明。一切樂豐盛。安樂而舍壽。
必生於善趣。欲生極樂國。持帶此明王。決定無疑惑。
鬥諍於言訟。戰陣大怖中。諸怖皆遠離。如佛誠言說。
常獲宿命智。生生皆無疑。國王皆歡喜。及後宮眷屬。
盡皆常恭敬。常與善人和。皆悉生憐湣。並人及與天。
令彼作加護。常恒於晝夜。大護成就明。等正覺所說。

