才說此四大陀羅尼已。一切諸佛諸大菩薩聲聞。異口同音說此大隨求大明王無能勝陀羅尼甲冑密言句。以一切如來印印之。此甚難得聞。何況書寫。受持讀誦。為他宣說。是故當知是大佛事。如來深極讚歎說隨喜者。極難得聞。此大隨求大無能勝陀羅尼名。極難得聞極甚難得。能盡諸罪。大力勇健具大威德神力。能生無量功德。能摧一切魔眾。能斷一切習氣聚及魔羅羂。能除他真言毒壓禱藥法相憎法降伏法。能令噁心眾生起大慈心。能護愛樂供養佛菩薩聖眾之人。能護書寫受持讀誦聽聞大乘經典者。又能滿足修佛菩提者。大梵持此大隨求無能勝明王。不被沮壞。於一切處獲大供養。如佛大師兩足之尊。雲何得知。此明王能摧一切諸魔。大梵過去有佛。號廣博微笑面摩尼金寶光焰照曜高勇王如來應正覺。初成道時。往詣菩提場欲轉法輪。一切如來稱讚。爾時一切魔並無量俱胝那庾多眷屬圍繞。現種種形作可畏聲。示種種魔境現作神通。雨種種器仗來往四方而作障難。

爾時廣博微笑面摩尼金寶光焰照曜高勇王如來。於須臾頃寂然而住。意誦此大隨求大明王無能勝大陀羅尼七遍。才誦此陀羅尼已。於刹那頃一切魔波旬。見彼如來一一毛孔。出無量俱胝百千那庾多金剛使者。身彼甲冑放大光明。各持刀劍鉞斧羂索杖棒三戟叉。各出如是言。捉縛惡魔摧噁心者。斬斷其命粉粹諸魔作如來障礙者。即彼一切難調惡魔。以如來大威力。於毛孔中出大丈夫。是諸魔眾悶絕擗地。皆失自性神通辯才四散馳走。如來以大慈劍。得勝魔境。成無上菩提。即轉一切如來法輪。如一切佛一切障者毘那夜迦。諸惡魔等。悉皆摧壞如來即轉法輪。超越生死大海得到彼岸。如是大梵此陀羅尼。有大勢力能獲神通到於彼岸。若才憶念。於危險處皆得解脫。意樂清淨噁心有情起大慈心。是故大梵常當憶念。如理作意依法書寫而常帶持。

複次。大梵烏禪那城有王。名曰梵施。彼有一人犯王重罪。王勅殺者一人領彼罪人將往山中令斷其命。殺者受教領彼罪人。至於山窟將刀欲殺。是其罪人先於右臂。帶此隨求無能勝陀羅尼。心複憶念。由此大明威力。其刀光焰狀如火聚。片片段壞猶如微塵。爾時。殺者見此事已。怪未曾有。即以上事具白於王。其王聞已便生大怒。複勅殺者將此罪人送藥叉窟。於彼窟中有眾多藥叉。令食此罪人。受王勅已即領罪人送藥叉窟。才送窟中時。藥叉眾歡喜踴躍奔走向前。欲食罪人。以彼罪人帶大隨求威德力故。時眾藥叉見彼罪人身上有大光明熾盛晃曜。諸藥叉眾悉皆驚怖。各作是念。此火欲來燒我。彼藥叉眾見是事已甚大驚怖。送此罪人安窟門外旋繞禮拜。

