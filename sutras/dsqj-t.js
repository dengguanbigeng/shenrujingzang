爾時焰魔卒還至王所。具以上事白焰魔王。其苾芻承此陀羅尼威力。罪障消滅得生三十三天。因號此天為先身隨求天子。大梵當知此陀羅尼有大威力。汝當受持書寫讀誦依法佩帶。常得遠離一切苦惱一切惡趣。不被電雹傷害雲何得知。大梵於形愚末壇城。有一長者名尾麼羅商佉。其家巨富庫藏盈溢。金銀充滿多饒財穀。於是長者身作商主。乘大船舶入海采寶。於大海中遇低彌魚欲壞其船。海中龍王複生瞋怒。起大雷震哮吼掣電雨金剛雹。時諸商人見此雷雹。各懷憂惱生大恐怖。叫呼求救無救濟者。時眾商人前詣商主。悲聲號哭白商主言。仁者當設何計救護我等令離憂怖。

爾時商主其心無畏。志性堅固有大智慧。見諸商人恐怖逼迫。而告之言。汝等商人勿怖勿怖生勇健心。我令汝等免斯怖畏。其諸商人心生勇健。複作是言。大商主唯願速說除災難法。令我等命皆得存濟。於是商主即告商人言。我有大明王名隨求陀羅尼。能降伏諸難調者有大神通。令汝解脫如此憂惱。即便書寫此隨求陀羅尼。安幢刹上其低彌魚應時即見此船。光明赫奕如熾盛火。由此陀羅尼大威力智火。燒低彌魚即便鎖融。彼諸龍等見是相已。悉起慈心。從空而下廣作供養。令此船舶直至寶洲。大梵此皆大智大明大隨求。以一切如來神力之所加持。是故名為大明王。若有書寫此陀羅尼安於幢刹。能息一切惡風雹雨非時寒熱雷電霹靂。能息一切諸天鬥諍言訟。能除一切蚊虻蝗蟲及諸餘類食苗稼者。悉當退散。一切應言利王爪者不能為害。一切苗稼花果藥草悉皆增長其味香美柔軟潤滑。若其國內旱澇不調。由此陀羅尼威力。龍王歡喜雨澤及時。

複次。大梵。若有流布此大隨求陀羅尼之處。是諸有情既知是已。當以上妙香花幢蓋種種供養。應以殊勝繒彩。纏裹經夾安於塔中或置幢刹。以種種音樂歌詠讚歎。旋繞供養虔誠禮拜。彼等有情心所思惟。所希求願皆得滿足。若能依法書寫。身上帶持所求皆得。求男得男求女得女。懷胎安隱漸增圓滿產生安樂。

大梵雲何得知。往昔曾於摩伽陀國。有王名施願手。以何因緣名施願手。其王初生之時。即展其手執母奶嗍奶足已。由手觸母奶。是其母奶變為金色。母奶增長自然流出。若有眾人來乞求者。王舒右手有淨信佛菩薩諸天。傾寫種種諸妙珍寶。入王手中施求乞者。隨其所須皆得滿足。一切悉得安樂成就。以是因緣名施願手。其王為求子故。供養諸佛及諸塔廟求子不得。王持齋戒廣設無遮施會。大作福業護持三寶。修理未來破壞寺舍故。置一庫藏。何以故大梵我念過去。於此摩伽陀國境俱屍那城大力士聚落多如來教法中。有一長者名曰法慧。於一切眾生起大悲心。為諸有情說此大隨求陀羅尼法要。當彼之時於長者家有一貧人。聞此妙法告長者子言。長者子我於汝家中作務常樂聽法。我當供養此法。彼貧匱人於長者家營事複供養法。於過後時其長者子與一金錢。其人得已發菩提心。為拔濟眾生故以此福回施一切有情。所得金錢便將供養此大隨求陀羅尼。作是願言。以此舍施之福。願一切有情斷其貧匱之業。由此因緣其舍施福無有盡期。如是多種福因緣故。供養諸佛菩薩。由此福業。淨居天子現於夢中而告王言。大王今可依法書寫此隨求陀羅尼令國大夫人齋戒帶持。即有子息。其王覺已。召占相人及有智婆羅門眾。擇吉宿曜直日。依法齋戒書寫此陀羅尼。令夫人帶於頸下。複更供養窣睹波塔諸佛菩薩。廣行舍施。應時有胎。日月滿足產生一子。色相具足端嚴殊勝見者歡喜。大梵當知此是無能勝無礙大隨求寶印心大明王陀羅尼威力故。一切如來之所供養。所求願者皆得稱心。

