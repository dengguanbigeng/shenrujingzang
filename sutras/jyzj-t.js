開經偈
無上甚深微妙法。百千萬劫難遭遇。
我今見聞得受持。願解如來真實義。

佛說淨業障經
失譯人名今附秦錄

如是我聞。一時佛住毘舍離菴羅樹園。與大比丘眾五百人俱。菩薩摩訶薩三萬二千。其名曰壞魔菩薩。神通遊戲光焰菩薩。蓮花身菩薩。放光王菩薩。常調身菩薩。滿眾願菩薩。寶莊嚴堅意菩薩雜華眼菩薩。淨音聲王菩薩。光照明菩薩。妙真金菩薩。降伏一切諸根境界菩薩。大雷音菩薩。如意光積菩薩。文殊師利法王子。如是等三萬二千菩薩而為上首。

爾時。有一比丘名無垢光。入毘舍離城次第乞食。以不知故入婬女家。時無垢光入其家已。是時婬女於無垢光起染汙心。作是思惟。我今必當與此比丘共行欲法。若不從我我將殞命。作是念已即便閉門。語比丘言。願與尊者共行欲事。若不從我我當必死。時無垢光語婬女言。且止大姊。我今不應犯如此事。所以者何。佛所制戒我應奉行。寧捨身命不毀此戒。爾時婬女複更思惟。我今當以咒術藥草令此比丘共為欲事。語比丘言。我今不能令汝退轉毀犯禁戒。但當受我所施之食而入舍內。便咒其食投比丘鉢。咒術力故令此比丘便失正念。起於欲心展轉增盛。爾時婬女見此比丘顏色變異。即前牽手共為欲事。

是時。比丘與彼婬女共相愛樂行婬欲已。持所乞食還詣精舍。到精舍已。生大憂悔舉體煩熱。咄哉何為破大戒身。我今不應受他信施。我今則是破戒之人當墮地獄。時無垢光向諸比丘同梵行者。說如是言。我今破戒非是沙門必趣地獄。時諸比丘問無垢光。有何因緣而破此戒。時無垢光具說上事。時諸同學語無垢光。仁者當知。此有菩薩摩訶薩。名文殊師利。得無生法忍。善能除滅破戒之罪。亦令眾生離諸蓋纏。我今與汝共詣文殊師利菩薩摩訶薩所。除汝憂悔。時無垢光猶故未食。與諸比丘詣文殊師利法王子所。到已問訊供養恭敬。即以上事具白文殊師利。文殊師利語無垢光。汝今且食。食已當共詣如來所問如此事如佛所說當共受持比丘食已。與文殊師利共詣佛所。到已頂禮佛足卻坐一面。

爾時。無垢光比丘心懷恐懼不敢問佛。於是文殊師利即從坐起整衣服。偏袒右肩右膝著地。合掌向佛。即以上事具白世尊。爾時世尊告無垢光。汝實爾不。答言實爾。佛告比丘。汝本有心欲犯婬不。答言不也。佛告比丘。汝本無心雲何而犯。比丘答言。我於後時乃生欲心。如是比丘。心犯欲耶。答言如是。佛告比丘。我常不言心垢故眾生垢心淨故眾生淨耶。答言。如是。佛告比丘。於意雲何。汝曾夢中受欲之時。心覺知不。答言。覺知。佛告比丘。汝向犯欲豈非由心而覺知耶。答言。如是。若如是者。比丘。寤夢犯欲有何差別。比丘答言。寤夢犯欲無差別也。佛言。於意雲何。我先不言一切諸法皆如夢耶。答言。如是。佛言。於意雲何。如夢諸法是真實耶。答言。不也。

佛告比丘。於意雲何。寤夢二心俱真實耶。不也世尊。佛告比丘。若非真實是有法不。不也世尊。佛告比丘。於意雲何。無所有法為有生不。不也世尊。佛告比丘。若法無生有滅有縛有解脫耶。不也世尊。佛告比丘。於意雲何。無生之法當墮阿鼻地獄餓鬼畜生中耶。答言。世尊無生之法尚無所有。而當有墮三惡道耶。

佛告比丘。一切諸法本性清淨。然諸凡夫愚小無智。於無有法不知如故妄生分別以分別故墮三惡道。複告比丘。諸法無實而現種種所應作事。為著貪欲瞋恚愚癡。凡夫等故分別諸法。不如如故非是真實。

複告比丘。諸法虛誑如野馬故。諸法如夢本性自然逮清淨故。諸法究竟如水中月泡沫等故。諸法寂靜無生老病死諸過患故。諸法無取非是色法不可見故。諸法無聚如虛空故。諸法無性過諸性故。諸法甚深過虛空故。諸法廣大無處所故。法無所作究竟寂故。法無所依境界空故。法無根本畢竟空故。法離蓋纏煩惱結使不可得故。法離熾然性不生故。法無障礙本性淨故。諸法無報猶如影故。諸法如幻不如如故。法無所依妄分別故。諸法流轉。而諸眾生著諸邊故。諸法不起諸緣各各性相違故。法無染愛無所屬故。法無穢汙一切結使不可得故。諸法無垢淨過空故。法無微相相寂靜故。諸法調柔性不生故。諸法如如初中後際無差別故。諸法解脫不相屬故。諸法無聞如瓦礫故。諸法非色同虛空故。諸法平等無積聚故。法不可持猶如虛空不可執故。諸法無得智者推求不可得故。法無擾動三世淨故。法無扼縛破暗冥故。法無荊棘離諸纏故。諸法安隱如涅槃故。法無怖畏過諸畏故。法無彼岸無此岸故。諸法無量過算數故。諸法無相其相空故。諸法無作斷諸願故。諸法無行行虛誑故。法無戲論滅覺觀故。法無窟宅離住處故。法無有濁常清淨故。法同涅槃生不可得空無有故。比丘當知。諸法如是不可宣說。是故我昔坐於道場得無所得。無有一法有出有沒有縛有解。亦無有法有障有纏有憂有悔。所以者何。諸法清淨無雜穢故。

爾時無垢光聞說是法。心懷踴躍悲喜交集。即時雨淚叉手合掌一心觀佛。即說偈言。

快哉世尊大功德。諸天世人所歸仰。
善覺一切妙勝行。稽首能斷諸苦行。
無所依者為作依。無有導者為獎導。
安住實道常清淨。稽首世尊大威德。
為世暗冥作燈明。諸無目者為作目。
深著虛妄能度脫。稽首勇猛大精進。
已離染汙無瞋恚。於諸縛著得解脫。
等於怨親能解縛。稽首真實功德聚。
幹竭渴愛及愚癡。破壞諸有除眾苦。
生死輪轉久已斷。稽首大力無上乘。
於諸分別無所著。解脫妙智難思議。
三界最勝離諸垢。稽首清淨無垢人。
我今悉求如是道。當脫無依眾生苦。
願令我得如是乘。終不小乘盡諸漏。
億那由他無量劫。常受眾苦不舍道。
如月盛滿顯眾星。我觀如來亦如是。
譬如有人入大海。其意下劣求水精。
雖遇無量珍寶聚。舍之而取下賤者。
如人聞佛無量力。而不生念我當得。
大乘廣博所作事。放舍菩提證聲聞。
譬如有人見大王。與諸群臣相圍繞。
不求王位希臣佐。當知是意非黠慧。
如人聞佛大功德。妙勝智慧所作事。
而於小乘生喜樂。是則下劣懈怠心。
眾生不應貪小乘。以如暗夜螢火明。
當希日光普大照。能破一切諸黑暗。
佛有無量大名聞。聲徹人天諸惡趣。
佛光微妙為最上。能照世間諸暗冥。
譬如師子處野幹。其心好樂野幹眾。
放舍師子所應作。而更隨逐野幹法。
如有大人在聲聞。其猶師子在野幹。
貪樂小法以為足。當知是輩行貧道。
若人欲求大乘道。當應常發如是心。
利益世間斷眾苦。不應同彼諸聲聞。

爾時。眾會聞無垢光所說偈已。四萬二千天子發阿耨多羅三藐三菩提心。即散摩訶曼陀羅華拘茂陀等。供養世尊。文殊師利贊無垢光。作如是言。善哉善哉。無垢。能報佛恩。於菩提道多所饒益。

爾時世尊即時微笑。諸佛常法若微笑時。有五色光從口而出。所謂青黃赤白紅頗梨色。遍照無量無邊世界上至梵世。蔽於日月所有光明。還至佛所繞佛三匝從頂上沒。

爾時。阿難即從坐起整衣服。偏袒右肩右膝著地。合掌向佛而白佛言。世尊。有何因緣而現微笑。諸佛世尊不以無緣而現微笑。佛告阿難。此無垢光比丘有大深慧。發阿耨多羅三藐三菩提心。我今當授阿耨多羅三藐三菩提記。佛告阿難。此無垢光比丘於未來世彌勒佛所逮無生忍。亦當供養見賢劫千佛。過是之後複經十劫。供養二十億諸佛已。得成為佛。號名功德蓮華最勝妙行師子雷音如來。複告阿難。功德蓮華最勝妙行師子雷音如來應正遍知。彼佛世界名無量音。七寶所成。無有緣覺聲聞弟子。純諸菩薩。彼佛世界常轉平等不退法輪。阿難。此無垢光。速當得阿耨多羅三藐三菩提。所以者何。所乘妙勝淨佛土故。

爾時世尊複告阿難。譬如日光所至之處破眾暗冥。如是阿難。若有眾生得聞此經。當知是處有大照明。能令眾生於一切法得無障礙。爾時阿難前白佛言。世尊。雲何眾生於一切法得無障礙。佛言。且止阿難。何用問此。如是事為如來若說障與無障諸天世人皆當驚疑。爾時文殊師利法王子白佛言。世尊。願說障礙不障礙法。諸菩薩聞。能於後時五濁惡世。於諸世法不生染著。佛告文殊師利。夫障礙者。貪欲是障礙。瞋恚是障礙。愚癡是障礙。佈施是障礙。持戒是障礙。忍辱是障礙。精進是障礙。禪定是障礙。智慧是障礙。佛想是障礙。法想是障礙。僧想是障礙。空想是障礙。無相想是障礙。無作想是障礙。無行想是障礙。不生想是障礙。文殊師利。取要言之。若於諸法有縛有解。當知如是皆是障礙。

爾時文殊師利法王子白佛言。世尊。雲何佈施持戒忍辱精進禪定智慧是障礙法。

佛告文殊師利法王子。一切諸法性無障礙。而諸凡夫愚小無智自生分別。於佈施持戒。忍辱精進。禪定智慧而作障礙。所以者何。文殊師利。凡愚之人行佈施時。於慳眾生不生恭敬。以不恭敬便生瞋心。以瞋心故墮大地獄。身自持戒。見犯戒者而生輕慢。說其過惡令他聞之生不恭敬。以不恭敬故墮於惡趣。自修忍辱。以忍辱故而生高心。我是忍辱餘人麁惡。以是忍故而生放逸。當知即是眾罪之本。自行精進於懈怠者生如是念。如此愚人不應食他信施供養。乃至不應受一飲水。常於己身而起貢高卑下他人。當知是輩愚小無智。自行禪定。見亂想者發如是念。我常修定。其餘比丘多諸亂心說於邪論。如此之人去道尚遠。何能得佛。作是念時。隨所起念。一念一劫。還受生死。受生死已。甫當更修菩提之道。自恃多聞。於無名法以不真智妄生分別。見有所得起大憍慢。我說是輩是大愚癡無智之人。諸覺所覆非是大人。雖複志求大乘之道。作如是言。我當於世為最為勝。而於聲聞小乘之人不生恭敬。輕慢惡賤說其過罪。以其噁心說麁語故而墮惡趣。

爾時文殊師利法王子白佛言。世尊。菩薩不應於佛法中妄宣人惡。佛言。如是如是。文殊師利。於意雲何。菩薩豈不於諸眾生常起慈心憐湣愛念。不以惡眼而視之耶。文殊師利言。如是世尊。複次文殊師利。於意雲何。菩薩豈當於一眾生不以聲聞緣覺大乘而度脫耶。不也世尊。菩薩未曾舍一眾生而不度脫。常於一切起平等心。

佛告文殊師利。譬如良醫等療眾病。國王大臣長者居士及諸貧民。常作是念。雲何能令眾生免苦得離諸病。文殊師利菩薩亦爾。常於眾生起大悲心發平等意。雲何當令一切眾生受行佛法使不斷絕。又如良醫。所有醫方經書咒術不斷絕時。心生歡喜踴躍無量。文殊師利。菩薩亦爾。諸佛種性不斷絕時。心生歡喜亦複如是。文殊師利。一切眾生不盡如醫能治眾病。設有能者是亦難得。文殊師利。菩薩亦爾。不盡如佛起菩提心而自莊嚴。設有能者是亦難得。又如良醫。於諸醫方經書祕術不應懈怠以修醫法。文殊師利。菩薩亦爾。不應懈怠如羸病人發菩提心。文殊師利。自然無師是為難得。不從他知是亦難得。妙勝之心是亦難得。修行佛法是亦難得。

爾時文殊師利法王子白佛言。世尊。雲何菩薩於一切法心無障礙逮得清淨。佛告文殊師利法王子言。若有菩薩觀於貪欲是一切法瞋恚愚癡是一切法。是則名為淨諸業障。

複次文殊師利。若有菩薩於諸五欲不生愛樂亦不放舍。觀欲實性即是佛法。是則名為淨諸業障。複次文殊師利若有菩薩而於五蓋以求菩提。如是觀時不得五蓋及與菩提。是則名為淨諸業障。複次文殊師利。若有菩薩觀九惱法即是慈心。思惟觀察九惱法時。不得他人及與己身。名最上慈。以於諸法無所得故。菩薩觀忍亦複如是。是則名為淨諸業障。複次文殊師利。若有菩薩觀於犯戒即是不犯。觀非毘尼即是毘尼。觀於系縛即是解脫。觀於生死即涅槃界。是則名為淨諸業障。複次文殊師利。若有菩薩觀貪欲界即涅槃界。瞋恚愚癡亦複如是。是則名為淨諸業障。複次文殊師利。若有菩薩觀一切法即是佛法。是則名為淨諸業障。複次文殊師利。若有菩薩觀一切法無有體相亦無根本。是則名為淨諸業障。複次文殊師利。若有菩薩觀慳及施不作二想。持戒毀戒不作二想。瞋恚忍辱不作二想。懈怠精進不作二想。亂心禪定不作二想。愚癡智慧不作二想。是則名為淨諸業障。

複次文殊師利。若有菩薩觀諸煩惱即是佛法。是則名為淨諸業障。爾時文殊師利法王子白佛言。世尊。雲何菩薩觀諸煩惱即是佛法。佛告文殊師利。於意雲何。汝頗見法能還與法作系縛不。答言。不也世尊。文殊師利。於意雲何。頗見有法能為諸法作解脫不。不也世尊。文殊師利。雲何菩薩得無生忍。文殊師利言。一切煩惱即無生忍。所以者何。一切煩惱同虛空性。以是義故。我觀諸法無智無斷無證無修。而諸凡夫障礙所蔽。無有佛法見有斷結。修佛法故。

爾時。世尊贊文殊師利法王子言。善哉善哉。文殊師利。善能解說無盡之法。文殊師利。過去久遠無量無邊不可思議阿僧祇劫。爾時有佛號日無垢光如來應供正遍知明行足善逝世間解無上士調禦丈夫天人師佛世尊。出現於世。文殊師利日無垢光如來壽九十劫。國名眾香。彼佛世界多諸眾生好樂小法。少能修習無上大乘。彼佛世尊般涅槃後。法住千歲分佈舍利。如我滅後等無差別。時有比丘名曰勇施。慚愧樂學善修戒身。多聞智慧顏貌端正。成就第一清淨妙色。

爾時勇施著衣持鉢入難勝城。次行乞食到長者舍。其家有女容貌端正未適夫主。時長者女見勇施已生愛染心。作如是念。我若不得勇施比丘以為夫者。當自殞命。初不向人說如此念。欲心內結遂以成病。爾時勇施乞食得已還詣精舍。而於後時女父命終。爾時其母而問女言。汝何因緣而致斯病。女時默然遂不飲食。爾時女母密遣餘女先來親善同苦樂者。而往問言。以何因緣而致斯病。時女答言。我於先時見一比丘顏貌端正。便生欲心以致斯病。若得從意我病則愈。若不得者便當殞命。是時餘女聞此事已。還向其母具說上事。其母聞已作是思惟。今我此女病患如是。若使不得勇施比丘。當作何計。複作是念。我今當請勇施比丘數至我家。當使此女從受經法。爾時勇施而於異時。入城乞食複至其家。見長者女身體羸瘦。而問之言。此女何緣而有此病。時母答言。而我此女好聽經法。我常固遮不遂其意。以致斯病。爾時勇施語其母言。莫遮此女使不聽法。母還報言。尊者。若能教授此女經法我當聽之。爾時勇施即便許可。其母語言。從今已往常至我家。答言可。爾時長者女聞是語已心大歡喜。我今當作種種方便。令此比丘於我生著。時長者女語勇施言唯願尊者。哀湣我故常至我舍。爾時勇施默然許可。即受其食還詣精舍。

爾時其母語其女言。從今已往好自莊嚴。以好栴檀種種雜香以塗其身。更著新好上妙衣服。如是莊嚴可得從意。其後勇施數到其家轉相親厚。數相見故便失正念而生欲心。即與彼女共行婬法。心遂耽著往來頻數。時彼女夫見此比丘往來頻數心生疑恚。即設方便欲斷其命。勇施比丘聞是事已。即作是念。當以毒藥持與彼女令斷夫命。

爾時勇施即以毒藥持與彼女。而語之言。若必念我可持此藥以殺汝夫。時長者女即以毒藥和著食中。勅其婢使。持此飯食以飯我夫。夫食飯已即便命終。爾時勇施聞彼命終。心生大悔作是思惟。今我所作是大重惡。何名比丘。受行婬法又斷人命。我今如是當何所歸。生大憂惱。我若命終當墮惡道。誰能免我如是之苦。以是事故從一精舍至一精舍。惶怖馳走衣服落地。作如是言。咄哉怪哉。我今即是地獄眾生。

時有精舍名曰醯無。中有菩薩名曰鼻揉多羅。勇施比丘即入其房舉身投地。時彼菩薩問勇施言。何為以身自投於地。答言。大德。我今即是地獄眾生。又複問言誰乃令汝為地獄人。勇施答言。我作大罪。犯於婬戒又斷人命。時彼菩薩語勇施言。比丘莫怖。我今力能施汝無畏。爾時勇施聞彼菩薩施無畏聲。心生歡喜踴躍無量。爾時鼻揉多羅菩薩。即時從地接起勇施牽其右手。將至異處坐林樹中。時鼻揉多羅菩薩湧身虛空高一多羅樹。語勇施言。今汝於我生深信不。勇施即時叉手合掌而答之言。我見仁者。如遇大師亦如世尊。爾時鼻揉多羅菩薩即時入於諸佛境界大乘妙門如來寶印三昧。入三昧已即於身上出無量佛身。皆金色三十二相遍林樹間。爾時諸佛即時同聲。說是偈言。

諸法同鏡像。亦如水中月。凡夫愚惑心。分別癡恚愛。
法無作無處。如虛空清淨。亦無有覺知。虛誑不牢固。
於內求恚愛。未嘗有得者。凡夫生染愛。實無有染著。
如於眠夢中。染著於諸色。亦如刀割物。而刀無所知。
凡夫亦如是。愚惑妄分別。於愛生染著。於恚增諍訟。
世間猶如夢。空無不牢固。如焰空中雲。癡愛寂無相。
諸法如草木。心不在內外。愛非壽命人。自性無所有。
凡夫見諸法。計從因緣生。無作不可取。性離常寂靜。
諸法猶如幻。凡夫生取著。幻性無堅固。貪瞋癡亦然。
諸法常無相。寂靜無根本。無邊不可取。欲性亦如是。
眾生如鏡像。計著於我所。離如妄分別。無堅固可取。
諸法如影響。欲恚無處所。如幻夢水月。實無染恚者。
境界不真實。空無不可取。分別法無主。根本常寂靜。
譬如幻化人。無有貪恚癡。幻夢等諸法。其邊不可得。
如月現於水。而不在水中。凡夫染癡恚。癡愛恚無性。
貪瞋恚愚癡。諸緣常空無。無眾生壽命。虛無常寂靜。
無眼亦無耳。鼻舌亦複然。凡夫癡無智。虛妄生牢固。
如虛空無邊。無盡無去來。諸法亦如是。如手摸虛空。
種種分別法。實無分別者。凡愚計諸陰。而實無有生。
我觀一切法。性相無所有。無生亦無滅。未曾有聚散。
諸法性解脫。寂靜無處所。無能希取者。解此名為智。

爾時林中萬二千天子。詣鼻揉多羅菩薩來聽法者。聞說是偈即時皆得無生法忍。勇施比丘見諸化佛神通變現。於諸法中思惟選擇。離諸蓋纏得無生忍。文殊師利。汝莫生疑。爾時鼻揉多羅菩薩豈異人乎。今彌勒菩薩是也。勇施比丘豈異人乎。寶月如來是也。

爾時文殊師利白佛言。世尊。勇施比丘已成佛耶。佛告文殊師利。今已成佛在於西方。去此佛土恒河沙數諸佛世界。有國名常光。寶月如來於彼成佛。文殊師利。汝觀是法能令眾生離諸業障。受行婬法斷人命根。能令現身得無生忍。所以者何。能觀三界如影響故。猶如幻師觀於幻人無有障礙。文殊師利。諸凡夫人於無有法妄生分別。墮諸惡趣受於無量百千萬苦。

爾時。文殊師利白佛言。世尊。若有菩薩得聞是經受持讀誦書寫供養尊重讚歎。而於現世得何等利。

佛告文殊師利。於意雲何。如日光明照閻浮提。於諸眾生有幾所利。文殊師利白佛言。世尊。如日光明照閻浮提。於諸眾生而作利益無量無邊不可思議。文殊師利。當知是經亦複如是。能令菩薩破諸結縛。能生無量智慧光明。亦於諸法得無障礙。速疾能生無礙智辯。若說法時不為眾魔及外道之所破壞。斷其樂說。文殊師利。譬如大火焚燒草木無有遺餘。當知是經燒一切結。亦複如是。文殊師利。如雪山王諸餘黑山不能障翳。若有菩薩得聞是經。亦複如是。諸餘外道不能如法而毀壞者。文殊師利。如轉輪王諸小國王無敢拒逆。若有菩薩得聞是經。亦複如是。一切雜論嚴飾章句。如是之人不能抑制。

文殊師利。譬如比丘善能持律能除他人破戒疑悔。當知此經亦複如是。能令眾生離諸憂悔。文殊師利。如日天子所至之處能破眾冥。若有菩薩得聞是經。亦複如是。能破一切無明黑暗。能生一切智慧光耀。所以者何。以因是經善修慧故。

爾時。惡魔來至佛所白佛言。世尊。如來大悲憐湣一切常施安樂。唯願世尊莫說此經。所以者何。若說此經諸魔宮殿皆悉震動。諸憂惱箭入我身中。以此經典行閻浮提故。世尊。我今當令如是經典無有受持讀誦書寫供養之者。當使此經似如邪道。令諸眾生起於邪見。讀誦方廣大乘比丘。心生疑悔誹謗此經。

爾時。釋提桓因以佛神力。即於佛前頭面禮足。以天曼陀羅華而散佛上。白佛言。世尊。惡魔波旬設諸方便欲為此經而作留難。世尊。我當受持讀誦書寫供養恭敬。如來滅後我與阿難。當令此經行閻浮提。普令周遍。我與四王諸鬼神等。常當擁護說是經者。若有受持讀誦書寫供養恭敬是經典者。於諸擁護我為宗主。

爾時。世尊告阿難言。汝當受持讀誦書寫供養恭敬如是經典。亦為他人流布顯現。所以者何。阿難。此經則是諸法之鏡。阿難言。如世尊教。我當受持。當何名斯經。雲何奉行。佛告阿難。此經名為淨諸業障。亦複名為入於諸法無障礙慧。說是經時六十比丘不受諸法漏盡意解。八十菩薩得無生法忍。爾時尊者阿難文殊師利法王子。及諸天世人乾闥婆阿修羅等。聞佛所說皆大歡喜。信受奉行。
