高齐天竺三藏那连提耶舍译

大悲经植善根品第十三
复次。阿难。若有比丘受持如是诸法门已。有诸清信善男子善女人等。乐闻法故有来听者。不为演说。是人则为如来怨仇。何以故。是诸人等应为法器。乐欲闻法。不为说故彼不得闻。以不闻故即便退失己之善根。亦复退失他人善根。所以者何。是人不知应可为说。不可为说。

阿难。我以是义欲令明了故说譬喻。犹如商人多赍宝货至大旷野险难路中。开诸宝货。布之在地。唤诸群贼而告之言。我此宝货希有难得。汝与我价。我以此宝当卖与汝。阿难。时彼群贼即于旷野执持刀杖打诸商人。夺其众宝。阿难。于意云何。是诸商人可于旷野布众宝物。唤诸群贼言买物不。

阿难白言。是诸商人犹尚不应旷野险路开诸宝货。况唤群贼。世尊。如是商人应自牢藏众珍宝物。着铠持仗以自防卫。于旷野处安隐而度。此事应尔。

尔时。世尊复告阿难。复有商人亦持诸宝从远方来。到诸城邑王都聚落。到已开诸宝物。布之在地。彼有好人来买宝物。是诸商人方执刀仗共买宝者而共斗战。阿难。于意云何。是诸商人得名黠不。

阿难白言。不也。婆伽婆。不也。修伽陀。世尊。是诸商人应作是言。我此宝物希有难得。汝与我价。当卖与汝。世尊。是诸商人应当如是。不应布诸宝已着铠持仗共相御逆。

佛言。阿难。有诸比丘。受持流通诸法宝藏。所谓修多罗。祇夜。伽陀。毘耶迦罗那。优陀那。尼陀那。阿波那。伊帝毘利多迦。阇多迦。毘弗略。阿浮陀达磨。优波提舍。而于彼等应为法器。不为说故彼不得闻。以不闻故。信等乐欲善心不生。以不生故。不得种诸善根。修殊胜行而般涅槃。彼诸不应为法器者而为演说。彼得闻已。信等乐欲善心不生。以不生故。不得解脱。是人便生诽谤。毁呰。作诸罪业。堕三恶道。阿难。犹如彼愚痴商人。应开宝处而不为开。不应开处而便强开。应可与处而不肯与。不应与处而便强与。阿难。若有清信善男子善女人。善心清净。乐欲闻法。应为法器。来听法者。应可为说而不为说。不应为说而便强说。是故。阿难。若有如是堪为法器。深信乐欲求涅槃者。应当为说。若有不堪为法器者。无信乐欲求其过失。破戒恶行伺求他过。为欲违反佛正法眼。不随顺故不应为说。何以故。勿令彼诸愚痴人等闻此法已生增上过。是故。阿难。当如是学。若有善男子。善女人应为法器。乐闻法者。勤心为说。诸有听者亦复应当摄心专听。阿难。彼若如是。俱能广生无量阿僧祇大功德聚。阿难。于意云何。所有地界及众生界何者为多。

阿难白言。如我解佛所说义。众生界多。非地界也。

佛言。阿难。如是如是。如汝所说。众生界多。非彼地界。亦非水火等界。阿难。及余三千大千世界所有众生。有可知者。有不可知者。有可见闻。有不可见闻。是等一切。于一刹那。一罗婆。一摩睺多顷。假使俱时得作人身。悉成男子。于一刹那。一罗婆。一摩睺多顷皆悉得成缘觉菩提。阿难。乃至无量无边诸世界中所有地土。是诸地土边际不可知。如是地土悉作微尘。彼诸微尘假使皆悉得作人身。悉成男子。彼作人已于一刹那。一罗婆。一摩睺多顷皆悉得成缘觉菩提。阿难。若复无量无边诸世界中有须弥山。铁围山。大铁围山。雪山。香山及余黑山。乃至三千大千世界所有药草。树木。丛林悉为微尘。有可知者。不可知者。有可见闻。有不可见闻。皆得人身。悉成男子。于一刹那。一罗婆。一摩睺多顷。假使一时皆悉得成缘觉菩提。阿难。彼诸缘觉假使寿命从过去际尽未来际。寿命住世不可得知。彼众生中惟有一人独不得成缘觉菩提。然彼一人为大长者。亦从过去尽未来际于中住寿不可得知。时彼长者亦随住寿。供养尔数诸辟支佛饮食。衣服。床座。卧具。病瘦汤药。一切供身称意乐具。恭敬。尊重。谦下供养彼辟支佛。若辟支佛般涅槃后起七宝塔。以诸天人宝幢幡盖。种种花鬘。涂香。末香及以烧香。衣服。歌舞。音声。伎乐。尽天人中最上供具。恭敬。尊重。谦下供养。阿难。于意云何。彼大长者得福多不。

阿难白言。如我解佛所说义。若能供养。恭敬尊重一辟支佛。所得福德尚多无量。不可算数。无等。无限。不可思议。何况供养尔许辟支佛。随其住寿。若灭度后恭敬尊重。谦下供养。

尔时。世尊复告阿难。我今以实告汝。彼辟支佛具足戒定慧解脱解脱知见聚。受彼长者种种供养。有一如来。应。正遍知出兴于世。不受长者衣服。饮食。床座。卧具。病瘦汤药。亦不说法。然彼长者但见如来。应。正遍知凡常威仪示现于世。所得福德多于供养彼辟支佛。具足戒定慧解脱解脱知见者。百千亿那由他倍不及长者见佛。如来凡常威仪示现于世所得福德。何以故。以佛如来具足无量阿僧祇不可思议大功德故。阿难。诸佛如来但以威仪福德善根。犹尚不能穷其边际。何况如来所有无量诸善功德。阿难。若于辟支佛所修行布施所得福德。无量阿僧祇。若于佛所修行布施所得福德。亦复无量无有限者。有何差别。阿难。彼所布施非无差别。阿难。譬如有人为求利故诣于他方。彼得利已即便回还。阿难。若施辟支佛所得福德比佛如来。亦复如是。阿难。若复有人于诸佛所修行布施所得福德不可为譬。何以故。阿难。若于佛所修行布施所得福德。无量阿僧祇不可思议。无等无匹。无有边际。不可穷尽。

阿难。若于佛所修行布施所得福德。我当为汝而作譬喻。诸有智者以喻得解。阿难。譬如画师画虽精好。其中犹有少许鄙拙不端严处。复有画师所作端正转更胜前。如是。阿难。若于辟支佛所修行布施所得福德。比于佛所修行布施所得福德。亦复如是。何以故。阿难。彼辟支佛以其智故得名辟支佛。此辟支佛智皆从如来智慧而生。诸佛如来一切种智转更胜前。是故。阿难。若于佛所乃至尽形衣服。饮食。床座。卧具。病瘦汤药恭敬。尊重。谦下供养。所得福德宁为多不。

阿难白言。如是。婆伽婆。如是。修伽陀。若于佛所乃至尽形恭敬供养所得福德。甚多无量。世尊。若于佛所乃至发心一生敬信所得福德。尚多无量。不可思议。不可算数。何况有人于如来所乃至尽形恭敬。尊重。谦下供养。

作是语已。佛告阿难。且置供养一佛如来以一切乐具乃至尽形而供养者。且置供养二。三。四。五乃至十佛。若二十。三十乃至百佛千佛。百千佛。亿佛。百亿佛。千亿佛。百千亿佛。亿那由他。百亿那由他。千亿那由他。百千亿那由他。乃至遍满阎浮提如来。应。正遍知。尽四天下千世界。二千世界。三千大千世界其中百亿日月。百亿须弥山。百亿铁围山。百亿大海。百亿阎浮提。百亿郁单越。百亿弗婆提。百亿瞿陀尼。八万州渚。并诸眷属。百亿四天下。百亿四天王天。百亿三十三天。百亿须夜摩天。百亿兜率陀天。百亿化乐天。百亿他化自在天。百亿梵天乃至阿迦贰咤天。此名三千大千世界。彼悉满中诸佛。如来。应。正遍知。譬如甘蔗。若竹。若𥯤。若佉陀利林。若迦赊林。彼诸如来寿命长远如恒河沙劫。时有长者寿命住世亦复如是。乃至尽形衣服。饮食。床座。卧具。病瘦汤药。恭敬尊重。谦下供养彼诸如来。若佛灭后起七宝塔。以天幢幡。诸妙宝盖。种种香华。涂香。末香。一切花鬘。诸妙莲花。优波罗花。拘牟头花。芬陀利花。一切歌舞。种种音乐。以如是等一切乐具。恭敬尊重。谦下供养。阿难。于意云何。彼大长者所得福德宁为多不。

阿难白言。如是。婆伽婆。如是。修伽陀。彼大长者于一如来以诸肴膳饮食供养所得福德。尚多无量不可算数。何况如是于诸佛所住恒河沙劫而设供具恭敬。尊重。谦下供养。彼佛灭后起七宝塔种种供养。所得福德不可为譬。

作是语已。佛告阿难。我今以实告汝。若彼长者于诸佛所随其寿命恭敬尊重。谦下供养。彼佛灭后起七宝塔以诸胜妙种种供养所得福德。阿难。若有善男子。善女人于诸如来分别演说菩提道时信解乐欲。具足深信。法是善说。僧是发心善修行者。信解诸行。一切无常。一切苦。一切空。一切法无我。寂灭涅槃。阿难。以此信解所得福德。转复胜前。阿难。若复有人信解如是诸法宝藏。转为他说。所得福德如是广大。如是无量。如是阿僧祇。如是不可思议。如是无等。如是无限。何以故。阿难。如是法宝无上法藏初中后善。若有修行如是布施所得功德。比此法藏。犹如草芥。应如是知。何以故。阿难。如是布施世间有漏是生死法。阿难。我此无量阿僧祇亿那由他劫所集法藏。断除生死。离诸杂食。流转故有。阿难。若有众生闻此法藏。从此生法而得解脱。乃至老。死。忧。悲。苦恼法而得解脱。阿难。我观此义故作是说。有二种人得大福德。一者。懃心为说。二者。至心专听。

作是语已。慧命阿难白佛言。世尊。若有善男子。善女人深信具足。如实修行分别诸法。信解乐欲。法是善说。僧是发心善修行者。信解一切诸行无常。若苦。若空。一切法无我。寂灭涅槃。如是善思深正念者。得几许福。

佛言。阿难。若复有人但知法是善说。僧是发心善修行者。如是善男子。善女人深正思惟。摄心专听。得闻法已。乃至一弹指顷深正思惟。法是善说。僧是发心善修行者。是人于彼所得福德无量无边。何况善男子。善女人深正思惟。摄心专听。听闻法已乃至一弹指顷如实修行。解知诸行一切无常。一切苦。一切空。诸法无我。寂灭涅槃。阿难。若于无量无边诸世界中所有一切诸众生界于一刹那。一罗婆。一摩睺多顷。假使一时俱得人身。彼得人已于一刹那。一罗婆。一摩睺多顷。假使一时于阿耨多罗三藐三菩提成等正觉。彼诸如来假使寿命从过去际不可得知。于未来际亦复如是。阿难。假使是等诸众生中。惟有一人于阿耨多罗三藐三菩提不成正觉。然彼一人为大长者。亦随寿命从过去际不可得知。于未来际亦复如是。尔时。长者乃至尽形恭敬。尊重。谦下供养彼诸如来。以诸乐具。衣服。饮食。床座。卧具。病瘦汤药而以供养。彼诸如来入涅槃后起七宝塔。起宝塔已。宝幢。幡盖。一切花鬘。涂香末香。尽世所有。恭敬。尊重。谦下供养。阿难。于意云何。时彼长者所得福德宁为多不。

阿难白言。若彼长者恭敬。尊重。谦下供养一佛如来。所得福德甚多无量。不可算数。不可思议。无等。无限。何况如是于诸佛所随其寿命恭敬。尊重。谦下供养。所得福德不可思量。

佛言。阿难。如是如是。如汝所说。如是长者所得福德不可思议。是故。阿难。我今以实告汝。若彼长者于诸佛所随其寿命恭敬。尊重。谦下供养所得福德。若复有人深正思惟。摄心专听。得闻法已。乃至一弹指顷信解乐欲。法是善说。僧是发心善修行者。信解诸行一切无常。一切苦。一切空。诸法无我。寂灭涅槃。所得福德不可譬类所能知也。阿难。如我先说有二种人得福甚多。一者。至心为说。二者。专心勤听。

尔时。世尊说是偈言。

为于二种义。应听佛所说。一切漏行尽。近圣成菩提。
若有说法者。及听佛正法。二俱得福多。能建诸仙幢。

尔时世尊复告阿难。有二种人共魔波旬极大战诤。何者为二。一者。至心为说。二者。专心勤听。何以故。阿难。如是梵行得满足者。谓善知识及善等侣。善心流注。何以故。阿难。若有众生遇善知识。遇知识已从生得解脱。乃至老病死。忧悲苦恼法。而得解脱。阿难。此事我昔告诸声闻。有二因缘能生正见。一者。从他闻法。二者。内正思惟。从他闻者当知从佛所闻。内正思惟者亦从佛知。何以故。阿难。如诸凡夫。佛未出时自无内正思惟。佛出世已。教诸凡夫作如是事。阿难。我观是义故作是说。内正思惟亦从佛生。

尔时。世尊说是偈言。

善哉妙丈夫。得见增诸智。若有断疑者。令凡得明慧。
见圣者得乐。共居亦得乐。不见诸凡愚。如常有乐者。

是故。阿难。我为是义随宜演说。梵行满足者。诸善知识及善等侣。能生善心。相续流注。何以故。阿难。若有众生遇善知识得生善心。生善心已。心则得信。心得信已。所作皆善。所作善已。则得善法。得善法已。安住善法。住善法已于佛世尊深得敬重。于法僧所亦深敬重。当得圣所爱戒。自在戒。智所赞戒。趣涅槃戒。阿难。如云降雨小坑满。小坑满已大坑满。大坑满已小河满。小河满已大河满。大河满已大海满。如是。阿难。若有善男子。善女人于诸佛所闻佛说已。得善根力。得善根已。近善知识。近善知识已。得善等侣。得善等侣已。得善流注。得善流注已。得最胜善。得最胜善已。得善心。得善心已。乃至如法。顺法。发心修行究竟转。究竟无垢。究竟梵行。究竟最后。

阿难。汝观如是一切外物同时生长。花果成时无有违失。何况汝等所作善行岂有违失。若有违失。无有是处。是故。阿难。汝等应当修行善行。无有众生修行善行而不得果。有违失者。阿难。我亦曾修一切善行。无有违失。阿难。我本修行菩萨行时。所修一切诸善功德所得果报无有违失。

阿难。汝观如来所行道路于彼所有丘陵。坑坎高下平正。屏厕臭处清净香洁。株杌。荆棘。薮林。丛草秽恶隐没善好低首。树神现身倾侧礼拜。城邑巷路所有众生见佛如来随佛而行。如来过后各还如故。阿难。汝观如来于过去世诸佛。菩萨。善知识所。声闻。缘觉。师僧。父母。耆年。长宿。沙门。婆罗门倾侧稽首。获得如是最胜果报。一切外物见诸佛已。应低首者即便低首。高者令下。下者令高。高下诸处皆悉平正。

阿难。汝观一切愚痴凡夫。于诸尊长不修恭敬。亦不礼拜。憍慢自恃。为慢所害。为慢所缠。

阿难。汝观如来网缦手足。一切皆以善行所得。

阿难。汝观如来本修善行。布施。爱语。利行。同事。以此善行摄护众生。不作分别。此是我父。此是我母。兄弟。姊妹。亲戚。善友。阿难。我于众生一味平等。心无差别。阿难。我于久远无有众生而不摄受。布施爱语。利行同事。如是摄护愚痴凡夫。然彼不知。以已善根福德因缘。生死本际受诸果报。阿难。我于众生与其善根所得福乐。多于自身修诸善业所得果报。阿难。一切世间所有乐具皆悉无常。是变易法。如此乐具是无常故。我本修行菩萨行时。为诸凡愚成熟佛道。令得无为圣。无漏乐。是无漏乐常不变易。更不败坏。是故。阿难。如是圣智当修诸业。如是圣智修诸业者是名正业。

如是。阿难。我本亦曾以此圣智修诸善业。阿难。我亦更说诸余善行。若有众生为涅槃故乃至发心作少善根。种诸种子。闻佛如来说诸妙法深解义趣。忆念如来。心生爱敬。有抆泪者。长叹者毛竖者。若堕地狱。畜生。饿鬼。无有是处。若于菩提不得究竟。亦无是处。阿难。复有众生忆念如来。于法觉悟。有流泪者。毛竖者。叹息者。阿难。莫作异观。彼诸众生堕于恶道。地狱。畜生。饿鬼。中者。无有是处。是故。阿难。汝莫放逸。应勤方便修诸善业。

阿难。诸佛世尊以不放逸得证菩提及助道法亦以不放逸故得。阿难。若有如是善受教者。求利益者。求安乐者。求怜愍者。起悲愍心应如是作。所应作者我已作竟。汝等今者亦应当作。勿令如是真道断绝。又复勿令佛正法眼而有隐没。阿难。汝应如是令佛法眼使得久住。各于人天广行流布。阿难。我今以是正法宝藏付嘱于汝。勿令毁灭。应如是作。是我教法。
大悲经教品第十四

尔时。慧命阿难白佛言。世尊。我今云何修行法眼。若我修行佛正法眼。云何久住于诸天人广行流布。世尊。我复云何结集法眼。云何显说。

作是语已。佛告阿难。我灭度后。有诸大德。诸比丘众集法毘尼时。彼大德摩诃迦叶最为上首。阿难。时彼大德诸比丘众当如是问。世尊何处说大阿波陀那。何处说摩诃尼陀那。何处说大集法。何处说五三法。何处诸天来问。何处天帝释问。何处诸天来下。何处说梵网经。如是次第。彼诸比丘复当问汝。阿难。佛在何处说修多罗。何处说祇夜。何处说毘耶迦罗那。何处说伽陀。何处说忧陀那。何处说尼陀那。何处说伊帝毘利多迦。何处说阇多迦。何处说毘弗略。何处说阿波陀那。何处说阿浮陀达磨。何处说忧波提舍。阿难。佛在何处说声闻藏。佛在何处说缘觉藏。佛在何处说菩萨藏。

阿难。时彼比丘如是问已。汝应如是答。如是我闻。一时佛在摩伽陀国菩提树下初成正觉。如是我闻。一时佛在伽耶城。如是我闻。一时佛在摩伽陀国阿阇波罗尼拘陀树下修苦行处。如是我闻。一时佛在波罗捺仙人住处鹿野苑中。如是我闻。一时佛在耆阇崛山。如是我闻。一时佛在毘富罗山。如是我闻。一时佛在摩伽陀国鞞提诃山。如是我闻。一时佛在王舍城仙人山中大黑方石。如是我闻。一时佛在舍卫国祇树给孤独园。如是我闻。一时佛在毘舍离城菴罗树园。如是我闻。一时佛在毘舍离猕猴池边大林精舍重阁讲堂。如是我闻。一时佛在瞻波城竭伽池边。如是我闻。一时佛在伽耶城伽耶山顶。如是我闻。一时佛在拘睒弥国瞿师罗园。如是我闻。一时佛在娑枳多城阿踰阇园迦罗迦林。如是我闻。一时佛在释种住处迦毘罗城尼拘陀园。如是我闻。一时佛在波离弗城鸠鸠咤园。如是我闻。一时佛在摩偷罗城频陀林中。如是我闻。一时佛在拘尸那城力士生地阿利罗跋提河边娑罗双树间。

阿难。以如是次第。在在处处佛所说法。在在处处大众所集。随其时节。随其句义。随其因缘。随其问答发起因缘。随所为人。随所为事。为欲分别显其智故。随其名味句义次第种种演说。随彼由绪。有因。有缘。善义。善味广为人说。佛说经已。一切大众皆大欢喜。顶戴奉行。

阿难。汝应如是结集法眼。如是分别种种显说如来。应供。正遍知说如是语。如是我闻。

一时已。大地极恶六种震动甚大可畏。令人毛竖。当于尔时。此三千大千世界六种震动现十八相。东踊西没。西踊东没。南踊北没。北踊南没。中踊边没。边踊中没。十八相者。动。遍动。等遍动。踊。遍踊。等遍踊。震。遍震。等遍震。吼。遍吼。等遍吼。起。遍起。等遍起。觉。遍觉。等遍觉。

当于尔时无量天。龙。夜叉。乾闼婆。阿修罗。迦楼罗。紧那罗。摩睺罗伽。释梵。护世。人非人等悲啼流泪。作如是言。婆伽婆。涅槃太速。修伽陀。涅槃太速。世间眼目隐没太速。世间盲冥无目太速。

慧命阿难悲啼流泪亦作是言。婆伽婆。涅槃太速。修伽陀。涅槃太速。世间眼目隐没太速。世间盲冥无目太速。世间导师隐没太速。

尔时。世尊复告阿难。汝莫忧悲。一切有为。生法。有法。分别法。觉知法。因缘生法。灭坏法。若不坏者。无有是处。阿难。汝于长夜以身。口。意慈孝如来。无量安乐。心无有二。无瞋。无恨。无有怨嫌。阿难。汝以如是当得大神通大功德。广大无量。犹如甘露。第一甘露。尽甘露际。是故。阿难。汝于梵行亦复应当以身。口。意恭敬供养。亦当如我应如是学。何以故。阿难。我灭度后于未来世法欲尽时最后五百年。持戒朋党。正法朋党将欲尽灭。破戒。非法朋党炽盛。诽谤正法。寿命短促。众生坏时。法灭坏时。比丘僧坏时。阿难。当于尔时惊畏恐惧。有诸比丘不修身。不修心。不修戒。不修慧。彼等不修身。戒。心。慧者贪着六处。何等为六。一者贪着钵。二者。贪着衣。三者。贪着食。四者。贪着床座。五者。贪着房舍。六者。病瘦因缘贪着汤药。彼等贪求胜妙衣钵乃至上好众味药故。更共斗诤。迭相言讼。上至官司。口如刀剑。互相诽谤。迭共憎嫉。如是。为彼衣钵。饮食。床座。房舍。汤药因缘共相憎嫉。心不纯熟。浊心相向。是故。阿难。汝于梵行身。口。意慈当好供给。具足供养。于诸梵行若见。若闻。若麁。若细。若信。若行。当于彼所莫起恼乱。应如是学。何以故。阿难。当于尔时极大怖畏。命浊。劫浊。众生浊。见浊。烦恼浊。俗人尔时。极受诸苦。为苦所中。为苦所恼。为极饥馑。为极病疫。为贼所恼。亢旱。水灾。为诸螽虫种种恼触。

阿难。时彼婆罗门。长者。居士虽复如是为苦所恼为苦所切。犹有净信。恭敬。尊重于佛。法。僧。数数得生具足深信。彼以信佛。法。僧因缘。于一比丘亦生深信。修行布施。作诸功德。受持禁戒。读诵受持。为人解说。有听受者得闻法已。心生爱敬。欢喜踊悦。如法修行种诸善根。以此善根身坏命终得生善道。诸天人中。

阿难。汝观如是诸恶比丘。当以信心舍家出家。得出家已贪着衣钵六种因缘堕三恶道。在家俗人为苦所恼尚生敬信。以信善根得生善道。是故。阿难。应正身律仪。口律仪。意律仪。当作是念。愿我敬信速得具足。愿我深心正直具足。愿我身心具善思惟。何以故。阿难。身。口。意业不善思惟有五种过。何者为五。一者。妄语。二者。两舌。三者。绮语。四者贪欲。五者。身坏命终堕三恶道。生地狱中。

阿难。善思惟者当得五种功德利益。何者为五。一者不妄语。二者。不两舌。三者。不绮语。四者。不贪欲。五者。身坏命终得生善道。诸天人中。

复次。阿难。若人斗诤。毁呰。言讼违竞相对。心不调柔。浊心变坏者有五过失。一者。妄语。二者。两舌。三者。于诸持戒不生敬信。四者。昼夜忧苦恶意而住。五者。身坏命终堕三恶道。生地狱中。

阿难。若复有人心住慈善。当得十一种功德利益。何者十一。一者。睡眠得安隐。悟则心欢喜。二者。不见恶梦。三者。人非人爱。四者。诸天拥护。五者。毒不能害。六者刀箭不伤。七者。火所不烧。八者。水所不溺。九者。常得好衣。肴膳。饮食。床座。卧具。病瘦汤药。十者。得上人法。十一者。身坏命终得生梵天。阿难。心住慈善得此十一功德利益。

是故。阿难。若我现在及灭度后。自然法灯。自作法归。莫求他灯。莫求他归。阿难。云何比丘自然法灯。自作法归。不求他灯。不求他归。阿难。若有比丘观内身。循身观。勤精进。系念一心。除世贪忧。如是观内身。循身观。观内受。内心。内法。勤精进。系念一心除世贪忧。阿难。是为比丘自然法灯自作法归。不求他灯。不求他归。是故。阿难。我为导师。于诸声闻所应作者我已作竟。汝等今者应如是作。此是我之教法当于阿兰若处。冢间树下。空舍露地。应当一心勤修止观。思灭苦本。慎莫放逸。汝若放逸。后必忧悔。

尔时。世尊说是偈言。

我已说正道。拔诸无智箭。汝今应勤修。诸佛所说法。
为净诸见故。除此更无道。修者得解脱。能断诸魔缚。
若能修此行。如佛之所说。能度一切苦。得满诸佛愿。

尔时。世尊说是经已。慧命阿难及诸比丘。诸来大众。及诸天人。阿修罗。乾闼婆。一切世间闻佛说已。随顺悲喜。举手拍头。椎胸号叫。悲啼流泪。顶戴奉行。
