大悲经梵天品第一
如是我闻。
一时。佛在拘尸那城力士生地娑罗双树间。尔时。世尊临般涅槃。告慧命阿难言。汝可于娑罗双树间安置敷具。如师子王右脇卧法。吾今后夜当般涅槃。阿难。我已究竟涅槃。断除一切有为言说。我已作佛事。已说甘露。无有窟宅。寂灭定甚深微妙。难见。难觉。难可测量。明智所知诸贤圣法。我已三转无上法轮。若有沙门。婆罗门。若天。若魔。若梵。若人。以世共法无能转者。我已击法鼓。吹法䗍。建法幢。置法船。作法桥。降法雨。我已光照三千大千世界。灭除大暗。开示众生。解脱正道。充益天人。所应度者皆悉已度。我已降伏一切外道及诸异论。动魔宫殿。摧魔势力。大师子吼作诸佛事。建丈夫业。满本誓愿。护持法眼。教大声闻。授菩萨记。为于未来佛眼不断故。阿难。我今于后更无所作。唯般涅槃。

尔时。阿难闻是语已。为忧箭所射。极大愁恼。悲泣流泪。白佛言。世尊。婆伽婆。涅槃太速。修伽陀。涅槃太速。世间眼灭。世间孤独。世间无救。无有导师。

尔时。佛告慧命阿难。止。莫忧悲。阿难。生法。有法。有为法。坏法若不灭者。无有是处。我昔告汝。一切所爱。称意等事。必有离散。阿难。汝已慈心。不二心。无恶心及与身业。孝养随顺而无限量侍养于我。阿难。若复天。人。阿修罗等。给侍供养声闻。缘觉。若减一劫。若满一劫。若复给侍供养如来于一念顷。其福多彼。汝已供养大神通佛乃至般涅槃。当得大福。广大功德。犹如甘露。第一甘露。最后甘露究竟涅槃。是故。阿难。汝莫忧悲。

尔时阿难忧悲抆泪。即为如来于双树间犹如师子右脇卧法安置敷具。实时三千大千世界所有树木。药草。丛林皆向如来涅槃方所。有欲倒者。有伛偻者。有欲至地者。有躄地者。于此三千大千世界所有众流。大河。小河。泉池。陂湖。佛神力故。止不流动。三千大千世界所有禽兽。佛神力故。默然而住。不鸣。不食。三千大千世界所有日。月。星宿。火光。明珠乃至荧火。佛神力故。皆不显现。无有光明。不能照曜。三千大千世界所有猛火。佛神力故皆悉止息。不然。不热。不能烧炙。三千大千世界所有一切地狱猛火。佛神力故。皆悉清凉。彼诸地狱所有众生于刹那顷。佛神力故。皆得安乐。三千大千世界所有畜生。一切皆起慈心。愍心。不相瞋恼。加害断命。一切饿鬼皆不飢渴。一切众生。佛神力故。身心踊悦。离苦得猗。具足称意第一安乐。

当于世尊右脇卧时。三千大千世界于中所有须弥山王。铁围山大铁围山。目真隣陀山。香山。雪山及诸黑山。大地。大海。一切皆悉六种震动。所谓动。踊。起。震。吼。觉。三千大千世界一切风轮皆不鼓动。

一切众生于刹那顷舍诸作业得猗而住。离于睡眠。心无散乱。欲作皆息。默然无声。三千大千世界所有天。龙。夜叉。乾闼婆。阿修罗。迦楼罗。紧那罗。摩睺罗伽。梵天。释天。护世王等。佛神力故。各见宫殿床座。园林皆悉暗昧。无复威光。不生爱乐。彼等眷属忧烦不乐。千世界主梵天王。三千大千世界主大梵天王。高心自恃。作如是念。作如是解。念此世界及诸众生是我所作。是我所化。彼三千大千世界主大梵天王。佛神力故。见己宫殿及床座等暗昧无光。不生爱乐。摩酰首罗净居天等亦复如是。

尔时三千大千世界主大梵天王作如是念。是谁力故而现此相。令我不乐宫殿。床座。是时。大梵天王遍观于此三千大千世界中造作富贵大自在主。如来。应供。正遍知。今日后夜当般涅槃。是故现此神力变化。不可思议。未曾有事。此之神力正是如来入涅槃相。时大梵王作是念已。忧愁不乐。战悚毛竖。极疾怱怱。梵众围绕。共诣佛所。其三千大千世界诸余梵天。皆悉已曾信受圣法。安住圣法。

尔时三千大千世界主大梵天王到佛所已。头面作礼而白佛言。唯愿世尊教勅于我。云何而住。云何修行。作是语已。如来即问大梵王言。梵天。汝今实作如是念言。我是大梵天。我能胜他。他不如我。我是智者。我是三千大千世界中大自在主。我造作众生。化作众生。我造作世界。化作世界。不。

大梵天言。如是。婆伽婆。如是。修伽陀。

佛言。梵天。汝复为谁所作。为谁所化。时彼梵天默然而住。

佛见梵天默然住故。而复问言。梵天。有时三千大千世界为劫火焚烧。炎炽洞然。于意云何。是汝所作。是汝所化耶。

时大梵天而白佛言。不也。世尊。

佛言。梵天。如此。大地依水聚住。水依风住。风依虚空。如是。大地厚六百八十万由旬。不裂不散。梵天。于意云何。是汝所作。是汝所化耶。

梵天言。不也。世尊。

佛言。梵天。此三千大千世界百亿日月流转之时。梵天。于意云何。是汝所化耶。

梵天言。不也。世尊。

佛言。梵天。有时日月天子不在宫殿。宫殿空虚。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。如是。春。秋。冬。夏时节。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。如是。水。镜。苏油。摩尼。玻璃及余净器现诸色像。所谓大地。山河。树林。园苑。宫殿。舍宅。聚落。城邑。驼。驴。象。马。獐。鹿。鸟。兽。日。月。星宿。声闻缘觉。菩萨。如来。释梵。护世。人非人等种种色像。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。如是。山崖。深谷。大小诸鼓。歌舞等戏。獐。鹿。鸟。兽。人。非人等所出音声。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。如诸众生于其梦中见种种色。闻种种声。嗅种种香。甞种种味。觉种种触。知种种法。作种种戏。种种啼哭。呻号。怖畏。苦乐等受。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。如四姓人端正。丑陋。贫穷。巨富。福德多少。善戒。恶戒。善慧。恶慧。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。一切众生所有怖畏。苦切。恼害。所谓水。火。刀。风。崖岸。毒药。恶兽。怨仇。人非人畏及以种种加害。于他常有怖畏。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有种种疾病。所谓风。冷。热病及诸杂病。时节代谢四大相违。若他所作。若先业报。所谓眼。耳。鼻。舌。身病。若复众生种种心意热恼等苦。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有旷野险贼。水灾等难。或复中劫刀兵。疫病及以飢馑。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有爱别离苦。所谓父母。兄弟。姊妹。宗亲。善友离别之苦。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所作。种种恶业。所谓贩卖生口。酒曲。紫矿。押油之具。若入大海旷野险处游行诸方。若诸仙方术及余种种断事之法。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所作种种业道。以是业因受于地狱。畜生。饿鬼。人。天之报。众生所有若身。口。意。善行。恶行及世间所有十恶业道。于诸众生都无慈愍。作诸苦恼。不利益事。堕恶道因缘。所谓杀生。偷盗。邪婬。妄语。两舌。恶口。绮语。贪瞋。邪见。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有种种苦事。所谓斩首。截其手足。刵劓耳鼻。节节支解。热油所灌。火灸熬煮。刀剑矛矟斫刺鞭打。系闭牢狱。斗诤言讼。梵天。于意云何。是汝所作是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所作婬欲邪行。或婬母女。姊妹。净持戒者及余恶业。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有种种杀害。厌虫起尸。咒术方药。鬼魅所着。及余种种恶业方便断命因缘。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。世间所有生。老。病。死。忧。悲。苦恼。无常法。尽法。变易法。于四姓人无所忌难。能令一切所爱无厌。种种之物败坏离散。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。众生所有贪。瞋。痴障结使缠缚。及余种种苦恼所缚。以是因缘令诸众生坚着瞋怒迷惑心故。造作无量种种业行。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。所有三恶趣。地狱。畜生。饿鬼。其处众生为种种事受诸苦恼。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。一切所有。若种子生。无种子生。树木。药草。若水陆生。华果。香树。种种胜味。甘。苦。咸。辛。酸。涩之味。随诸众生所喜。不喜作损益者。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。世尊。

佛言。梵天。五道流转。生死成坏。所有众生无明覆盖与爱结相应。驰走流转始终难知。及未来生死流转不断其处。人天。若魔。若梵。沙门。婆罗门。此等世间如乱丝缠缚。常驰流转彼此往来。此诸众生于流转中不知求出。梵天。于意云何。是汝所作。是汝所化。是汝所加耶。

梵天言。不也。婆伽婆。

佛言。梵天。汝从何因作是念言。此诸众生是我所作。是我所化。是我所加。所有世界是我所作。是我所化。是我所加耶。

梵天言。世尊。我以无智邪见。未断颠倒心故。常于如来所说正法不听受故。我本曾作如是恶见。如是恶说。此诸众生是我所作。是我所化。所有世界是我所作。是我所化。世尊。我今还复问佛此义。所有世界是谁所作。是谁所化。一切众生是谁所作。是谁所化。是谁所加。是谁力生。

佛言。梵天。所有世界。是业所作。是业所化。一切众生是业所作。是业所化。业力所生。何以故。梵天。无明缘行。行缘识。识缘名色。名色缘六入。六入缘触。触缘受。受缘爱。爱缘取。取缘有。有缘生。生缘老。死。忧。悲。苦恼。故有如是大苦聚集。梵天。无明灭乃至忧。悲。苦恼灭。更无作者。使作者。安置者。唯有业。有法。和合因缘。故有众生。若能离此业。法。和合。当知是人则能远离生死流转。梵天。如是世间业尽。烦恼尽。苦尽。苦息。如是出离。是名得于寂定涅槃。

梵天。于彼谁得涅槃。若业是业尽。若烦恼是烦恼离。若苦是苦息。如是等法。以诸佛神力故。诸佛所加故有。何以故。梵天。若非诸佛出世显说。则不闻有如是等法。梵天。若诸佛。世尊出兴世时。得有显说如是寂定甚深难觉光明法门。若诸众生得闻生法。从生得解脱。得闻老。病。死。忧。悲。苦恼法。从彼老。病。死。忧。悲。苦恼法而得解脱。梵天。是故。诸佛现作是加。

梵天。诸佛作是开示显说。所谓诸行犹如光影。无常。动转。不定。不究竟。尽法。变易法。假使诸佛灭度之后。正法隐没亦复如是。示现所加。所谓诸行犹如光影。若佛不现。一切诸行于刹那顷如光影者。则不应说一切诸行犹如光影。如梦。如响。

梵天。诸佛以知一切诸行。犹如光影。如梦。如响。无常。动转。尽法。变易法故。说言诸行犹如光影。如梦。如响。智者于彼观其相已。以其相。以其攀缘因缘义故。得知诸行无常。动转。尽法。变易法。破坏离散。时节代谢。于刹那顷乃至日夜。半月。乃至一月。一岁。乃至百岁。一劫。乃至百劫一切尽坏。有大火聚。然已还灭。有大水聚。流已还止。有大猛风吹已还息。世界大地有已还无。有诸大山。所谓铁围山。大铁围山。须弥山及诸黑山等。有已还无。日。月。星宿及诸眷属有已还无。不明。不照。而复堕落。诸天宫殿有已还灭。诸有王都。城邑。聚落。树林。园池。可乐之事生已还灭。诸天人等生已还灭。灭已复生。

诸有智者见其相已心生厌离。以此诸行无常。离坏变易尽故。以平等信心舍家出家。得知诸行犹如光影。如梦。如响。及见水中日。月。星宿等诸光影已。以彼相。以彼攀缘因缘义故得到菩提。有诸智士蒙佛教勅及善友教授。或自思惟。得知诸行犹如光影。如梦。如响。生于信心舍家出家。或有得证须陀洹果。斯陀含果。阿那含果。阿罗汉果。若大乘人或得初忍。或得第二。第三忍及能得到无上菩提。假使诸佛灭度之后。于世间中亦复如是说法流行。若诸众生得闻法已。于三乘得度。所谓声闻。辟支佛乘。一切种智无上大乘。

梵天。汝应当知此法次第亦是诸佛之所加也。是故。智者见其相已心生厌离。能知诸行是无常苦。动转不定尽法。变易法。犹如光影。如梦。如响。

梵天。此等亦是诸佛境界。诸佛所加。有诸众生已曾修行因成就者。得闻如是正法声已。于如来所思念敬信。一切诸行无常坏灭。犹如光影。如梦如响。有诸众生于诸佛所曾修梵行者。或有在家受禁戒者。以是因缘解知如是一切诸行无常坏灭。犹如光影。如梦。如响。知已生信。舍家出家。诸佛世尊虽未出世。以有如是诸佛加故。以诸佛所种善根故。得到菩提。

梵天。应如是知。此等皆是诸佛境界。诸佛所加。梵天。此三千大千世界非梵刹土亦非外道六师刹土。唯是我等诸佛刹土。

梵天。我昔于此无量百千亿那由他阿僧祇劫修菩萨行。无量阿僧祇诸如来所种无量阿僧祇善根。净持禁戒。苦修梵行及修无量百千亿那由他难行。苦行。摄此佛土。修治令净。如诸众生所修善根。随其所堪而清净者。随其时器应得度者。我于长夜以四摄事摄此众生。所谓布施。爱语。利行。同事。彼等以我誓愿力故。生此佛土。闻我说法即能信解。不复归信梵。释。护世。诸天王等。梵天。应如是知。此是佛土。非是梵。释。护世刹土。亦非外道六师刹土。

尔时。娑婆世界主大梵天王及百千梵众现忧愁相。作如是言。诸佛世尊通达希有胜妙之法。

是三千大千世界主大梵天王于如来所生希有心。诸佛希有乃有无量不可思议无尽境界。大梵天王实时归依为佛弟子。于世尊所请求教勅。作如是言。婆伽婆是我大师。修伽陀是我大师。唯愿世尊教勅于我。云何而住。云何修行。

佛告梵天。此三千大千世界是我佛土。我今以此付嘱于汝。汝当顺我。勿使真道善眼令有断绝。无上佛眼。法眼。僧眼令有断绝。莫作末后灭法人也。梵天。当有长子童真弥勒菩萨摩诃萨从佛口生。从法化生。大悲怜愍为欲利益一切众生。欲令得乐。欲令安隐。彼亦于此三千大千世界如法补处。如我居此等无有异。汝既现在随顺我教。亦应顺彼。勿令如是真道法母。佛眼。法眼。僧眼而有断绝。何以故。梵天。乃至如是法母不断者。随其时节。佛眼。法眼。僧眼得不断绝。释梵天眼。人眼。解脱眼。乃至涅槃眼得不断绝。梵天。是故。我今付嘱于汝。我此佛土三千大千世界。梵天。我已教勅。汝应随顺。莫作末后灭法人也。

尔时。三千大千世界所有梵天。大梵天。彼等一切先于圣法已得正信。彼三千大千世界主大梵天王实时于圣法中深得正信。

大悲经商主品第二
尔时。有魔子名曰商主。已于佛所深得敬信。闻佛涅槃。心怀忧恼。战悚毛竖。速诣佛所。到已顶礼。退住一面而白佛言。唯愿世尊怜愍众生。安乐众生。救护世间。怜愍利益诸天人故住世一劫莫入涅槃。我亦怜愍诸天人故。如是劝请。世尊。勿使众生盲冥太速。无有说者。无导。无救。无依。无趣。

尔时。商主作是语已。佛即告言。商主。汝父波旬先已请我令入涅槃。作如是言。婆伽婆。入般涅槃。修伽陀。入般涅槃。婆伽婆。今者正是入涅槃时。商主。汝父波旬如是请我。我随彼意许入涅槃。商主。以是因缘。我今时至。称其所许。故入涅槃。

商主复言。世尊。是魔波旬非是我父。非我善友。常求杀害。是我怨家。大恶知识。常欲令我不得乐事。和合安隐。但作毁坏。不欲利益。世尊。是魔于我极欲作恶。毁谤天人。作大怨仇。常于如是慧炬。慧光。大智明灯求欲灭之。世尊。若有正实语人作如是言。诸天人中。有一极毒恶人出于世者。当知即是魔波旬也。世尊。若有正实语人作如是言。有人不为益己身故。不益他故。不益多众生故而发心者。当知即是魔波旬也。世尊。若复有正实语人作如是言。有人不为怜愍利益天。人。魔。梵。阿修罗。沙门。婆罗门一切世间故。又不欲令和合安隐故。欲令退落受苦恼故。而发心者。当知即是魔波旬也。世尊。我亲从佛闻如是说。有二种人。一者。如法。二者非法。当知世尊所许波旬入涅槃者是不如法。唯愿世尊于此所许莫生坚着。但为怜愍。利益。安乐诸天人等一切众生舍此所许。住世一劫。若佛久住。诸天人等利益安乐。是故世尊莫速涅槃。

佛告商主。善哉善哉。若令众生得利益者。正应如是。商主。若人供给灌顶登位刹利大王。或有供给王子。大臣。或有防护国土。城邑。聚落等者。是人从其刹利王所得大荣爵。受于福禄。其刹利王常于此人及其子孙。亲友。眷属。亦宠福禄。拥护荫覆。商主。汝今若于如来。应供。正遍知。无上法王所心生净信。以净信故。如来则当慰喻于汝。与汝福报。我今慰喻汝者。以汝佛所心生净信。种善根故。如是应知。商主。汝当以此净信善根于我灭后未来世中作辟支佛。名曰悲愍商主。

我涅槃后正法灭已。是魔波旬得大喜悦。以喜悦故坠落魔宫。堕于阿鼻大地狱中。具受无量种种苦恼。何以故。以魔波旬于是大胜慧灯。慧光隐灭之时生大喜故。商主。若有正实语人作如是言。有人为自害故。为自坏故。与己作恶故而发心者。当知即是魔波旬也。何以故。商主。我灭度后。乃至有是正法住世。随其时节是魔波旬得住魔宫。我法灭已。是魔极大喜踊欣庆。得大称意。于刹那顷坠落魔宫。堕阿鼻地狱。

商主。譬如有人上于大树。其树花果悉以具足。是人取其称意花果。既受用已。还复折其所住之枝。商主。于意云何。是人尔时住彼折枝得住树不。又于其树受安乐已还折其枝。可名有智不。

商主言。不也。婆伽婆。不也。修伽陀。

佛言。商主。魔亦如是。常希如来。应供。正遍知入涅槃故。常乐隐灭如来所说正法毘尼故。商主。乃至正法住世。是魔波旬于其时节得住魔宫。我法灭时。其魔波旬生大踊悦。喜庆称意。故坠落魔宫。堕阿鼻地狱。

商主。喻如彼人于其树上而自害故勤作是事。魔亦如是。为自害故。为害他故。而勤发心。商主。魔于后时堕阿鼻地狱受大苦痛。如夺命苦。为苦触已。当念。我言如来。应供。正遍知是真语者。实语者。不异语者。不虚语者。如是善说。善哉身律仪。善哉口律仪。善哉意律仪。是身善行。是口善行。是意善行。获得可乐。可欲。可爱。称意果报。是身恶行。是口恶行。是意恶行。获得不可乐。不可欲。不可爱。不称意果报。我昔与彼身恶行相应。口恶行相应。意恶行相应。以是业报今堕地狱。受如是等极痛。极切。极苦。极恼。极不可忍。如临死之苦。是魔波旬当于尔时忆我所说。得净信心。得净信已。实时于彼地狱命终生三十三天。何以故。商主。若其恶心于如来所作诸过失。身坏命终堕大地狱。若复慈心供养如来不求过者。身坏命终得生善道天人之中。彼以善根得值诸佛。值诸佛已。复种善根。种善根已。次第当得无漏涅槃。

商主。汝于如来。应供。正遍知心得净信。以此善根。弥勒出世当得值遇。值弥勒已。则能觉悟睡眠放逸诸众生等。作如是言。诸众生辈应当勇猛勤作善业。如来。应供。正遍知出世甚难。如忧昙华。时乃一现。如来亦尔。时乃一出无窟宅涅槃。时有说者。人身难得。八难难离。得值佛世。生于中国亦复甚难。是故汝等慎莫放逸。当勤修行。于后莫悔。

商主。汝于弥勒佛所禀受法教。摄彼弥勒无上法王国土人民。常以慈心。无恶心。无怨仇心。愍心。乐心。普覆心。护持养育。以此善根于魔宫殿次补魔处具大富贵。为自在主。商主。若有众生于如来所种诸善根。乃至得发一念净心。彼等众生以此善根得近甘露。第一甘露。最后甘露。

商主。汝以善根于彼广受人天报已。经八十劫于末后身作辟支佛。名曰悲愍。何以故。商主。以汝闻我涅槃声已。便于我所生净信心。于众生所生悲愍心。为诸众生得安乐故。求请我住不般涅槃。汝复于彼弥勒法中悲愍众生。觉悟睡眠放逸众生。令得忆念而不放逸。教以善法。以是因缘得辟支佛记。商主。我当与汝如是善报。应当深心喜悦称意。商主。此等是汝劝请如来善根因缘。如来即以法施荫覆报汝善根。

尔时。商主复白佛言。世尊。若佛不受我所劝请入涅槃者。愿我从今。乃至法住。离于五欲。专持孝道。不乐游戏。不着异衣。不用华鬘。涂香。末香及不受用诸天胜报。何以故。如是世尊。众生之宝。明当与我别离异处。更不合会。更不复有。毕竟不可见。世尊。我有何乐。有何戏笑。有何可乐。有何称意。如是最大慧炬慧灯。大智光明若隐灭者。我当有何踊悦。称意喜庆等事。是大智日有无量百千光炎眷属灭除无明大黑暗者。作大智明者。如是灭没。我当有何踊悦称意。有何可乐。有何戏笑。我于如是众生之宝有别离故。测量众生。不缺减众生。与明众生。无罪众生。无痴众生。无上众生。最上众生。无似众生。无等众生。无等等众生。能救一切众生。众生妙众生。众生所供众生。共乘众生。调伏众生者。怜愍众生者。真语者。实语者。时语者。应时语者。不异语者。如说修行者。住大慈悲者。于诸众生心无罣碍者。于诸众生平等心者。无戏论者。无我我所者。无积聚者。无窟宅者。无依倚者。无荒险者。无垢者。救济者。引导者。化度者。预备者。解缚者。养育者。令众生忆念者。令惺悟者。教诲者。于战斗胜者。拔镞者。医王治心者。施大良药者。究竟度苦者。说法者。商主将去者。示浅处者。持梢尾者。持炬者。作明者。作光者。照曜者。施目者。示导者。令到安隐国土者。远离一切荒险垢者。无渴爱者。离诸使者。离诸结者。离贪瞋痴者。离诸烦恼者。离憍慢怒者。如是大丈夫妙丈夫。极丈夫。健丈夫。猛丈夫。莲华丈夫。芬陀利丈夫。龙丈夫。师龙丈夫。师子丈夫。上首丈夫。凶丈夫。雄丈夫。象丈夫。无上丈夫。无上调御丈夫。共乘者。具一切力者。具十力者。得四无所畏者。具十八不共法者。得大福智力者。满足无量法藏者。无嫉妬者。悦豫一切众生者。无上大施主。最胜施主。心无嫌恨者。得大禅定者。得诸禅三昧三摩跋提境界者。无量慧者。无障慧者。得无等慧境界者。摧魔幢者。渡淤泥者。到彼岸者。住彼岸者。到无畏处者。除一切众生怖畏者。安慰一切众生者。大众生坚固者。于今后夜当有别离。更不可见。世尊。如来常于诸大众中正师子吼更不得闻。我当有何踊悦称意。

世尊。譬如有人于其灌顶刹利王所得福禄者。王命终后生大忧苦。知王恩养。念王恩养。赏王恩养。彼诸众生为其王故专持孝道。或一日。二日乃至七日。若半月乃至一月忆念流泪。世尊。我亦如是。如来灭后乃至正法住世。随其时节舍离五欲。专持孝道。不乐戏笑。不着异衣。不用华鬘。涂香。末香及不受用诸天果报。

大悲经帝释品第三
尔时。释提桓因往诣佛所。到已顶礼。退住一面而白佛言。唯愿世尊教勅于我。云何修行。世尊。昔于一时。四大阿修罗王严驾着铠。将诸眷属来诣三十三天所欲共斗战。当于尔时。圣者目连仍住在世。如是诸天共阿修罗对阵之时。圣者目连到四阿修罗所以如法伏之。如是。诸天及诸阿修罗悉得安隐。无复斗战之苦。共相违反。毁呰诤论。世尊。是大目连既已灭度。如来今复欲般涅槃。我等如是于后数数当复斗战。共相违反。愿垂教勅。若四阿修罗王与我战时。我于彼等作何方计。

佛告释提桓因言。憍尸迦。止。莫忧悲。莫愁。莫虑。若持戒者所愿必成。唯净戒者成。非不净戒。梵行者非不梵行。离欲者非不离欲。离瞋者非不离瞋。离痴者非不离痴。智慧者非不智慧而得成也。憍尸迦。我从今后当作加被。憍尸迦。乃至我之正法未灭。若有诸天。阿修罗等共相斗战。随其时节称我名故诸天得胜。

尔时四大阿修罗王闻佛说是加护声已。其心忿恨。毛竖怖畏。来诣佛所。到已顶礼。却住一面白佛言。世尊。何故如来作是加护。

佛告四大阿修罗言。汝等莫忧。莫虑。有时汝等得大自在。过彼三十三天。无复斗战。无诤。无竞。无相违反。是故。汝等慎莫斗战。莫相毁呰。莫相诤论。勿作违反心。当作慈心。愍心。得众欲具足。诸仁者。命不久停。为自在主亦复无常。诸仁者。世间所有具足合会必归离散。诸仁者。当观如来穷无常际。于诸众生无所怨仇。无违无竞。常为和合。一切众生平等发心。何况汝等薄少善根。彼此迭相乐斗诤者。诸仁者。若有发心恼害他者。是人长夜还得恼害。诸仁者。若人喜杀。是人还得短寿之报。若喜斗诤。是人常有怖畏死报。不具大眷属。无大势力。诸仁者。善。恶二业终不败亡。是故汝等从今已后各住慈心。住身业慈。口业慈。意业慈。莫斗。莫竞。莫相毁呰。以是因缘。汝等长夜得利益安乐。后则不悔。

作是语已。四阿修罗王白佛言。世尊。如是。婆伽婆。如是。修伽陀。我等如是依如来教。如是修。如是住。世尊。我从今后一切当舍斗战之具。各修慈心。

尔时。释提桓因闻佛涅槃。为忧箭所射。极大愁恼。悲泣流泪而白佛言。世尊。我从今日乃至法住。不受五欲。不入内宫。不着异衣。大德婆伽婆。譬如家长丧亡。是人知识得恩养者。心生苦恼。忆念旧恩。念恩养故悲泣流泪。专持孝道。世尊。我亦如是。乃至法住。随其时节悲泣流泪。专持孝道。不行五欲。不入内宫。不着异衣。何以故。无上导师明当别离。不可得见。更不合会。释提桓因作是语已。即便伏面啼哭而住。
