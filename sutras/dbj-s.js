大悲经罗睺罗品第四
尔时。大德罗睺罗作如是念。我今有何喜悦。有何称意。有何欣庆而能堪忍面见世尊入般涅槃。作是念已。东北方去此十佛国土。彼有世界名摩离支。佛号难胜如来。应。正遍知。尔时慧命罗睺罗从拘尸城力士生地没。向东北方难胜如来。应。正遍知所。到已。稽首作礼。却住一面。忧愁不乐。

尔时。难胜如来告罗睺罗言。罗睺罗。汝莫忧悲。罗睺罗。一切所爱。称意等事。有为和合。必皆离散。罗睺罗。凡是事法尔。诸佛世尊作佛事讫皆般涅槃。罗睺罗。汝可还彼。今释迦牟尼如来。应。正遍知。力士生地娑罗双树间如师子王右脇而卧。今日后夜于无余涅槃界而般涅槃。罗睺罗。汝必须往。若佛如来入涅槃后汝必忧悔。

作是语已。时罗睺罗白难胜佛言。世尊。我不忍闻释迦牟尼如来。应。正遍知入涅槃声。况能忍见彼佛世尊入般涅槃。是故我不堪忍往彼。

尔时。罗睺罗答彼难胜佛已即于彼没。往诣上方过九十九世界到第百世界。彼有如来。应。正遍知号曰商主。今现在世。尔时罗睺罗到已。头面作礼。悲泣流泪。忧愁啼哭。却住一面。

住一面已。时商主佛告罗睺罗言。止。罗睺罗。汝莫忧悲。罗睺罗。一切诸法生者不生。老者不老。病者不病。死者不死。尽者不尽。无有是处。罗睺罗。过去诸佛。声闻。缘觉寂灭离而般涅槃。未来诸佛。声闻缘觉寂灭离而般涅槃。现在诸佛。声闻。缘觉寂灭离而般涅槃。罗睺罗。假使如来住世一劫。若百劫。必当如是入般涅槃。罗睺罗。诸佛世尊更无余法。唯是究竟寂灭涅槃。罗睺罗。究竟寂灭者。是究竟定。究竟清凉。究竟尽。究竟乐。究竟安隐。所谓无窟宅涅槃界。罗睺罗。生苦。老苦。病苦。死苦。恩爱别离。怨憎合会。所求不得。五阴重担。如是皆苦。罗睺罗。唯涅槃是乐。

罗睺罗。汝亦不久当般涅槃。罗睺罗。汝及释迦牟尼佛入涅槃处。无生。无老。无病。无死。无爱别离。无怨憎会。无不适意。罗睺罗。汝莫悲恋。莫忧莫愁。罗睺罗。汝当思惟。谁是生者。谁是老者。谁是死者。谁是流转。谁复还生。罗睺罗。皆是虚妄颠倒取着。未闻圣法。诸凡夫等未见诸圣。未信圣法未学圣法。未解圣法。未知圣法。未住圣法故。心颠倒想。颠倒见颠倒。以颠倒故生。生故老。老故死。死已还生。驰走流转。枯焦败坏。爱恋忧愁。椎胸号哭。罗睺罗。一切圣人唯以此法毘尼息一切行。于上更无所作。罗睺罗。如是。导师所作已讫。声闻弟子所作者已作。于上更无所作。罗睺罗。汝莫悲恋。莫忧。莫愁。

罗睺罗。彼释迦牟尼佛无上法王于释种中尊。汝当往彼最后礼拜。供养。恭敬。若涅槃后汝必忧悔。

罗睺罗。彼释迦牟尼佛今在力士生地娑罗林间如师子王右脇而卧。思欲见汝罗睺罗。汝必须往。

作是语已。慧命罗睺罗白商主佛言。世尊。我不忍闻释迦牟尼如来。应。正遍知入涅槃声。况能忍见彼佛世尊入般涅槃。作是语已。身心闷绝。不自胜持。复作是言。而彼世尊释迦牟尼于释种中尊。无上法王。众生中宝。我今何能忍见彼佛入般涅槃。怜愍一切世间者。一切世间形相无与等者。与一切世间作灯者。与一切世间作眼目者。与一切世间作慧炬者。照曜一切世间者。明日离散。当无所有。

作是语已。时商主如来告罗睺罗言。止。罗睺罗。汝莫忧悲。罗睺罗。汝可不闻。彼佛世尊说如是法。一切行无常。一切行苦。一切法无我。寂灭涅槃。罗睺罗。彼佛世尊说如是偈。

诸行无常。是生灭法。生已还灭。灭彼为乐。

罗睺罗言。如是。世尊。

佛告罗睺罗。彼佛世尊昔可不作如是说也。一切所爱。称意等事。必归磨灭。不久离散。假使久住。会亦有离。

罗睺罗言。如是。婆伽婆。如是。修伽陀。

佛言。罗睺罗。有为诸法。生法。有法。觉知法。分别起法。从因缘生。若不灭者。无有是处。

尔时。罗睺罗忆念己父释迦牟尼如来。应。正遍知已。流泪而言。我于明日更不见佛。诸比丘众围绕说法。如大海中须弥山王众相庄严。起光明照。犹如满月众星围绕。如日千光处空照曜。如深大海无量众宝所藏积处。如转轮王。无量眷属而共围绕。如雪山王根力觉花之所开敷。如铁围山。一切恶风所不能动。如是世尊。一切外道诸论议风不能倾动。犹如莲花处在池中。不为世法之所能染。犹如大梵具梵眷属。犹如帝释有千眼目。如师子王坐师子座无所恐惧。离诸怖畏能师子吼。我于明日更不得见。时罗睺罗作是语已。默然悲泣。思惟而住。

尔时。商主如来告罗睺罗言。汝今速可诣彼佛所。彼佛如来思欲见汝。罗睺罗。汝当速去。莫更重问致有稽留。慎莫劳扰彼佛世尊。罗睺罗。汝必须往。何以故。罗睺罗。诸佛法尔。佛以慈悲思欲见汝。不入涅槃。

尔时。罗睺罗头面礼彼商主佛已。譬如壮士屈伸臂顷。复如伸臂屈顷时。罗睺罗即于彼没。诣拘尸城力士生地娑罗双树间到如来所。亦复如是。到已。头面礼足。右绕三匝。却住一面。忧愁悲泣。合掌流泪。

尔时世尊告罗睺罗言。罗睺罗。汝莫悲恋。忧愁。啼哭。心生热恼。罗睺罗。汝于父所作父事讫。我亦汝所作子事讫。罗睺罗。汝莫生恋。忧愁悲悔。罗睺罗。我与汝等俱为一切众生得无畏故。发勤精进。不作怨仇。不作恼害故。发大精进。罗睺罗。我今般涅槃已更不与他作父。罗睺罗。汝亦当般涅槃。更不与他作子。罗睺罗。我与汝等二俱。不作恼乱。不作怨仇。

尔时罗睺罗白佛言。世尊。婆伽婆。莫般涅槃。修伽陀。莫般涅槃。唯愿世尊住世一劫。为于多众安隐乐故。怜愍世间故。利益安乐诸天人故。

作是语已。佛告罗睺罗言。罗睺罗。如来。应。正遍知尽知诸法。于世间中得名为佛。罗睺罗。然彼佛法。不消。不尽。不生。不灭。不来。不去。不成。不坏。不坐。不卧。不合。不散。何以故。罗睺罗。如是法住。毕竟不生。毕竟不灭。毕竟空。毕竟无自性。寂定涅槃。不入众数。无窟宅。不可说。非语言道。此是诸佛法。所谓毕竟住故。毕竟灭故。毕竟寂灭故毕竟离故。毕竟离欲故。毕竟不和合故。毕竟不作故。毕竟尽故。罗睺罗。我随宜说此法。假使诸佛若出世。若不出世。如是诸法住。诸法如。法尔故。法不变易故。法离欲故。法无自性故。罗睺罗。如是。如来不将戒聚入般涅槃。不将定聚。慧聚。解脱聚。解脱知见聚入般涅槃。罗睺罗。汝莫悲恋。莫忧莫愁。罗睺罗。一切诸行无常。无定。无所悕望。无常尽变易法。罗睺罗。乃至息一切行。厌舍不着。唯求解脱。罗睺罗。此是我之教法。

佛为罗睺罗说此见实谛品时。大德比丘六十人皆尽诸漏心得解脱。二十五比丘尼亦心解脱得尽诸漏。无量天人远尘离垢得法眼净。六万八千诸菩萨得无生法忍。一切皆悉欢喜踊跃。叹言佛法不可思议。彼等皆悉以优波罗花。波头摩花。拘牟头花。芬陀利花而散佛上。各作是言。我于来世亦当如是作天人师。出兴于世说如是法。世间无上。无相涅槃。如是以大涅槃而般涅槃。彼诸菩萨作是语已。默然而住。

大悲经迦叶品第五
尔时。阿难在佛床边。悲啼流泪。闷绝躄地。犹如临崖斫断大树。作如是言。婆伽婆。涅槃太速。修伽陀。涅槃太速。众生中宝。大慈悲者隐没太速。世间大灯。世间大炬。天人中最隐没太速。众生芬陀利于世间中隐没太速。众生龙象善自调者。复调众生。未调者令调。隐没太速。无上导师。能示世间安隐道者隐没太速。世间慧眼。大光普照。能示世间。隐没太速。世间盲冥无引导者。众生父母于世间中隐没太速。世间孤独无所恃怙。众生中宝。云何明日我更不见。唯有名在。

尔时。世尊告阿难言。止。阿难。莫忧悲。我曾告汝。一切所爱。称意等事。和合之法必有离散。阿难。有为诸法。生法。有法。觉知法。因缘法。灭坏法。若不坏者。无有是处。彼若得住。亦无是处。阿难。假使久住。法当如是。必亦有离。是故。阿难。汝莫忧悲。

尔时。阿难瞻仰尊颜目不暂舍。思惟是已亦复躄地。犹如临崖斫断大树。

佛复告言。阿难。止。莫忧悲。不以忧悲令我住世。阿难。我曾告汝。一切所爱。称意等事。有为和合必当别离。假使久住会亦当灭。诸行法尔。阿难。汝以身。口慈孝如来。无量安乐心无有二。无瞋。无恨。无有怨仇。

尔时。阿难从地而起。抆泪而言。世尊。我何得不愁。何得不悲。我与如是大慈悲者。出一切世间者。怜愍一切世间者。一切世间所爱惜者。一切世间所归趣者。导引一切世间者。利益一切世间者。安乐一切世间者。如是大宝众生。明当别难。

尔时。阿难大号哭已。抆泪而言。奇哉。奇哉。诸行是尸而作欺陵。能令如是大灯。大炬。大日光明。无量光炎。百千亿那由他炎幢眷属。普现世间见知念慧境界。普照大宝众生隐没太速。大智慧者。大光明者。今于世间隐没太速。世间孤独。作覆护者隐没太速。如来具足神通变化。今于世间隐没太速。世尊。我何得不愁。何得不悲。世尊。我今自怪心不破裂以为百分。世尊。我亦自怪不于佛前而取命终。必是世尊神力加我。以是义故不取命终。何以故。我于佛所亲承面受八万四千诸法宝藏受持不忘。未广流布在于十方诸天人故。世尊。我为如来神力所加。以是义故。我不命终。

世尊。我何得不愁。何得不悲。世尊。我到迦毘罗城世尊生处释种集时作何等语。可言日种释迦牟尼佛。释种中尊。无上法王般涅槃耶。我到王舍城毘提希子阿阇世王所作何等语。可言大师佛日隐没。能拔世间无间业箭医王去耶。我到舍婆提城作何等语。可言大悲怜愍世间者隐没去耶。我到祇陀林。给孤独长者而问我言。如来何时来住祇陀林给孤独园。作何言答。我到毘舍离城诸离车子前当作何言。可言怜愍世间最大尊师隐没去耶。诸方所有善男子。善女人来问义者作何言答。可言是大智人世间智者。断一切疑者隐没去耶。诸方所有诸比丘众为欲见佛。供养礼拜。问讯世尊。为布萨故来问法者。来问义者。我更不见。不闻彼说得上人法。世尊灭后有如是等神通变化。修梵行者隐没于世。我何得不愁。何得不悲。

作是语已。佛告阿难言。阿难。止。汝莫忧愁。我之梵行当广流布。久住世间。利益天人。阿难。我灭度后过四百年。迦叶共汝及诸弟子展转相承。作神通变化。修行梵行利益天人。阿难。汝莫忧悲。我之正法当广流布。久住世间。利益天人。阿难。我涅槃后。迦叶比丘共汝发心。令我阿僧祇亿那由他劫所集无上三藐三菩提法增益诸善。使不退失。何以故。阿难。是迦叶比丘少欲知足。远离精进。乐不忘念。乐不戏论。定慧现前。阿难。迦叶比丘能于大众示教利喜。于诸梵行说法不惓。犹如父母。阿难。迦叶比丘于诸四众所见悬远。怜愍世间。为欲利益安乐众生诸天人故。发如是心。

尔时。阿难白佛言。世尊。迦叶比丘如是发心。利益安乐几许诸天人众。

佛言。阿难。迦叶比丘入涅槃时作是誓愿。愿我灭后。以我神力所加持故。令我身衣不变不坏。发毛。肤色。诸根支节亦不变坏。乃至弥勒如来。应。正遍知出兴世时。令我此身见彼世尊。共作初会。如是第二第三大会。以我愿力所加持故。当令多百众生。多千众生。多千万众生。多百千亿那由他众生得圣道果。若弥勒佛见我身。衣不变不坏。三会声闻亦见我身不变不坏诸根支节及袈裟已。然后我身住在空中。以己身火阇维其身。阇维身已灰炭不现。阿难。是为迦叶发心利益安乐众生。阿难。迦叶比丘如是愿力所加持故。成熟如是诸众生已而般涅槃。

阿难。迦叶比丘般涅槃已。有四石山当来到迦叶所。覆障其身合成为一。阿难。是迦叶身在彼四石山中身不变坏。至弥勒佛出兴于世。随尔许时迦叶比丘身住不坏。及袈裟衣亦住不坏。何以故。阿难。持净戒者。修梵行者。有智慧者所愿能成。非戒不净。不修梵行。无智有欲所能成也。阿难。迦叶比丘先以愿力所加持故入般涅槃。入涅槃已。彼迦叶身常不变坏。发。毛。血。肉。诸根支节及以衣服亦不变坏。身亦不臭。乃至弥勒。

阿难。彼弥勒佛出兴世时。共彼初会九十六亿诸比丘众到迦叶所。阿难。是弥勒佛以迦叶身示彼九十六亿诸比丘众。作如是言。诸比丘。此迦叶比丘于释迦牟尼如来法中作大声闻。住胜头陀少欲知足。远离精进。乐不妄念。乐不戏论。定慧现前。能于多众示教利喜。于诸梵行说法不倦。犹如父母。诸比丘。是迦叶比丘于诸四众所见悬远。毕竟无疑随顺多众。诸比丘。汝观迦叶怜愍世间。为欲利益安乐一切诸人天故发如是心。

阿难。弥勒如来。应。正遍知第二会时。共九十四亿诸声闻众来到其所。第三会时。共九十二亿诸声闻众亦来到迦叶所。阿难。彼弥勒佛示彼九十二亿比丘众言。此迦叶比丘于释迦牟尼如来法中最大声闻。住胜头陀。少欲知足。乃至发心为欲利益安乐一切诸天人故。阿难。弥勒如来当于彼时舒金色右手摩迦叶顶。观察诸比丘言。诸比丘。是迦叶比丘于释迦牟尼佛灭度之后广持正法。而此众中无有一人于我灭后。广能如是持我正法如迦叶者。

阿难。是迦叶比丘于彼第三大会。以本愿力所加持故。住虚空中现种种神通。种种变化已。以己身火阇维其身。阇维身已。灰炭不现。时弥勒佛当于彼时发起迦叶已。为彼九十二亿诸比丘众数数说法。多百。多千。多亿那由他百千天人得圣道果。

阿难。迦叶比丘发心利益多众生故。汝亦发心利益安乐多众生故。如是。阿难。迦叶比丘及汝发心故。过四百年能持我之正法。及作神通种种变化。修行梵行。各能增益诸天人众。

大悲经持正法品第六
尔时。世尊复告阿难。汝莫忧悲。我之梵行当广流布。各能增益诸天人众。阿难。我灭度后。摩偷罗城优楼蔓茶山有僧伽蓝名那驰迦。于彼当有比丘名毘提奢。有大神通。具大威力。正智得道。多闻无畏。持修多罗。持毘尼。持摩多罗迦。于诸梵行示教利喜。说法不倦。彼亦当作神通变化。修行梵行。广行流布我之正法。增益天人。

阿难。汝莫忧悲。我灭度后。还于优楼蔓茶山那驰迦僧伽蓝。当有比丘名提知迦有大神通。具大威力。于诸梵行说法不倦。能令我法广行流布。增益天人。阿难。汝莫忧悲。我灭度后。还于优楼蔓茶山傍。有山名优尸罗。彼有四万比丘集会。有神通。有大威力。多所堪能。正智得道。多闻无畏。持修多罗。持毘尼。持摩多罗迦。各能于诸梵行示教利喜。说法不倦。彼等比丘神通变化。修行梵行。令我正法广行流布。各能增益诸天人众。

阿难。汝莫忧悲。我灭度后。还于优楼蔓茶山傍。当有比丘名优波毱多。有大神通。具大威力。乃至亦能神通变化。修行梵行。令我正法广行流布。增益天人。于彼当有千阿罗汉。集八万八千诸比丘众共一布萨。作一羯磨。心不欺诈。共相授记。彼等皆能神通变化。修行梵行。令我正法广行流布。各能增益诸天人众。阿难。汝莫忧悲。是优波毱多及诸弟子。各各能令我之正法广行流布。于诸天人能正显说。

阿难。汝莫忧悲。我灭度后。于波离弗城有僧伽蓝名跋多尼。彼有比丘名阿轮婆毱多。三明六通具八解脱。禅智二分解脱自在。有大神通。具大威力乃至彼等亦能神通变化。修行梵行。令我正法广行流布。增益天人。阿难。汝莫忧悲。我灭度后。还于波离弗城有僧伽蓝名鸠鸠咤。当有比丘名郁多罗。有大神通。具大威力。乃至亦能神通变化。修行梵行。广行流布我之正法。增益天人。阿难。汝莫忧悲。我之梵行当广流布。各能增益诸天人众。

阿难。我灭度后。于鸯伽国当有我诸声闻作般遮跋瑟伽会。彼处当有过一万三千阿罗汉集。彼等一切有大神通。具大威力。有多堪能。乃至于诸梵行说法不倦。彼有上座名设陀沙茶。有大神通具大威力。有多堪能。于诸梵行说法不倦。彼等亦能神通变化。修行梵行。令我正法广行流布。各能增益诸天人众。

阿难。汝莫忧悲。我灭度后。金钵悉陀城当有二比丘于婆罗门种中出家。一名毘头罗。二名删阇耶。各有神通。具大威力。有多堪能乃至亦能神通变化。修行梵行。令我正法广行流布。增益天人。

阿难。汝莫忧悲。我灭度后。婆鸡多城当有比丘名大精进。有大神通。具大威力。乃至亦能神通变化。修行梵行。令我正法广行流布于诸天人。

阿难。汝莫忧悲。我灭度后。当有比丘名末田提。三明六通具八解脱。禅智二分解脱自在。有大神通具大威力。乃至于诸梵行说法不倦。北天竺国罽宾川中。当有无量诸龙。夜叉。乾闼婆等具大身力依住彼川。是末田提比丘到于彼处。为彼诸龙。夜叉。乾闼婆等来共斗诤。是末田提比丘神通变化。以法降伏诸龙。夜叉。乾闼婆等令得敬信。得敬信已。令人住在彼罽宾川。建立诸僧伽蓝。多有声闻。多百多千声闻众集。阿难。是末田提比丘于一切时令彼住处具诸善事。阿难。我若具足称扬广说彼末田提所有功德。不能穷尽。阿难。是末田提比丘具诸功德。能令我法毘尼神通梵行于诸天人广行流布。

阿难。汝莫忧悲。我灭度后于北天竺乾陀罗国。当有比丘名曰迦叶。有大神通具大威力。有多堪能。正智得道。多闻无畏。持修多罗。持毘尼。持摩多罗迦乃至亦能令我正法广行流布。

阿难。汝莫忧悲。我灭度后北天竺国有城名得叉尸罗。彼有长者名阇知迦。名震诸方。具大豪富。多饶财宝具足。功德智慧相称。端正可爱。相好第一。彼阇知迦长者深信于我。及诸声闻。供养恭敬。尊重赞叹。次第积集菩提善根。于未来世满千劫已。成阿耨多罗三藐三菩提。佛号普光。劫名造贤。世界名具大庄严。阿难。彼阇知迦长者于诸天人广行流布我之正法。

阿难。汝莫忧悲。我灭度后北天竺国当有王都名富迦罗跋帝。人民炽盛。丰乐安隐。彼处多有诸婆罗门。长者。居士随顺修多罗。深信于我及诸声闻。供养恭敬。尊重赞叹。彼有无量声闻弟子。有大神通。具大威力。有多堪能。阿难。于彼多有长者。居士正智得道。多闻无畏。具大智慧。阿难。彼富迦罗跋帝王都所有在家诸白衣等。彼命终已生兜率天。诸出家者悉堕地狱。何以故。彼不住戒。不住律仪故。

阿难。彼富迦罗跋帝王都所有婆罗门。长者。居士等。当作是念。释迦牟尼佛之正法必当隐没。何以故。诸比丘等于诸利养增上贪求。多毁禁戒。其心散乱。不乐闲林。舍离禅乐。与诸四众数相往来。破戒违道。共诸婆罗门。长者。居士等。亲友交通不相敬重。饮食花果迭相赠遗。不依律仪无有惭愧。婬彼女妇。彼诸婆罗门。长者。居士等。见闻彼诸比丘作非法已。生大惊怖。心甚忧恼。作如是言。佛之正法可隐没耶。当于彼时。还于富迦罗跋帝王都当有优婆塞名曰法增。有大神通。具大威力。有大福德。正智得道。多闻无畏。持修多罗。摩多罗迦。善巧方便。是优婆塞为欲令彼婆罗门。长者。居士等生敬信故。上升虚空示教利喜而作是言。汝等诸人慎莫怖畏。莫疑莫虑。彼释迦牟尼佛之正法犹住在世。汝可发勤精进。作诸善业。未得者令得。未证者令证。未达者令达。圣法今在。宜可速求。时。婆罗门。长者。居士等心皆喜悦而行布施。作诸功德。于我舍利装饰严持。及诸声闻勤作供养。听受读诵。转为他说。受持禁戒。勤修禅定。彼诸婆罗门。长者。居士等。为彼法增示教利喜。皆趣善道及涅槃道。阿难。彼优婆塞亦能令我正法广行流布。增益天人。

如是。阿难。于我灭后亦当多有俗人于我法中深得敬信。曾于过去供养多百多千无量诸佛。植诸善根。于我舍利勤修庄严及诸声闻供养恭敬。尊重赞叹。阿难。彼等亦令我之正法广行流布。增益天人。

阿难。我灭度后。于未来世北天竺国。当有比丘名祁婆迦出兴于世。曾于过去无量百佛植诸善根。供养恭敬。深信具足。安住大乘。为欲怜愍利益安乐诸众生故。发如是心。多闻持菩萨藏。称扬大乘。显发大乘。是比丘见我舍利。形像。塔庙有破坏者。装校修治。以金庄严竖立幢幡。宝盖铃网出微妙音。兴造如来无量形像及诸塔庙。其诸塔庙皆以半月师子庄严。能令诸天人众心生信乐。为欲满足菩提善根故。怜愍众生故。护持养育故。摄受我法故。为不敬信者令敬信增修故。亦令多众种善根故。作般遮跋瑟迦会。阿难。当于尔时。多有比丘不持禁戒。多作非法。不乐闲林。舍离禅乐。破戒违道。共相言讼。贪惜积聚。独占一房。与诸俗人互相往来。舍离佛法。于诸梵行不生敬重。形似沙门。当于尔时有少比丘发勤精进。远离愦閙。系念现前。定慧一心。安住善法。少欲知足。乐修乞食。安住圣种。多闻无畏。持修多罗。持毘尼。持摩多罗迦。当于尔时。祁婆迦比丘令诸比丘着袈裟者其心柔软。诸根无缺。具足深信第一敬重。于彼所有着袈裟者起持戒想。作福田想而行布施。修诸善根。彼祁婆迦比丘修集无量种种最胜菩提善根已而取命终。生于西方过亿百千诸佛世界无量寿国。于彼佛所种诸善根。复经八十亿诸如来所修诸梵行。以此善根于未来世过九十九亿劫而成正觉。佛号无垢光。世界名一切功德庄严。阿难。彼祁婆迦比丘令我正法于诸天人广行流布。

阿难。汝莫忧悲。我之梵行当广流布。天人信乐。阿难。我灭度后。于未来世当有边国名曰舍摩。彼有国王名曰大施。而于我法心生净信。于我舍利。及诸声闻勤修供养。称扬赞叹。阿难。彼大施王于舍摩国集我声闻诸比丘众尊重供养。于彼当有过三千阿罗汉。皆有神通。功德。威力。乃至于诸梵行说法不倦。阿难。彼等亦能令我正法于诸天人广行流布。

阿难。汝莫忧悲。我灭度后北天竺国有城名兴渠末但那。彼得我舍利尊重供养。当以花鬘。涂香。末香。音声。伎乐幢幡。宝盖。衣服。卧具。众宝。金银以用庄严。阿难。时彼精舍当有多人以信出家。受持禁戒。修行善法。诸俗人等修行善法亦复无量。阿难。彼有持戒。多闻。有智。于我法中深得净信。于我声闻及我舍利勤修装饰。严治供养。于佛。法。僧供养加护。以此善根。于天人中受福报已。有得阿耨多罗三藐三菩提者。有得缘觉乘者。有得声闻乘。而涅槃者。阿难。彼以如是种种供养。当得如是神通威力。阿难。是等诸人开示演说。令我正法于诸人天广行流布。阿难。汝莫忧悲。我之正法当广流布。增益天人。阿难。我之舍利及我形像遍阎浮提。何况人不见处。所谓天。龙。夜叉。罗刹。乾闼婆。阿修罗。迦楼罗。紧那罗。摩睺罗伽。鸠槃茶等宫殿之中。所造形像。阿难。汝莫忧悲。我法毘尼于诸天人当广流布。

大悲经舍利品第七
尔时。世尊复告阿难。我灭度后。若有善男子。善女人。若在家。若出家。乃至供养我之舍利如芥子等。恭敬尊重。谦下供养。我说是人。以此善根。一切皆当得涅槃果。尽涅槃际。阿难。若我灭后。所有善男子。善女人心生敬信。为我造立形像塔庙。阿难。应生深信。慎莫疑惑。我说是人以此善根。一切皆当得涅槃果。尽涅槃际。阿难。且置现在供养我者。且置我灭度后供养如芥子等舍利者。且置为我造立形像及塔庙者。阿难。若有信心念佛功德。乃至一花散于空中。我说是人以此善根。一切皆当得涅槃果。尽涅槃际。阿难。若复有人见佛世尊神通威力。为供养故。乃至一花散于空中。犹能得涅槃果。何况亲承如来而供养者。及我灭后供养舍利者。阿难。诸佛境界不可思议。若复有人能供养者。所得福德亦不可思议。阿难。若人念佛乃至一花散于空中。我以佛智见知是人所得果报不可思议。汝应当信。何况未来所有佛子深得敬信。思惟佛功德。求佛智者。

尔时。阿难闻佛语已。心怀踊跃。生大欢喜而白佛言。希有。婆伽婆。希有。修伽陀。今正是时。唯愿世尊说其念佛。乃至一花散于空中而供养者所得果报。诸比丘等从佛所闻。读诵受持。以是当得。怜愍世间。利益安乐诸天人故。于现在世及未来世所有众生从彼闻者。复得数数种诸善根。心生敬信得大称意。彼作是念。释迦牟尼于释种中无上法王。大慈悲者。怜愍世间者。劝喻我等。令我生念发大精进。

作是语已。佛告阿难。谛听谛听。善思念之。吾当为汝分别解说所得果报。

阿难白言。如是。世尊。愿乐欲闻。

佛告阿难。若有众生以念佛故。乃至一花散于空中。如是福德所得果报不可穷尽。阿难。如是众生从前际来。劫数长远。生死流转不可得知。于未来际亦复如是。若有众生以至诚心念佛功德。乃至一花散于空中。于未来世。当得释天王。梵天王。转轮圣王。于其福报亦不能尽。以其善根福报边际不可尽故。要当入般涅槃。何以故。阿难。施佛福田。不以有为果报所能尽边。我说是人必得涅槃。尽涅槃际。

阿难。且置亲承供养我者。且置供养我如芥子等舍利者。且置为我造立形像及诸塔庙而供养者。且置以念佛故乃至一花散于空中而供养者。若复有人在于室内以念佛故。乃至一花散于空中。阿难。我说是人当得涅槃。得第一涅槃。尽涅槃际。最胜涅槃。妙涅槃。清净涅槃。安住涅槃。阿难。以是因缘。诸福田中佛为最。佛为王。何以故。施佛田者。非谓世间果报所能尽也。以是因缘。于佛福田为最第一。阿难。诸佛如来顺正道者。能作无上究竟福田。于佛福田所有施者。必穷尽涅槃际。得第一涅槃。

阿难。且置如是以花散佛所得功德。若复有人但心念佛。一生敬信。我说是人亦当得涅槃果。尽涅槃际。阿难。且置人中念佛功德。若有畜生于佛世尊能生念者。我亦说其善根福报当得涅槃。尽涅槃际。阿难。汝今当观诸佛世尊。与诸众生作福田者。能令众生当得如是神通威力。是故。阿难。汝莫忧悲。若有善男子。善女人。乃至畜生。诸众生等。于佛生信。当得如是神通果报。广大功德。譬如甘露。第一甘露尽甘露际。

阿难。汝以身。口慈孝如来。无量安乐。心无有二。无瞋。无恨无有怨仇。阿难。若有三千大千世界满中须陀洹。斯陀含。阿那含阿罗汉。如苷蔗。竹𥯤。若麻。若草。若有善男子。善女人。若一劫。若减一劫。以诸称意一切乐具恭敬尊重。谦下供养。阿难。于意云何。是善男子善女人所得福德宁为多不。

阿难言。甚多。婆伽婆。甚多。修伽陀。

佛言。阿难。若复有人于诸佛所但一合掌。一称名。如是福德比前福德。百分不及一。千分不及一。百千亿分不及一。数分不及一。迦罗分不及一。何以故。阿难。以佛如来诸福田中为最无上。是故施佛成大功德神通威力。

阿难。且置三千大千世界所有声闻。阿罗汉等。若复三千大千世界满中辟支佛。如甘蔗。竹𥯤。若麻。若草。若有善男子。善女人。若一劫。若减一劫。以诸称意一切乐具恭敬尊重。谦下供养彼辟支佛。若辟支佛灭度后起七宝塔。若有善男子。善女人乃至尽形。以诸香花。涂香。末香。衣服。卧具。宝幢。幡盖恭敬尊重。谦下供养。阿难。于意云何。是人于彼所得福德宁为多不。

阿难言。甚多。婆伽婆。甚多。修伽陀。

佛言。阿难。若复有人于如来所起一净信。思惟。信解。作如是言。诸佛智慧不可思议。以此信解善根功德。比前供养彼辟支佛所得功德。迦罗分不及一。乃至优婆尼沙陀分不及一。何以故。阿难。诸佛世尊。无量大慈。无量大悲。无量戒。无量定无量慧。无量解脱。无量解脱知见。无量修集。无量达证。阿难。诸佛世尊智慧不可思议。诸佛境界亦不可思议。若有供养不可思议者当得不可思议报。

阿难。汝莫忧悲。汝当得大神通功德利益。何以故。阿难。汝以身。口。意慈供养我来过二十年。受持如来八万四千诸法宝聚。于诸多闻最为第一。巧言辩慧问答中最。正智得道。多闻无畏。持修多罗。持毘尼。持摩多罗迦。于诸四众说法不倦。阿难。我灭度后。汝共大德摩诃迦叶当作第一最大导师。大作佛事。阿难。汝莫忧悲。汝当得大神通功德利益。
