大悲经以诸譬喻付嘱正法品第十二
尔时。世尊复告慧命阿难言。且置我今得菩提时功德利益。若我本行菩萨道时功德利益。缘觉尚无。何况声闻及余众生。阿难。我菩萨时久修苦行。弃舍王位。妇儿。妻子及诸婇女。身命。手足。头目。耳鼻。血肉。骨髓及受种种无量苦痛。彼等一切悉为汝等悕求阿耨多罗三藐三菩提故。阿难。一切难舍我悉已舍。所受众苦悉为众生。阿难。此等功德。若我广说则不可尽。如有闻者心则迷闷。况有说者。

阿难。若有众生起一念心。悲愍释迦牟尼如来。应供。正遍知本昔修行菩萨苦行。作如是言。为我等故具受无量种种苦痛。难为之事。阿难。我说彼等一发心者。必定当得最后涅槃。何况我所种善根者。阿难。或有愚人漫捍无信。闻我本修菩萨苦行乃至不生一念悲心。不言如来有大利益。亦不敬信是故所有殊胜行者能得涅槃。阿难。如是功德利益胜法。缘觉所无。何况一切声闻。凡夫所能有也。

阿难。诸有修行菩萨行者所得大悲亦非缘觉所能有也。阿难。若有如我修菩萨行者得于大悲。得大悲已悉皆当得阿耨多罗三藐三菩提。是故此法大慈。大悲之所摄也。以是因缘。缘觉所无。以是义故。彼不得作如来。应供。正遍知。不具十力。四无所畏。大慈。大悲。

阿难。我知本昔修菩萨行推求善法。于彼生死心常惊怖。于诸众生修大悲心。而于梦中见大铁围有崩倒处。世界中间有诸众生在大地狱。为彼狱卒之所逼切。身体碎坏。周遍炽然犹如火聚。受大苦切如夺命苦。我诣其所。彼诸众生合掌礼拜而作是言。仁者。汝今受乐。我等今受地狱之苦。楚毒难忍。如夺命苦。无救。无护。无归。无趣。大丈夫。若欲救我如是苦者。必定堪能。阿难。我时于彼地狱众生起大悲心。即于梦中悲泣流泪如恒河水。我时安慰彼众生言。诸仁者。莫生怖畏。我令汝等脱是苦聚。阿难。我时令彼地狱众生集在一处。以其右手普摩其顶而告之曰。诸仁者。莫生怖畏。我当必定救度汝等。作是语已。地狱火聚实时得灭。其诸众生于刹那顷得受安乐。阿难。我于尔时从梦悟已。振衣取泪以器盛置。阿难。我本如是具大悲法修菩萨行。何况今得阿耨多罗三藐三菩提。阿难。汝应当知如是之法亦非缘觉所能有也。何况声闻。凡夫人等。阿难。若有此法者是修菩萨行。

阿难。当观如来本昔所修菩萨行时于诸众生具足如是怜愍利益大悲之心。如是功德。若我具以口业宣说不得边际。

阿难。过去之世有大商主为采宝故。将诸商人入于大海。彼所乘船众宝悉满。至海中间其船卒坏。时彼商人心怀怖畏。极生忧恼。其中或有得船板者。或有浮者。有命终者。阿难。我于尔时。作彼商主。在大海中用以浮囊安隐而渡。时有五人呼商主言。大士商主。唯愿惠施我等无畏。说是语已。尔时商主即告之言。诸丈夫。勿生怖畏。我令汝等从此大海安隐得渡。阿难。彼时商主身带利剑而作是念。大海之法不居死尸。如其我今自舍身命。此诸商人必能得渡大海之难。作是念已。即唤商人置己身上令善捉持。彼诸商人有骑背者。有抱肩者。有捉髀者。尔时商主为欲施彼无怖畏故。大悲修心。起大勇猛。励身心力。即以利剑断己命根速取命终。于时大海𣿖其死尸置之岸上。时五商人便得渡海安隐受乐。平吉无难还阎浮提。阿难。彼时商主岂异人乎。我身是也。五商人者。今五比丘是也。是五比丘昔于大海而得渡脱。今复于此生死大海而得渡脱。安置无畏涅槃彼岸。

阿难。汝今当观修何苦行具足。云何无量功德得为菩萨摩诃萨也。阿难。如是功德。次第应知。亦非缘觉所能有也。阿难。如诸菩萨功德如是。诸辟支佛无此法故。不作如来。应供。正遍知。不成阿耨多罗三藐三菩提。阿难。以能如是修诸苦行得为菩萨大悲怜愍一切众生。

阿难。复有愚人于我佛所不生敬信。以是因缘不得作阿耨多罗三藐三菩提根本种子。亦不得证无上涅槃。彼若于我心生敬信即便得作菩提种子。能证涅槃。阿难。修少分行得少分功德。修满足行得满分功德。

阿难。我当更说余行决定。若有众生乃至能发一念敬信。以此善根得为种子。何况复种胜上善根。阿难。若于佛所种善根者乃至一念发心念佛。我说彼等犹如甘露。最后甘露。

阿难。行者应当以一切种而念如来。所谓念于如来所念。念如来善根。念如来姓日。姓不相似以苷蔗种上姓生故。姓日者。为离诸暗而作光明。阿难。我生释种故种姓清净。

阿难。当念如来生。念如来种族。念如来姓。念如来积财具足念如来端正。念如来所生国土。念如来相。念如来随形好。念如来十力。念如来四无所畏。念如来十八不共法。念如来所生具足。念如来可美。念如来无愚痴。念如来本行具足。念如来愿具足。念如来戒定慧解脱解脱知见具足。念如来慈悲喜舍具足。念如来威仪具足。阿难。若有人随所念佛。彼彼功德得大神通。大利益。广大功德。犹如甘露。第一甘露。最后甘露。

阿难。我于往昔为菩萨时行檀波罗蜜。我以佛智观彼功德不得边际。何况所修尸波罗蜜。羼提波罗蜜。毘梨耶波罗蜜。禅波罗蜜。般若波罗蜜如是等诸余功德。若彼菩萨未得授记所有功德。佛智观察不得边际。何况授记所有功德。乃至何况得成佛时一切功德。于百千亿那由他劫观察宣说不得边际。何以故。如来。应供。正遍知功德无量。阿难。我以实智观此利益。如是说也。若有忆念我菩萨时功德利益。心生敬信。以此善根悉皆当得后际涅槃。是故。阿难。汝莫忧悲。我为令汝与诸天人作大利益。作大摄受。已说道法。令彼得向无上安隐。后际涅槃。汝等于此勤修方便。慎莫放逸。

尔时。世尊告诸比丘言。吾今后夜当般涅槃。汝等今者最后见我最后受化。最后合会。汝等从今更不见我。我亦不复见于汝等。汝诸比丘。止。莫忧悲。一切所爱。称意之物皆当离散。诸比丘。生法有法。有为法。差别法。觉知法。因缘所生败坏之法。若不灭者无有是处。诸比丘。假使久住。会当去矣。诸比丘。凡有生者无不有死。一切诸行无有常定。究竟不变。诸比丘。生死是苦。涅槃是乐。汝若欲令未得者得。未达者达。未证者证。当勤求之。诸比丘。勤修方便。慎莫放逸。诸佛世尊以不放逸故。得阿耨多罗三藐三菩提及余一切助道善法。是故。汝等当受我化。

尔时大众。比丘。比丘尼。优婆塞。优婆夷。天。龙。夜叉。乾闼婆。阿修罗。迦楼罗。紧那罗。摩睺罗伽。释天。梵天。四天王等。得闻如是最后教已。愁苦不乐。为忧箭所射。啼哭流泪。极大号叫。作如是言。婆伽婆。入槃涅槃一何驶哉。修伽陀。入般涅槃一何驶哉。世间眼灭。世间盲冥。一何疾哉。我今云何与众生宝别离太速。

尔时。阿难闻是语已。瞻仰如来目不暂瞬。即便思惟。悲号啼哭。放身投地。犹如斫倒临峻大树。

尔时。世尊告阿难言。止。莫忧悲。我向岂不如是语汝。一切称意。所爱之事皆当别离。生法。有法。有为法。差别法。觉知法。因缘所生败坏之法。若不灭者无有是处。

慧命阿难闻是语已即白佛言。婆伽婆。我何得不愁。修伽陀。我何得不悲。我与如是众生之宝。众生共乘。众生导师。世间所求。世间归趣。天人大师当有别离。是故。婆伽婆。我何得不愁。修伽陀。我何得不悲。世尊。我与如是大悲怜愍一切众生世间亲友。一切世间眼目之宝。作光明者当有别离。而我自怪心不破裂以为百分。世尊。我复自怪而得住此不取命终。世尊。又我自怪身不破坏犹如麦䴰。世尊。我复思惟。今得如是不命终者皆由如来神力加故。婆伽婆。我那得不愁。修伽陀。我那得不悲。今者如是众生共乘。世间导师。怜愍世者。明当不住。更不可见。

尔时。佛告慧命阿难言。汝爱我耶。

阿难言。甚爱。婆伽婆。甚爱。修伽陀。

佛言。阿难。云何爱我。

阿难言。我爱世尊。非以口业言说可尽。亦不可以喻况能尽。婆伽婆。我爱如是。修伽陀。我爱如是。世尊。我为如来。弃舍身命亦无悋惜。婆伽婆。我爱如是。修伽陀。我爱如是。世尊。我爱如来唯佛证知。婆伽婆。我爱如是。修伽陀。我爱如是。

尔时。世尊复告阿难。汝若爱我。申汝右手来。

尔时。阿难即舒右手。于时世尊以金色右手。其掌柔软。色如紫矿。执阿难手而作是言。阿难。汝若爱我。应当为我而作爱事。何者为我所作爱事。我于无量百千亿那由他阿僧祇劫所习阿耨多罗三藐三菩提大法宝藏。付嘱于汝。汝当随顺。如我所转当如是转。令得广行而不断绝。莫作中间灭法人也。阿难。我今为汝当作护持。令佛所说正法毘尼而得增长。不退减故。不失坏故。

我今说喻。诸有智者从喻得解。譬如贵族。巨富长者。豪富饶财。多诸库藏。所须之物无不具足。如是财宝不共他有。种姓具足籍胄渊远。所生因缘悉亦具足。如是长者生育一子。子既长大。勤教令学历算。书印及余种种深密工巧。深密智慧。子既学已。后时长者语其子言。我今于汝所作已竟。汝既学得历算。书印。深密工巧。深密智慧。今日是我最后教勅。一切财宝是我所有。我今悉当付嘱于汝。汝从今日当学三事可得存我门族旧业。何等为三。一者。欲。二者。精进。三。不放逸。如是。豪贵巨富长者如是善巧教其一子。而彼一子狂惑放逸。父母财产费用皆尽。阿难。于意云何。彼长者子受父教不。

阿难言。不也。婆伽婆。不也。修伽陀。

佛言。阿难。如是长者为与其子作父事不。

阿难言。作也。婆伽婆。作也。修伽陀。

佛言。阿难。如来则为世间之父。汝如一子。今日是我最后教诫。付嘱于汝我此百千亿那由他阿僧祇劫所习无上法宝库藏。汝等亦应学于三事。何等为三。一者。欲。二者。精进。三不放逸。如是。汝等若住三事。我此阿僧祇劫所习无上法宝库藏则得久住。未达善法者令得通达。已通达者令不退失。是故汝等。应当坚持我此阿僧祇劫所习阿耨多罗三藐三菩提法宝库藏。未住三事者。令住三事。未达善法令得通达。已通达者令不退失。何以故。我为慈悲怜愍利益诸世间故。为令彼等得安乐故。阿难。我与世间已作父事。亲友事竟。我于汝等应作已作。

复次阿难。我于阿僧祇劫所习阿耨多罗三藐三菩提法。三事因缘当有隐没。何等为三。一者。无信。二者。不住决定之行。三者。不忏悔。是故。阿难。今当护持正法宝藏。为住深信。决定忏悔。应作欲。进。不放逸等三事方便。如是。汝等于我法尊世间之父。如其子事应作已作。阿难。以是义故。我复说喻。令此无上正法宝藏。而得成就增上付嘱。以此喻故。诸有智者闻说得解。复得增上深爱敬信。便生念言。彼释迦牟尼如来。应供。正遍知为我等故。临涅槃时以其右手执阿难手。付嘱于此阿僧祇劫所习阿耨多罗三藐三菩提法。

譬如商主远游道路。所应作者皆已作讫。阿难。于意云何。而彼商主为当还家。为在道住。

阿难言。世尊。彼来还家。不在道住。

阿难。如是。如来。世间之父。世间亲友。世间导师。是大商主。以阿耨多罗三藐三菩提智。所应作者皆已作讫。更无佛事而可作也。一切众生所应度者皆已度竟。所应度者无不善调。

阿难。有于三事不满。不得。如来。应供。正遍知不般涅槃。何等为三。所谓菩萨摩诃萨未得住于不退转法。若于如来无上正法隐没之时。或经一劫。百劫。千劫或百千劫。百千亿那由他劫。未能得成阿耨多罗三藐三菩提。诸佛世尊虽涅槃时至。见此菩萨善根未熟。为令成熟住不退故。以神通力加其自身住世不灭。待此菩萨得不退已。实时授其次第补处阿耨多罗三藐三菩提记。是佛如来然后入于无余涅槃。是故。我今与弥勒等无量百千亿那由他菩萨摩诃萨授阿耨多罗三藐三菩提记。令其住于阿毘跋致。此是诸佛怜愍众生应作已作。

复次。阿难。若诸众生应于如来当得解脱而未度者。如来终不入于涅槃。若佛世尊知彼无量百千亿劫余佛世尊未出于世。若自世界。若余世界。于五道中所有众生。或经一岁。或百岁。千岁。或百千岁。或百千亿那由他岁。乃至一劫若过一劫。是等于我应得度脱。不于一切声闻。缘觉而得度脱。以佛智慧如是知已。彼佛世尊虽涅槃时至。怜愍彼故。以神通力加其自身住世不灭。乃至令彼得成熟已然后度脱。阿难。此是第二。诸佛世尊应作已作。然后入于无余涅槃。

复次阿难。如来所说。若修多罗。若毘尼。若摩得勒伽。所有深义。非学。无学声闻大众共议能知。于其众中设有比丘生疑欲问。敬重佛故恐畏恼乱。不敢辄问。于是如来。应供。正遍知佛智知已。化作一比丘至如来所问言。世尊。此所作事云何而作。佛即告彼化比丘言。比丘。此所作事应如是作。阿难。此是三事。诸佛世尊必定须作。其事不满不入涅槃。

彼等一切。我于今者已作已满。更无所作。更无所说。阿难。我今已为诸声闻说修学毘尼波罗提木叉。为尽苦故示于正道。说行决定正作其事。是故。阿难。汝等从今。我不说者慎莫说之。我所说者勿令断绝。阿难。如我所说应如是学应如是作。慎莫放逸乐。不放逸故则得道果。以是义故。教勅汝等莫忧莫悲。

阿难。吾今后夜当般涅槃。我今当舍己之国土。己之境界。更不复来至此世界。亦复不到他世界也。汝等从今更不见我。我亦不复见于汝等。阿难。我当入于无余涅槃。如是涅槃寂静清凉。无尘离垢。一切苦息。舍于窟宅。无生。无老。无病。无死。无忧。无悲。无苦。无恼。无不称意。无诸悔恨。无怨憎会。无爱别离。如恒河沙等诸佛世尊。及与一切声闻。缘觉。皆悉已去。今去。当去。

阿难。汝今当观我犹爱彼无余涅槃。有诸愚痴凡夫之人。而不爱彼胜妙寂静安乐涅槃。亦复不能一念发心随顺解脱。是人若能一念发心。以是因缘即为种子当得涅槃。阿难。一切凡夫何有是力。一切凡夫羸劣无力。阿难。我观一切愚痴凡夫犹如麦䴰。是故。阿难。愚痴凡夫何得有力。何得有安。所有不能一念发心顺解脱者。若能发心。决定得为涅槃种子。阿难。一切愚痴凡夫之人。无有戒力。定力。慧力。阿难。我已具足无量佛力。具足阿僧祇不可思议无量无等戒定慧解脱解脱知见力。惭力。愧力。久积集力。智力。舍力。福力。慧力。根力。加力。具足十力。犹故爱彼无余涅槃。

阿难。有诸凡夫暗钝无智。少于知法。乐着生死牢狱缠缚乃至不能一念发心随顺解脱。当令彼等得为涅槃根本种子。阿难。如是。如来所赞。所说诸修多罗留在未来。若佛灭后未来世中有人得闻。闻已发心。则便得入正法宝藏无余涅槃界。

阿难。我当说喻令得增上深解其义。阿难。譬如商主将诸商人涉于广大旷野险路。免诸贼难到无畏城。其中有人失伴在后。极甚怖畏。寻迹而去。逐诸商人。甚大苦恼。得过险路。见诸商伴。阿难。如是。如来成阿耨多罗三藐三菩提已。演说如是诸修多罗留在未来。于佛灭后。有诸善男子。善女人等。若得听闻。闻已发心。到我所留正法宝城。无余涅槃界。到正法城已思惟忆念。护持显说我法宝藏。阿难。我为一人尚当付此无上正法令汝坚持。何况无量百千众生。是故。我今以此亿那由他阿僧祇劫所习阿耨多罗三藐三菩提正法宝藏付嘱于汝。汝等应当善诵坚持。为诸净信四部大众开示分别。莫作中间灭法人也。

阿难。当来之世有诸众生不闻如是修多罗义而生退没。是故。阿难。我当说喻。譬如豪贵巨富长者多饶财宝。库藏盈满。资生所须皆悉具足。然彼长者唯有一子远行他方。时彼长者身遇重病。痛苦极甚。临命终时。以多宝物。摩尼。真珠。琉璃。珂贝。金银钱财寄余长者。作如是言。汝应当知。我子既已远行他方。然我今者身遇重病。不久命终。为我子故。以是无量库藏财宝寄付于汝。如其我子他方来还。为我教之令莫放逸。当令坚住不放逸法。然后付此库藏宝物。当付宝时应作是言。童子。汝父往日临命终时为于汝故。以此宝物寄付于我。今我还汝。是汝己物。应当领受。慎莫放逸。坚持守护勿令损失。尔时。豪贵巨富长者作是语已。即以所有众多宝物而寄付之。彼余长者即便领受。受已不久。其长者子他方而还。彼余长者所受寄物悉不还之。阿难。于意云何。是谁过也。

慧命阿难白佛言。世尊。受寄者过。非余人也。何以故。其受寄者亲自受彼豪贵长者众多宝物。不还彼子故。

佛言。阿难。豪贵长者。喻如来也。临命终者。喻于如来欲入涅槃。言一子者。喻未来世有诸净信善男子。善女人等。远行他方者。喻流转五道。大宝藏者。喻于如来亿那由他阿僧祇劫所习无上大法宝藏。受寄长者。喻于汝等诸大声闻。菩萨摩诃萨。护正法者。阿难。如是亿那由他阿僧祇劫所习无上大法宝藏。为未来世诸善男子。善女人等寄付于汝及大迦叶。弥勒等诸大菩萨。汝等若能顺我付嘱。彼未来世所有受化净信佛子。应以法宝而授与之。何以故。阿难。有诸众生是我往昔为菩萨时所成熟者。以恶业故堕于地狱。畜生。饿鬼。如是众生如来灭后得出恶道。生于人中。所有诸根增长成熟。故于我法中以少因缘能生敬信。其中或有得出家者。闻我所说诸修多罗当发胜行。或于声闻乘。或于缘觉乘。或于大乘而般涅槃。

阿难。我为未来诸善男子。善女人等。付嘱于汝我此百千亿那由他阿僧祇劫所习无上大法宝藏。令彼得闻。何以故。彼等众生若不闻此真道正法。当有退没。是故。我今为彼未来善男子等。付嘱于汝大法宝藏。若彼得闻则无有退。

以是因缘我复说喻。阿难。譬如转轮王广开库藏。勅诸典臣。诸丈夫。汝当布施一切沙门。婆罗门。贫穷乞人及行路者。随其所须。求食与食。须饮与饮。须乘与乘。及以华鬘。涂香。末香。衣服。卧具。清净房舍。活命之具。诸库藏臣得王勅已而不行施。阿难。于意云何。是谁过也。

阿难言。大德婆伽婆。诸藏臣过。非轮王也。

佛言。阿难。如是如是。我为法王。于亿那由他阿僧祇劫广集如是大法库藏。自觉悟已欲令增广。于天人中开示显说。乃至为汝所开示者。为诸敬信沙门。婆罗门。一切凡夫求法义者。悉令得闻。是故。阿难。我今以此大法宝藏。已广开显。付嘱于汝。汝若不为净信沙门。婆罗门。长者。居士及诸凡夫乐法义者广宣分别。则于如来当有过失。何以故。阿难。我为无上法转轮王。多有法宝功德库藏。多诸助道七觉法财。十力无畏皆悉具足。于诸法中而得自在。故名法王。汝持我此八万四千正法宝藏。为诸净信沙门。婆罗门。长者。居士。净信凡夫。诸法师等求法义者。具足演说勿生分别。莫作中间灭法人也。是故。阿难。汝若以我亿那由他阿僧祇劫所习阿耨多罗三藐三菩提无上法宝。能为四众而显说者。则于如来无诸过失。若不说者有大过也。

复次阿难。若漏尽阿罗汉比丘证无为故。不能为他分别显说。是人不益如来导师。亦不护持我之正法。是故我今付嘱汝法。何以故。阿难。譬如有人于大黑暗执持草炬还归舍宅。复有多人欲度黑暗。其执炬者依此草炬得度黑暗到己舍宅。到已除灭而不与他。阿难。于意云何。是人既知草炬未尽。及知大众皆欲度暗。自用此炬而不与他。可名正作为好不也。

阿难言。不也。婆伽婆。不也。修伽陀。

佛言。如是如是。阿难。若有比丘得阿罗汉果。证无为法已。亦知大众度生死暗。而不为他分别显说我阿僧祇劫所习法宝令得增广。是人不名利益导师。不名摄受我之正法。是故阿难。我今以此亿那由他阿僧祇劫所习法宝付嘱于汝。乃至坚持为他广说。勿令断绝如是真道。莫作末后灭法人也。

阿难。若有比丘比丘尼。优婆塞。优婆夷于此法宝自安住已。必能为他分别显说我此亿那由他阿僧祇劫所习法宝。应付彼等当与其分。是故。阿难。我此亿那由他阿僧祇劫所习善法第二付嘱。为于未来诸众生故。勿令如是诸众生等不得听闻而有退失。

复次阿难。譬如豪贵巨富长者多诸库藏。摩尼。真珠。珊瑚。珂贝。资生所须皆悉具足。时有怨家烧其库藏。如是长者复有诸怨及怨亲友。于长者所心常乐作不利益者。有不乐彼得喜乐者。有不乐彼得安隐者。如是诸怨见其大火烧库藏时。舍之默住。不灭此火。而彼长者复有亲善。常欲怜愍利益心者。欲令安隐者。见其火已舍而默住。不欲灭之。阿难。于意云何。如是亲友可名正发随顺理不。

阿难言。不也。婆伽婆。不也。修伽陀。

佛言。阿难。彼等亲友见其大火焚烧库藏舍而不救。故复加增炽。尽烧一切库藏不耶。

阿难言。如是。婆伽婆。如是。修伽陀。

佛言。如是如是。阿难。我于亿那由他阿僧祇劫所习无上善根法宝坏灭之时。有诸比丘心无敬信。毁破净戒习行恶法。于歌舞处能为上首。不乐离欲。修行禅定。心多散乱。懈怠懒惰。少于闻法不乐读诵。何能为他分别显说。令人得闻住持法宝。

复次。阿难。譬如灌顶刹利大王唯有一子远行不在。其刹利王身遇重病。既得病已。以诸宝藏种种杂物。持往寄付大臣。长者。作如是言。若我子还。汝当置立令绍王位。以诸库藏悉皆付之。诸臣长者各各别受彼王所寄。既受寄已王便命终。王命终已。其子行还。即绍王位。既登位已。具得自在。诸臣。长者而不还彼宝藏财物。作如是言。善哉。大王。正法治化。以此宝物赐与我等。阿难。于意云何。其所受寄大臣。长者。于彼王所有过不耶。

阿难言。如是。婆伽婆。如是。修伽陀。彼有过也。

佛言。阿难。其远行者。喻五道众生。病者。喻佛欲入涅槃。多宝藏者。喻三十七助道善法。大臣。长者。喻诸阿罗汉。付宝物者。喻我以此亿那由他阿僧祇劫所习法宝付嘱于汝。乃至如是为彼未来诸弟子故。

阿难。当来之世有诸众生。我于往昔所成熟者。以恶业故生于地狱。畜生。饿鬼。我灭度后于彼命终得生人中。所有诸根增长成熟。于我法中心生敬信。有得出家者。有在家者。有得须陀洹者。乃至有得阿罗汉者。有于学地而命终者。有于佛地发深信者。有种人天诸善根者。如是当得具足利益。有得如是敬信心者作如是言。彼世间父善付我等。复得生于增上敬信。阿难。我为彼故。以此法宝付嘱于汝。乃至令彼得闻如是法宝藏故。是故。阿难。汝当以我大法宝藏。令彼净信诸善男子。善女人等而得闻也。阿难。若不令彼而得闻者。汝于如来则为有过。何以故。阿难。彼善男子善女人等。若闻如是大法宝藏。或有得成殊胜之行。或有得生大爱乐心。或有闻时流泪毛竖。阿难。若复有人闻是法门。念佛功德流泪毛竖者。我记彼等以此善根皆得涅槃。
