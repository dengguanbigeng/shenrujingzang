回向偈
抄经功德殊胜行。无边胜福皆回向。
普愿沉溺诸众生。速往无量光佛刹。
十方三世一切佛。一切菩萨摩诃萨。
摩诃般若波罗蜜。

回向偈

愿以此功德。庄严佛净土。
上报四重恩。下济三途苦。
若有见闻者。悉发菩提心。
尽此一报身。同生极乐国。

