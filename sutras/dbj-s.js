大悲经礼拜品第八
尔时。世尊复告阿难。若有众生闻佛名者。我说是人毕定当得入般涅槃。阿难。若有称言南无佛者。此有何义。

阿难白言。佛是一切诸法之本。佛是眼目能引导者。佛是演说一切法者。善哉。世尊。愿为比丘解释此义。我今亲承得闻持受。

尔时。世尊复告阿难。谛听谛听。善思念之。吾当为汝分别解说。

尔时。阿难闻佛语已而白佛言。愿乐欲闻。

佛言。阿难。所言南无佛者。此是决定诸佛世尊名号音声。阿难。以是决定诸佛名号音声义故。称言南无诸佛。阿难。我为是义故说譬喻。令诸众生于此法中增益信心。复令一切诸善男子。善女人闻佛世尊名号音声深得敬信。

阿难。曾于过去有大商主将诸商人入于大海。到彼海已。其船卒为摩竭大鱼欲来吞噬。阿难。尔时商主及诸商人心惊毛竖。忧愁不乐。恐命不济。无救。无护。无归。无趣。各皆悲泣。呻号。忧悔。种种悲叹。呜呼痛哉。彼阎浮提如是可乐。如是希有。世间人身如是难得。我今当与父母离别。兄弟。姊妹。妇儿。亲戚。朋友别离。我更不见。亦不得见佛。法。众僧。极大悲哭。忧悲不乐。各皆祈请诸尊神天欲求自济。

阿难。尔时商主正见明远。于佛。法。僧心得净信。更不信事诸余天神。尔时。商主告诸商人。诸人当知。若欲存济。免此危难得解脱者。汝等应当一时同声随我所说。假令我等不得解脱。后生善道。时彼商人闻此语已。各言商主。我当从教。唯愿速说。

阿难。尔时商主偏袒右肩。右膝着地。住于船上。一心念佛。合掌礼拜。高声唱言。南无诸佛。得大无畏者。大慈悲者。怜愍一切众生者。如是三称。时诸商人亦复同时合掌礼拜。异口同音唱言。南无诸佛。能施无畏者。大慈悲者。怜愍一切众生者。如是三称。尔时彼摩竭鱼闻佛名号。礼拜音声生大爱敬。得不杀心。时摩竭鱼闻即闭口。

阿难。尔时商主及诸商人皆悉安隐得免鱼难。船及商人所愿得称。安隐而还到阎浮提。时摩竭鱼闻佛音声心生喜乐。更不噉食余诸众生。因是命终。彼命终已得生人中。生人中已于其佛所闻法毘尼。深得净信。舍家出家。得出家已近善知识。谦下供养得阿罗汉道。具足六通。于无余涅槃界而般涅槃。

阿难。汝观彼鱼生。生畜生道得闻佛名。闻佛名已得生人道。因生人道便得出家。得出家已即便得证阿罗汉果。得阿罗汉已便般涅槃。阿难。汝观诸佛神力如是。彼鱼闻已获得神通。名号称誉。毕定利益。何况有人得闻佛名。听闻正法亲于佛所。种诸善根而不毕定利益。

阿难。如我昔说。作少善根得少分报。满分善根得满分报。阿难。所言少分善根者。是人为欲速成熟故。种声闻种子作声闻乘。以是善根得满声闻地。种缘觉种子作缘觉乘。以是善根得满缘觉地。阿难。以是因缘我说少分行。

阿难。言满分行者。是人从无始来。于诸佛所种佛种子。一切善根久远修行。以是善根因缘力故得值诸佛。值诸佛已。为欲积集满足菩提诸善根故。满足菩提诸善根已得成佛道。所谓如来。应供。正遍知。声震于世是名满分行。阿难。此满分行。如我诸经昔已广说。如是次第汝应当知。若少分行得少分果。若满分行得满分果。

阿难。如我经中亦复说言。乃至受持四句偈等。如是说者。我为钝根。薄德。少智诸众生故随宜而说。

阿难。我为一切无归众生为作归趣。无舍众生为作舍宅。无护众生为作救护。无明众生。为作灯明。盲无目者为作眼目。阿难。一切外道。痴冥。无智不能自救。何能救他正作归趣。阿难。我为一切天人教师。怜愍一切诸众生者。于当来世法欲灭时。当有比丘比丘尼于我法中得出家已。手牵儿臂而共游行。从酒家至酒家。于我法中作非梵行。彼等虽为以酒因缘。于此贤劫一切皆当得般涅槃。

阿难。何故名为贤劫。阿难。此三千大千世界劫欲成时尽为一水。时。净居天以天眼观见此世界唯一大水。见有千枚诸妙莲华。一一莲华各有千叶。金色。金光大明普照。香气芬薰甚可爱乐。彼净居天因见此已。心生欢喜踊跃无量而赞叹言。奇哉奇哉。希有希有。如此劫中当有千佛出兴于世。以是因缘。遂名此劫号之为贤。

阿难。我灭度后。此贤劫中当有九百九十六佛出兴于世。拘留孙如来为首。我为第四。次后弥勒当补我处。乃至最后卢遮如来。如是次第汝应当知。

阿难。于我法中。但使性是沙门污沙门行。自称沙门。形似沙门。当有被着袈裟衣者。于此贤劫。弥勒为首。乃至最后卢遮如来。彼诸沙门。如是佛所于无余涅槃界次第当得入般涅槃。无有遗余。何以故。阿难。如是一切诸沙门中乃至一称佛名。一生信者。所作功德终不虚设。

阿难。我以佛智测知法界非不测知。阿难。所有白业得白报。黑业得黑报。若有净心诸众生等作是称言南无佛者。阿难。彼人以是善根必定涅槃。得近涅槃。流注相续入涅槃际。何况值佛在世。亲承恭敬。谦下迎送。尊重供养。及佛灭后供养舍利者。阿难。彼沙门性污辱沙门。自谓沙门。形似沙门者。乃至应有一称佛名。何况余心能生敬信种诸善根。阿难。我为是义说如是偈。

诸佛如是不思议。佛之正法亦复然。
若能敬信不思议。必当获得不思报。
过去一切诸如来。能作光明悲愍者。
亦曾供养大势佛。悟胜菩提不可数。
我昔与檀常相应。布施愍济诸众生。
净信根深勤精进。以勤精进化一切。
爱重众生如父母。兄弟亲戚诸知识。
于诸亲戚无瞋恨。悟胜菩提不可数。
我求安乐菩提时。于无量劫行布施。
悲心怜愍众生故。舍身头目肌肉血。
亦舍无量重王位。所爱妻妾及男女。
无量宝乘象马车。为求最胜菩提故。
无量千万亿劫时。数数精勤而驰走。
净心无量行布施。为求此胜菩提故。
忍受无量众苦恼。冰寒毒热及飢渴。
发勤精进死不舍。为求最胜菩提故。
我若百年及一劫。说其行相不可尽。
悲愍一切众生故。为求安乐胜菩提。
轮回生死常值遇。百千亿数诸如来。
彼诸如来大势力。常以金花而奉献。
肴饍饮食及衣服。涂香末香众花鬘。
多亿宝幢胜幡盖。供养如是诸如来。
无量多亿诸众生。轮回生死无有边。
我常到彼而安慰。胜檀广益一切众。
尸罗羼提勤精进。禅定三昧慧方便。
身等念处四正勤。善修习行四神足。
亦修五根及五力。七菩提分八圣道。
一切助道我修习。悕求此胜菩提故。
我以正智修诸业。无有一切诸不善。
常不放逸修诸行。曾无一毫之过恶。

大悲经善根品第九
尔时。世尊复告阿难。若有众生于诸佛所一发信心。如是善根终不败亡。何况复作诸余善根。阿难。我为众生知彼义故而作譬喻。诸有智者以喻得解。

阿难。譬如有人。析破一毛以为百分。取一分毛霑一滴水。持至我所而作是言。瞿昙。我以此水寄付瞿昙。莫令此水而有增减。亦复莫令风日飘曝干竭此水。不令鸟兽饮之令尽。勿使异水而有和杂。以器盛持。莫置在地。如来尔时即受彼寄。受彼寄已置恒河中。不令入回。亦复不令余物揩突。如是。水滴在大河中随流而去。使不入回。复无遮碍。诸鸟兽等亦不饮尽。如是。水滴不增。不减。一等如故。共大水聚渐入大海。若是水滴。毘岚风起坏世界时。假使是人住世一劫。我亦如是得住一劫。彼人尔时至劫尽时而来我所。作如是言。瞿昙。我本寄水。今有无耶。阿难。如来尔时知彼水滴在大海中见知住处。不与余水共相和杂。不增。不减。平等如故。持还彼人。

阿难。如是。如来。应。正遍知有大神通。有大威力。有多堪能清净大智。不可量智无碍知见。如是等事明了无障。于受寄人中最尊。最胜。若于佛所寄付如是微细水滴。经于久远而不亏损。此义应知。阿难。细毛端者。喻心意识。恒河者。喻生死流。一滴水者。喻一发心微少善根。大海者。喻佛。如来。应。正遍知。所寄人者。喻彼清信婆罗门。长者。居士等住一劫者。喻佛如来受彼寄水终不亏损。亦如彼人寄彼水滴经于久远不亏一毫。如是。阿难。若于佛所一发信心善根不失。何况诸余胜妙善根。我说是人一切悉是趣涅槃果。乃至尽涅槃际。

阿难。设复有人于如来所得一发心。一生敬信。以余不善恶业障故堕在地狱。畜生。饿鬼。以本造业自作自受。若大慈悲诸佛世尊出兴于世。以无障碍智知此众生本作善根。以余不善恶业障故堕在地狱。佛知是已。从彼地狱拔之令出。安置岸上无所畏处。安置岸已。复令众生忆念往昔所作善事。而教之言。善男子。汝等应当忆念往昔所种善根。如是善根在于某时。某世界中。于某佛所修行种植。彼诸人等。承佛威力即得忆念。得忆念已。作如是言。如是。婆伽婆。如是。修伽陀。佛复告言。善男子。汝等昔于诸如来所种少善根。不亏。不损。于彼得利。所谓息一切苦得一切乐。善男子。汝得来此是佛境界。汝于长夜行非境界。从无始来生死流转。汝于佛所种少善根终不亏损。譬如王子。若王。大臣。设有余过闭在牢狱。说本事缘令其改悔。放之令出。

如是。阿难。彼诸众生。本于如来所种善根。设作余恶不善业故。若堕地狱。畜生。饿鬼诸恶道中。若大慈悲诸佛世尊出兴于世。本以发心善根因缘所加持者。佛皆见知。于地狱中拔之令出。安置涅槃清凉岸上无所畏处。置无畏处已。令其忆念而教之言。善男子。汝当忆念以本造作善根因缘得如是报。彼诸众生作如是言。如是。婆伽婆。如是。修伽陀。我等承佛威神加故。如是忆知。

大悲经布施福德品第十
尔时。世尊复告阿难。汝应当知。如是等辈。作少善根终不虚设。乃至发心生一念信。我说是人皆得涅槃。尽涅槃际。以是义故。故作譬喻。令诸清信男子。女人深得净信。转复敬重生大爱乐。欢喜踊跃。

阿难。如捕鱼师为得鱼故。在大池水安置钩饵令鱼吞食。鱼吞食已。虽在池中不久当出。何以故。如是等鱼为彼坚牢钩绳所中。虽复在水。当知是鱼必在岸上。何以故。如是钩绳系岸树故。时捕鱼师来到其所即知得鱼。便牵钩绳安置岸上。随意所用。

如是。阿难。一切众生于诸佛所得生敬信。种诸善根。修行布施乃至发心得一念信。虽复为余恶不善业之所覆障堕在地狱。畜生。饿鬼及诸难处。若佛世尊出兴于世。以佛眼观见诸众生行菩萨乘。若缘觉乘。若声闻乘。此诸众生种诸善根。此诸众生断诸善根。此诸众生堕在退分。此诸众生在胜进分。此诸众生种诸种子置贤圣地。于佛福田。乃至发心一生敬信。修行布施。以此善根。诸佛世尊以佛眼观见此众生发心胜故。从于地狱拔之令出。既拔出已。置涅槃岸。置涅槃已。令其忆念本于某佛种诸善根。彼忆念已。作如是言。如是。婆伽婆。如是。修伽陀。佛言。善男子。汝等以此善根得大果报。得大利益。以于佛所修行布施。种善根故。善男子。如是寄者终不亏损。假使久远。乃至百千亿那由他劫。彼一善根必得涅槃。尽涅槃际。

阿难。所言鱼者。喻诸凡夫。池者喻生死海。钩喻佛所植一善根。绳喻四摄。捕鱼师者喻佛如来。随意用鱼喻诸如来安置众生于涅槃果。阿难。如是次第。汝应当知。若施佛田。假使久远终不败亡。终无穷尽。无有边际。必当趣涅槃果。

阿难。我今当复更作譬喻。若施佛田得第一涅槃。尽涅槃际。阿难。若有众生贪世间报。行世间行。爱乐世间。悕求世间。于诸佛所修行布施。以此善根回向悕求人天善道。复有众生于诸佛所种诸善根。作如是言。以此善根愿我世世莫入涅槃。阿难。是等众生以此善根不入涅槃。无有是处。何以故。阿难。如是诸佛无上福田。无诸荒秽。亦无棘刺。离欲垢过。极甚清净。如是田中种少善根福德种子。于余田中不生长者。于三种菩提能作种子。若无上菩提。若缘觉菩提。若声闻菩提。彼诸善根终不差失。以是布施心生敬信。增上因缘得趣善道及清净法。必入涅槃。

阿难。譬如长者营田之时。地不荒秽。无诸荆棘及以瓦砾。粪坏肥良。垦治调柔。以新种子盛以宝器不腐不败。依于时节下种田中。随时溉灌。锄治。料理。于一切时常善护持。阿难。若是长者营田之士于余时中到彼田所。住在田畔作如是言。咄哉。种子。汝莫作种。莫生。莫长。我不求利。亦不求报。阿难。于意云何。可以田夫语故。种子不生。不作种也。

阿难言。不也。婆伽婆。不也。修伽陀。彼必作果。非无果实。

佛言。如是如是。阿难。若有众生乐着生。死。三有爱果。于佛福田种善根者作如是言。以此善根愿我莫般涅槃。阿难。是人若不涅槃。无有是处。阿难。是人虽不乐求涅槃。然于佛所种诸善根。我说是人必得涅槃。尽涅槃际乃至佛所得一发心。一生敬信种善根者。一切皆当得般涅槃。尽涅槃际。

阿难。于当来世有边地王。彼虽不解佛法功德。见佛精舍及见形像心生信者。我昔曾于五道之中处处受生。修行一切菩萨行时。以四摄法。布施。爱语。利行。同事。摄彼边王。阿难。彼边地王见我精舍及见形像心生敬信。以此善根必得涅槃。尽涅槃际。阿难。彼边地王当有群臣并诸王子。大臣。辅佐。亲戚骨血及诸伴侣。于我灭度后见我精舍及见形像。虽不解知诸佛功德及佛正法。少修善根。心生信者。我本修行菩萨行时亦曾以四摄法摄护彼等。以是善根所加持故。当得涅槃。尽涅槃际。阿难。我于长夜怜愍众生。以四摄法长夜摄受。以诸佛法利益养育。

阿难。汝观如来在路行时。能令大地高处令下。下者令高。高下诸处悉得平正。如来过后地辄还复。一切树林倾侧向佛。树神现身低头礼拜。如来过后树辄还复。丘陵。坑坎。屏厕。臭秽。荆棘。丛林。一切瓦砾皆悉扫除。严治平正清净无秽。馨香芬烈甚可爱乐。众华布地。庄严光丽。如来足履蹈上而过。阿难。汝观如来本所修行诸善功德。在路行时无有众生而不倾侧稽首礼者。无情诸物。大地。山崖。树林。药草。于佛行处无不倾侧。何以故。阿难。我本修行菩萨行时。于诸师所倾侧礼拜。亦于父母第一尊重倾侧礼拜。耆年长宿。中年。少年。亲友骨血无不倾侧。于佛。菩萨善知识所。声闻。缘觉及以外道五通诸仙。沙门。婆罗门。如是一切应受供人。诸佛。菩萨及善知识。声闻。缘觉。外道诸仙。沙门。婆罗门。父母。兄弟。亲友骨血及余耆年。中年。少年。同师等侣。无不倾侧。谦下礼敬。阿难。我以如是善业报故。于无上菩提得成佛已。彼诸事物。有情。无情。如来行时无不倾侧低头礼拜。

阿难。我本曾以清净微妙称意资产。至心自手。施诸师长及余众生。阿难。以是业报。如来行时大地平正。扫洒严治。清净无泥。又无瓦砾。

阿难。我于无量诸如来所。菩萨知识。声闻。缘觉。外道诸仙在路行时。我昔曾与扫治道路。泥治。房舍。若行。若住于佛精舍。我以慈心。平等心。无高下心。无谄曲心。清净心扫治令净。于一切时常求阿耨多罗三藐三菩提。为一切众生故。安乐一切众生故。怜愍一切众生故。利益安乐诸天人故。阿难。以是善根。若佛如来在在处处。若行。若住。若坐。若思惟念欲行来。路首自然街巷清净。地平如掌。阿难。如来所有身业功德殊胜难知。不可得边。

阿难。我今为欲满此义故。当有清信善男子。善女人于如来所深生敬信。得未曾有。阿难。须弥山王高八万四千由旬。在大海中亦八万四千由旬。阿难。假使我灭度时。如此坚固高大山王无不倾侧。何况诸余黑山。药草。丛林。若不倾者。无有是处。

阿难。且置坚固须弥山王。所有铁围山高十六万八千由旬。彼等亦是金刚坚固。佛涅槃时无不倾侧低头礼敬。若欲远避不倾侧者。亦无是处。何以故。阿难。我本修行菩萨行时。一切众生所作事业终不别离。若有众生瞋恚乖张。我令和合。昔不和者能令和合。坚固安住。具足不坏。各生慈心。愍心。阿难。以是善根因缘力故。如来获得不可坏身。亦令眷属坚固不坏。

阿难。如来复获眷属坚固不可坏法。所谓四念处。四正勤。四如意足。五根。五力。七觉分。八圣道分。阿难。此三十七助菩提法是佛如来大眷属。所有诸佛。声闻。缘觉安住其中。一切世间诸天人众所不能坏。何以故。阿难。佛以是法。一切世间诸天。魔。梵。沙门。婆罗门及诸眷属。天人。阿修罗。及须弥山。大铁围山。大地。草木。佛涅槃时。无不低头倾侧而向。何能破坏。若有坏者。无有是处。何以故。阿难。如来身者不可破坏。佛之舍利亦不可坏。

阿难。如来怜愍一切众生。以本愿故碎此舍利令如芥子。为令佛法增广流布。阿难。如来本修菩萨行时发如是愿。我于阿耨多罗三藐三菩提成正觉已。般涅槃后。令我舍利增广流布。阿难。以本愿故我灭度后令此舍利增广流布。彼诸众生见佛如来般涅槃故得圣道果。佛为怜愍彼等众生。分此舍利令如芥子。阿难。如来。应。正遍知临般涅槃时。怜愍世间诸众生故。入如是三昧分此舍利。令如芥子。然如来身不受苦痛。一切支节分散解时能令舍利犹如芥子。时佛如来无有苦痛。乃至如是怜愍摄受彼诸众生及摄未来诸众生故。令得安隐诸善道故。

供养舍利。尊重。迎送。谦下供养。种种庄严。种种华香。涂香。末香。衣服。幢幡及众宝盖。歌舞。音乐。我说彼等当得涅槃果。乃至尽涅槃际。

阿难。我灭度后一百年中。于波离弗城当有国王名阿输迦。于孔雀户种姓中生。以法治世。彼于我法当得敬信。得敬信已令我舍利增广流布。一日一时起八万四千塔安我舍利。阿难。汝莫忧愁。我之舍利于天人中当广流布。

阿难。且置现在供养如来。且置我灭度后供养舍利如芥子者。阿难。若有梦中见佛精舍心生敬信。我说彼人以此善根当得涅槃。得第一涅槃。尽涅槃际。阿难。于未来世所有诸佛出兴于世。是诸如来无不称我功德行者。亦如我今。称赞过去诸佛功德。未来诸佛称我名字亦复如是。

阿难。我说法时。凡诸众生远尘离垢。得法眼者。阿难。彼诸众生。我本修行菩萨行时一切皆悉先已成熟。

阿难。若施僧田功德有尽。施四方僧功德亦尽。施辟支佛所作功德于中不尽。若于佛所作功德者不可穷尽。

复次阿难。如我前说。诸福田所作功德者。皆悉当得涅槃果。尽涅槃际。阿难。且置亲承供养我者。且置我灭度后供养我舍利者。阿难。若有念佛。乃至一华散于空中。我以佛智见彼善根不可量。不可说。阿难。彼等众生所作善根。以念佛心乃至一华散空中者。尽此劫来驰走流转。从初至末不可得知。于流转时。于如来所奉散一华所得果报不可称说。或作梵天王。释天王。转轮圣王。以其善根不可尽故。必得涅槃。尽涅槃际。何以故。阿难。如是诸佛大神通所奉施一华。得如是等无量福报。广大利益。大功德聚。不可称量。无有边际。必当趣涅槃界。

阿难。若于佛所作功德者当得如是不可称量无边福报。乃至佛所得一发心。生一念信者。我说是人梵行究竟。安隐究竟。尽究竟际。是故。阿难。若有善男子。善女人欲求梵天王。转轮圣王。护世四天王。三十三天。夜摩天。兜率陀天。化乐天。他化自在天。及余诸天。诸龙。夜叉。乾闼婆。阿修罗。迦楼罗。紧那罗。摩睺罗伽。人非人等一切世间主得自在者。应当如是尊重。迎送。恭敬。供养诸佛世尊。若欲悕求声闻地者。辟支佛地者及求无上三藐三菩提者。如是善男子。善女人亦应如是恭敬。尊重。谦下供养。

阿难。我昔为求阿耨多罗三藐三菩提时于无量佛。无量百佛。无量百千佛乃至无量亿那由他百千佛所。恭敬。尊重。谦下。供养衣服。饮食。床座。卧具。病瘦因缘所须汤药。若行。若住。若坐。若卧。以诸华鬘。涂香。末香。栴檀。沈水。幢幡宝盖供养彼佛。彼佛灭后。起立塔庙种种庄严。以诸香花。涂香。末香。歌舞。嬉戏。百千伎乐恭敬。尊重。谦下供养。怜愍世间诸众生故。利益安乐诸天人故。未得度者欲令得度。未解脱者令得解脱。未安隐者令得安隐。未涅槃者令得涅槃故。

阿难。我以五茎优波罗华散然灯佛。于彼即悟无生法忍。如是善根是少分报。阿难。我以然灯如来。应。正遍知所。散五茎华及余善根少分福报。汝欲知不。

阿难白言。如是。世尊。愿乐欲闻。如是。婆伽婆。如是。修伽陀。今正是时。唯愿世尊分别显示于然灯佛种少善根所得果报。

尔时。世尊舒金色右臂。以一小指放天优波罗华。香遍满三千大千诸佛世界。百亿日月所流行处无不周遍。尔时。世尊于诸天人。阿修罗中现此奇特未曾有法。于诸佛所种少善根所得福报。示现不虚。不亏损故。

尔时。世尊而说此偈。

诸佛不思议。如来法亦然。
能信不思者。必获不思报。
有想无想等。一切诸众生。
无量百亿劫。一切悉供养。
所有辟支佛。无漏阿罗汉。
不可思议劫。供养彼一切。
正觉若住世。若佛涅槃后。
乃至一合掌。此福胜于前。
佛戒无缺漏。三昧得自在。
于法无疑惑。佛眼无不了。
若于善逝修慈者。若昼若夜少时间。
如是供养福无量。三界无等无有比。
过去阿僧祇劫中。于诸世间导师所。
诸天人中作光明。修诸善业不可数。
阿僧祇劫流转时。受彼福报不可尽。
我以彼福为因缘。能得如是胜菩提。
我昔怜愍众生故。无量百千亿佛所。
世世常修胜供养。佛不与我授记莂。
彼佛世尊人中上。知我善根未纯熟。
虽行诸善不得记。以我无是胜忍故。
我又见彼然灯佛。奉散五茎优波罗。
布发淹泥令佛蹈。即悟无生胜法忍。
时彼导师然灯佛。即授我记升虚空。
汝于来世阿僧祇。当得成佛号释迦。
从此生死流转来。修行无量诸善业。
愍众生故受诸苦。为求如是胜菩提。
我见世间孤独苦。悲心怜愍常布施。
彼福无限无有量。导师广说不能尽。
我为菩萨修行时。于诸善逝佛世雄。
昼夜称名而供养。无量亿劫不可数。
一二三四五至十。二十三十略称名。
愍诸众生故修行。最胜佛本所供养。
如我本修苦行时。无量众苦我忍受。
世世不舍菩提心。一切诸佛无能比。
我于世世流转时。弃舍百千万亿头。
舍宝国土及王位。为求闻法多善说。
我为无上正法时。深心乐求不可量。
布施持戒及忍辱。精进觉悟胜菩提。
诸佛势力不思议。以诸功德所建立。
能演正法不思者。亦能显示胜菩提。

大悲经植善根品第十一
尔时。世尊复告阿难言。我从然灯佛来。次复值佛名莲华上。我以金华奉散彼佛。为求阿耨多罗三藐三菩提故。次复值佛。名一切世间最胜自在。我以银华。奉散彼佛。为求如是一切种智。次复值佛。名极高行。我把宝钱奉献彼佛。为求如是不可知智。次复值佛。名曰上誉。我把众宝奉献彼佛。为求如是无障碍智。次复值佛。号释迦牟尼。我以杂华散彼佛上。为求如是无上菩提。次复值佛。名曰帝沙。我以赤旃檀末涂散彼佛。亦复为求无障碍智。次复值佛。名曰弗沙。我以深信。七日。七夜目不暂瞬。以无量偈赞彼世尊。次复。值佛名毘婆尸。我复以豆散彼世尊。次复值佛。名曰尸弃。我以无价宝衣奉上彼佛。次复值佛。名毘舍浮。我以肴膳饮食供养彼佛世尊。

阿难。此贤劫初次有佛兴。名拘留孙。我于彼所净修梵行。为求如是自然智故。次复值佛。名拘那含牟尼。我于彼佛修行梵行。次复有佛。名曰迦叶。时我于彼亦修梵行。我于是等一切佛所。为求阿耨多罗三藐三菩提。为自度。亦为度未度者。自得解脱。亦为未解脱者令得解脱。自得涅槃。亦为未涅槃者令得涅槃。汝今观我供养尔许无量阿僧祇诸佛世尊。恭敬尊重。谦下供养。具足无量诸善功德。为求如是阿耨多罗三藐三菩提故。阿难。如是次第。汝应当知。虽于佛所种少善根。当得如是大神通。大利益。广大功德。

阿难。我于佛所种植如是不可思议菩提善根。今得如是不思议报。无等。无敌。无有边际。汝应当信。

尔时世尊重说偈言。

我于然灯两足尊。值遇修行菩萨行。
五茎青莲散彼佛。实时记我无上道。
次有佛名莲华上。我时亦复得值遇。
以金宝华散彼佛。为求最胜菩提故。
次复有佛大导师。名诸世间最自在。
极高上行及上誉。释迦帝沙弗沙佛。
毘婆尸弃毘舍浮。拘留孙佛拘那含。
迦叶佛等皆供养。为求最上胜菩提。
此等及余过去佛。我皆修行胜供养。
悲愍一切众生故。为求无上胜菩提。
彼佛千亿皆供养。积集善根已满足。
降魔势力及眷属。获得无忧安隐道。
我转无上大法轮。为众生故显正法。
天人龙等紧那罗。应菩提器我度竟。
我已显示安隐道。未来诸佛及声闻。
若欲救度诸苦者。应当修习我德行。
