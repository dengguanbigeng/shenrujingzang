大随求陀罗尼经序品第一
如是我闻。一时婆伽梵。住大金刚须弥卢峯楼阁。安住大金刚三摩地。以大金刚庄严劫树于大金刚池宝莲花光照。金刚沙而布于地。于大金刚加持。金刚道场天帝释宫殿。以俱胝那庾多百千庄严大金刚师子之座。说法神通处。一切如来神力之所加持。入一切法平等出生萨婆若智。与八十四俱胝那庾多菩萨众俱。皆是一生补处。于阿耨多罗三藐三菩提得不退转。皆得大势。皆悉示现大金刚解脱三摩地佛刹神通。于刹那间随入一切有情心行。成就种种美妙广大甚深巧说诸法。辩才无碍得大神通。悉能供养无量佛世界如来。大供养云海解脱三摩地自在神通。不共觉分道支一切地波罗蜜。善巧四摄慈悲喜舍力远离清净心相续中。其名曰。

金刚藏菩萨摩诃萨。金刚眼菩萨摩诃萨。金刚身菩萨摩诃萨。金刚慧菩萨摩诃萨。金刚手菩萨摩诃萨。金刚相击菩萨摩诃萨金刚那罗延菩萨摩诃萨。金刚游戏菩萨摩诃萨。金刚积菩萨摩诃萨。金刚髻菩萨摩诃萨。金刚妙菩萨摩诃萨。金刚幢菩萨摩诃萨。

如是上首菩萨摩诃萨众俱。

复与大声闻众皆大阿罗汉。断除有结尽一切漏。得善正知。心善解脱。悉能现不思议神通力。神境通游戏。皆得大势。于见无著。离一切垢。焚烧习气种。其名曰具寿舍利子。具寿满慈子。具寿劫宾那。具寿须菩提。具寿迦叶波。具寿大迦叶波。具寿优楼频螺迦叶波。与如是等上首大声闻众俱。复有大自在天子为上首。与无量无边不可说阿僧祇净居天子众俱。

复有娑诃世界主大梵天王为上首。与梵众天子俱。

复有苏夜摩天子化乐天子他化自在天子。及天帝释各与诸天子以为眷属俱。

复有毘摩质多罗阿苏罗王。末离阿苏罗王。令欢喜阿苏罗王。照曜阿苏罗王。罗睺阿苏罗王。如是上首阿苏罗王。与无量无边阿苏罗王以为眷属俱。

复有娑伽罗龙王。德叉迦龙王。嚩苏枳龙王。商佉波罗龙王。羯句咤迦龙王。莲华龙王。大莲华龙王。如是等上首龙王。与无量无边阿僧祇龙王众俱。

复有树紧那罗王。与无量紧那罗王眷属俱。

复有一切义成就持明仙王。与无量持明仙王眷属俱。

复有五髻乾闼婆王。与无量乾闼婆王眷属俱。

复有金银蘖路茶王。与无量蘖路茶王眷属俱。

复有多闻药叉王。宝贤药叉王。满贤药叉王。半支迦药叉王。与无量无边药叉王眷属俱。

复有诃利帝母。与五百子以为眷属俱。复有七护世母天。七大罗刹母。游虚空七仙天。九执曜天。方隅地天。辩才天女名与眷属俱。

复有作障者毘那夜迦。并毕隷多。部多。一切皆是大威德者。各与眷属俱。

复有一切山王。一切海王及护世王水天。并持国天王。增长天王。恶目天王。持棒罗刹主七风天伊舍那天并及其后。与千俱胝那庾多眷属俱。

复有那罗延天。与眷属俱。

复有捺多迦那么迦。噜贺迦。大伽那钵底。弥瞿罗迦如是等毘那夜迦王。与无量无边毘那夜迦以为眷属俱。

复有六十游行诸城堡王与眷属俱。

复有四姊妹女天并兄。以为眷属俱。

复有金刚商羯罗女。与六十四金刚女以为眷属俱。

复有金刚军童子。苏摩呼童子。顶行童子。与无量金刚族以为眷属俱。

复有净信佛法僧。天龙药叉乾闼婆阿苏罗蘖路茶。紧那罗摩户罗伽部多。毕舍遮。阿钵娑么囉。嗢摩那娑𠆙娑。呬里迦。乌萨多罗迦并日月天子。晨朝天。日午天。黄昏天。中夜天。及一切时天。与无量无边阿僧祇眷属俱。于是世尊善转法轮佛事已终。福德智慧究竟圆满。善摄受一切智大菩提。获得炽盛地波罗蜜。以三十二大丈夫相庄严法身。八十四随好庄严一切支分。一切有情无所观顶相。超胜一切魔罗。通达一切智智。具足五眼。一切相成就。一切智智成就。一切佛法成就。摧一切魔异论。高显名称大雄猛师子吼。坏无明黑闇。以无量无边阿僧祇百千俱胝那庾多劫之所积集。施戒忍勤勇静虑般若方便愿力智波罗蜜难行苦行。转得三十二大人相八十四随好庄严。其身坐大宝金刚莲华藏师子之座。其座以无量金刚宝珠罗网庄严。微风摇击出妙音声。以无量金刚界安住神足。以无量金刚宝庄严。摩竭口吐于赤珠。复含在口。以无量宝严饰莲花蕊。虎珀大虎珀。帝青大帝青。补沙罗伽。庄严光网普遍端严。以无量金刚宝庄严幰盖柄。以无量俱胝那庾多百千劫树。荫影庄严。其座广博大如须弥。犹如金山。吉祥炽盛光明庄严。照过千日。其地圆满犹如净月。令诸有情深所乐见如来之法。如大劫树其花开敷。所说妙法初中后善。其义深远其语巧妙。清净洁白纯一无杂。

尔时。世尊从顶毫相。放大光明，其光名曰现一切如来光网。由此光明。普照三千大千世界乃至如恒河沙数佛世界。于彼世界所有如来。于大庄严楼阁无量宝庄严师子座上说法。并一切菩萨及大声闻苾刍苾刍尼净信男净信女。天龙药叉乾闼婆阿苏罗蘖路茶紧那罗摩户罗伽。悉皆照曜显现分明。尔时世尊普为一切说伽陀曰。

我今说随求。愍念诸有情。此大陀罗尼。能摧难调者。
诸极恶重罪。若得才闻此。随求陀罗尼。一切罪消灭。
安乐诸有情。解脱一切病。大悲众生故。是故世尊说。
为获解脱故。远离诸恶趣。若入修罗宫。药叉罗刹宫。
步多龙鬼神。如是诸宫殿。随意悉能入。皆用此大明。
而作于加护。斗战危险处。不被怨沮坏。并诸鬼魅等。
由称陀罗尼。诸魅悉坏灭。娑謇嗢未那。毕舍拏吉你。
猛恶吸精气。常害有情类。彼皆悉殄灭。由随求灭德。
他敌皆灭坏。所作剧厌祷。咒诅法无效。定业不受报。
不被蛊毒中。水火及刀杖。雷电与霜雹。黑风恶暴雨。
诸难皆得脱。冤敌悉降伏。若人持此明。或带于颈臂。
所求愿悉成。一切所希愿。悉皆得如意。天王皆加护。
及诸大龙王。菩萨大勤勇。缘觉及声闻。一切诸如来。
明妃大威德。悉皆而拥护。受持随求者。金刚秘密主。
护世四天王。于彼持诵人。昼夜常加护。帝释忉利众。
梵王毘纽天。及摩酰首罗。众生俱摩罗。大黑喜自在。
一切天母众。及余诸魔众。苦行威德仙。及余密语天。
皆悉来拥护。持此随求者。大威德菩萨。明妃大悲尊。
勇猛具神力。摩摩毘俱胝。多罗央俱尸。及余金刚锁。
白衣及太白。圣摩诃迦离。使者金刚使。妙索金刚索。
执轮大力者。金刚鬘大明。甘露军咤利。无能胜明妃。
黑耳吉祥天。大福威德尊。莲花军咤利。花齿及珠髻。
金发宾蘖罗。大威德吉祥。及电庄严天。一髻大罗刹。
及佛地护尊。迦波利明女。楞伽自在尊。及余多类众。
彼等皆拥护。由大明在手。诃利帝及子。半支迦大将。
商弃尼积齿。吉祥及辩才。由持此密言。昼夜常随逐。
若有诸女人。持此陀罗尼。彼皆悉成就。男女在其胎。
安隐胎增长。产生皆安乐。一切病悉除。诸罪皆消灭。
福力常具足。谷麦及财宝。悉皆得增长。出言令乐闻。
所至获恭敬。男子及女人。清净能受持。常怀慈悲心。
拔济诸有情。皆愿获安乐。令彼离疾病。国王并后宫。
皆生恭敬心。吉祥常炽盛。福聚皆增长。一切真言法。
皆悉得成就。成入一切坛。得成三昧耶。如来诚实说。
