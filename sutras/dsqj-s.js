尔时焰魔卒还至王所。具以上事白焰魔王。其苾刍承此陀罗尼威力。罪障消灭得生三十三天。因号此天为先身随求天子。大梵当知此陀罗尼有大威力。汝当受持书写读诵依法佩带。常得远离一切苦恼一切恶趣。不被电雹伤害云何得知。大梵于形愚末坛城。有一长者名尾么罗商佉。其家巨富库藏盈溢。金银充满多饶财谷。于是长者身作商主。乘大船舶入海采宝。于大海中遇低弥鱼欲坏其船。海中龙王复生瞋怒。起大雷震哮吼掣电雨金刚雹。时诸商人见此雷雹。各怀忧恼生大恐怖。叫呼求救无救济者。时众商人前诣商主。悲声号哭白商主言。仁者当设何计救护我等令离忧怖。

尔时商主其心无畏。志性坚固有大智慧。见诸商人恐怖逼迫。而告之言。汝等商人勿怖勿怖生勇健心。我令汝等免斯怖畏。其诸商人心生勇健。复作是言。大商主唯愿速说除灾难法。令我等命皆得存济。于是商主即告商人言。我有大明王名随求陀罗尼。能降伏诸难调者有大神通。令汝解脱如此忧恼。即便书写此随求陀罗尼。安幢刹上其低弥鱼应时即见此船。光明赫奕如炽盛火。由此陀罗尼大威力智火。烧低弥鱼即便锁融。彼诸龙等见是相已。悉起慈心。从空而下广作供养。令此船舶直至宝洲。大梵此皆大智大明大随求。以一切如来神力之所加持。是故名为大明王。若有书写此陀罗尼安于幢刹。能息一切恶风雹雨非时寒热雷电霹雳。能息一切诸天斗诤言讼。能除一切蚊虻蝗虫及诸余类食苗稼者。悉当退散。一切应言利王爪者不能为害。一切苗稼花果药草悉皆增长其味香美柔软润滑。若其国内旱涝不调。由此陀罗尼威力。龙王欢喜雨泽及时。

复次。大梵。若有流布此大随求陀罗尼之处。是诸有情既知是已。当以上妙香花幢盖种种供养。应以殊胜缯彩。缠裹经夹安于塔中或置幢刹。以种种音乐歌咏赞叹。旋绕供养虔诚礼拜。彼等有情心所思惟。所希求愿皆得满足。若能依法书写。身上带持所求皆得。求男得男求女得女。怀胎安隐渐增圆满产生安乐。

大梵云何得知。往昔曾于摩伽陀国。有王名施愿手。以何因缘名施愿手。其王初生之时。即展其手执母奶嗍奶足已。由手触母奶。是其母奶变为金色。母奶增长自然流出。若有众人来乞求者。王舒右手有净信佛菩萨诸天。倾写种种诸妙珍宝。入王手中施求乞者。随其所须皆得满足。一切悉得安乐成就。以是因缘名施愿手。其王为求子故。供养诸佛及诸塔庙求子不得。王持斋戒广设无遮施会。大作福业护持三宝。修理未来破坏寺舍故。置一库藏。何以故大梵我念过去。于此摩伽陀国境俱尸那城大力士聚落多如来教法中。有一长者名曰法慧。于一切众生起大悲心。为诸有情说此大随求陀罗尼法要。当彼之时于长者家有一贫人。闻此妙法告长者子言。长者子我于汝家中作务常乐听法。我当供养此法。彼贫匮人于长者家营事复供养法。于过后时其长者子与一金钱。其人得已发菩提心。为拔济众生故以此福回施一切有情。所得金钱便将供养此大随求陀罗尼。作是愿言。以此舍施之福。愿一切有情断其贫匮之业。由此因缘其舍施福无有尽期。如是多种福因缘故。供养诸佛菩萨。由此福业。净居天子现于梦中而告王言。大王今可依法书写此随求陀罗尼令国大夫人斋戒带持。即有子息。其王觉已。召占相人及有智婆罗门众。择吉宿曜直日。依法斋戒书写此陀罗尼。令夫人带于颈下。复更供养窣睹波塔诸佛菩萨。广行舍施。应时有胎。日月满足产生一子。色相具足端严殊胜见者欢喜。大梵当知此是无能胜无碍大随求宝印心大明王陀罗尼威力故。一切如来之所供养。所求愿者皆得称心。

