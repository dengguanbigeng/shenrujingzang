以此明加护。合死得解脱。若以黑索羂。将至阎魔宫。
命复倍增寿。由书带大护。若有寿尽者。七日后当死。
才书带此明。无上大加护。或若才闻故。依法加持者。
处处获安隐。随意受安乐。六十八俱胝。一百那庾多。
三十三诸天。辅翼于帝释。来护于此人。随逐作加护。
四大护世王。金刚手大力。一百明族众。常加护彼人。
日天及月天。梵王与毘纽。自在夜摩天。宝贤及力天。
满贤大勇猛。诃利帝及子。半遮罗半支。俱摩罗众主。
吉祥大明妃。多闻及辩才。商弃尼华齿。一髻大威德。
如是大药叉。常当而拥护。石女生子息。胎孕咸增长。
常加护彼人。乃至寿命存。丈夫常得胜。恐怖斗战处。
由此满诸愿。由依净信天。诸罪悉消灭。由书此大明。
诸佛常观察。大威德菩萨。彼名称增长。福寿亦复然。
财谷皆丰盛。获得悉无疑。睡眠及觉悟。悉皆得安乐。
怨家及鬼神。皆不能沮坏。当于斗战时。常皆获得胜。
若修密言时。此护最为胜。安乐修诸明。悉得无障碍。
一切密言教。悉皆得成就。成入一切坛。速成三昧耶。
乃至于来世。诸佛皆委寄。由持此大护。诸吉祥皆满。
意愿悉成就。由才书此明。一切乐丰盛。安乐而舍寿。
必生于善趣。欲生极乐国。持带此明王。决定无疑惑。
斗诤于言讼。战阵大怖中。诸怖皆远离。如佛诚言说。
常获宿命智。生生皆无疑。国王皆欢喜。及后宫眷属。
尽皆常恭敬。常与善人和。皆悉生怜愍。并人及与天。
令彼作加护。常恒于昼夜。大护成就明。等正觉所说。

