转读并念诵。及为他宣说。诸法皆通达。如是得法味。
诸罪即消灭。心意所乐求。诸事皆成就。一切死怖中。
毕获而救护。王官及水火。霜雹并劫贼。斗战及言讼。
利牙爪兽难。一切悉消融。由诵洛叉遍。速成就此明。
一切诸佛说。称诵令欢喜。满菩提资粮。一切所住处。
若用此大明。而作于加持。欲作诸事业。自他利益事。
任运得成就。以大护无疑。大梵汝当知。我今复宣说。
为患重病人。应作四方坛。瞿摩和土泥。用五色粉画。
而作曼荼罗。四瓶安四角。智者依仪轨。坛上散诸花。
应烧殊胜香。及种种饮食。人见令净信。如是用香花。
依法而奉献。四角插四箭。用五色缕缠。令病者澡浴。
身著清净衣。遍体而涂香。引入坛中心。面对东方坐。
尔时持明者。先诵此大明。令满于七遍。自加持己身。
次诵三七遍。加持于病者。由诵此大护。诸疾皆息除。
即取一水瓶。盛香花饮食。七遍作加护。东方远弃掷。
次取南方瓶。花香食如教。准前诵七遍。远弃掷南方。
次用西方瓶。花香及饮食。依前加持法。北方亦复然。
尔时持诵者。仰面向上方。诵此明一遍。成最胜加持。
大梵作是已。一切苦悉除。如是加持法。释师子所说。
一切诸法中。无有能与比。三界中胜护。彼人无夭死。
