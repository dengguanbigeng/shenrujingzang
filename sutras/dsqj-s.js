复次大梵。其天帝释共阿苏罗斗战之时。帝释常以此陀罗尼。置于顶髻珠中带持。帝释天众不被伤损。而常得胜安隐还宫。初发心菩萨乃至究竟地菩萨。带持能离种种障难魔业故。若有人带此陀罗尼。一切如来之所加持。一切菩萨之所护念。一切人天国王王子大臣婆罗门长者。常恒恭敬礼拜承事。一切天龙阿苏罗蘗路茶紧那罗摩睺罗伽人非人等。皆供养彼带持者。彼等天龙八部皆言。彼人是大丈夫。如来复言彼善男子善女人。能摧一切魔障。离一切疾病。离一切灾横。除一切忧恼。恒为一切天龙之所守护。

佛告大梵。复有四陀罗尼。是无能胜妃大心真言。若有书写带佩于身。常应诵持深心思惟观行。能除恶梦不祥之事。一切安乐皆得成就。

唵。阿蜜哩多嚩㘑。嚩囉嚩囉。钵囉嚩囉尾戍第。吽吽。颇咤颇咤。娑嚩贺。

唵。阿蜜哩多。尾卢枳𩕳。蘖婆僧囉乞洒抳。阿羯哩洒抳。吽吽。颇咤颇咤。娑嚩贺。

唵。尾磨黎惹也嚩㘑。阿蜜哩帝。吽吽。吽吽。颇咤颇咤。颇咤颇咤。娑嚩贺。

唵。跛囉跛囉。三跛囉三跛囉。印捺囉也。尾戌驮𩕳。吽吽。噜左㘑。娑嚩贺。

才说此四大陀罗尼已。一切诸佛诸大菩萨声闻。异口同音说此大随求大明王无能胜陀罗尼甲冑密言句。以一切如来印印之。此甚难得闻。何况书写。受持读诵。为他宣说。是故当知是大佛事。如来深极赞叹说随喜者。极难得闻。此大随求大无能胜陀罗尼名。极难得闻极甚难得。能尽诸罪。大力勇健具大威德神力。能生无量功德。能摧一切魔众。能断一切习气聚及魔罗羂。能除他真言毒压祷药法相憎法降伏法。能令恶心众生起大慈心。能护爱乐供养佛菩萨圣众之人。能护书写受持读诵听闻大乘经典者。又能满足修佛菩提者。大梵持此大随求无能胜明王。不被沮坏。于一切处获大供养。如佛大师两足之尊。云何得知。此明王能摧一切诸魔。大梵过去有佛。号广博微笑面摩尼金宝光焰照曜高勇王如来应正觉。初成道时。往诣菩提场欲转法轮。一切如来称赞。尔时一切魔并无量俱胝那庾多眷属围绕。现种种形作可畏声。示种种魔境现作神通。雨种种器仗来往四方而作障难。

尔时广博微笑面摩尼金宝光焰照曜高勇王如来。于须臾顷寂然而住。意诵此大随求大明王无能胜大陀罗尼七遍。才诵此陀罗尼已。于刹那顷一切魔波旬。见彼如来一一毛孔。出无量俱胝百千那庾多金刚使者。身彼甲冑放大光明。各持刀剑钺斧羂索杖棒三戟叉。各出如是言。捉缚恶魔摧恶心者。斩断其命粉粹诸魔作如来障碍者。即彼一切难调恶魔。以如来大威力。于毛孔中出大丈夫。是诸魔众闷绝擗地。皆失自性神通辩才四散驰走。如来以大慈剑。得胜魔境。成无上菩提。即转一切如来法轮。如一切佛一切障者毘那夜迦。诸恶魔等。悉皆摧坏如来即转法轮。超越生死大海得到彼岸。如是大梵此陀罗尼。有大势力能获神通到于彼岸。若才忆念。于危险处皆得解脱。意乐清净恶心有情起大慈心。是故大梵常当忆念。如理作意依法书写而常带持。

复次。大梵乌禅那城有王。名曰梵施。彼有一人犯王重罪。王勅杀者一人领彼罪人将往山中令断其命。杀者受教领彼罪人。至于山窟将刀欲杀。是其罪人先于右臂。带此随求无能胜陀罗尼。心复忆念。由此大明威力。其刀光焰状如火聚。片片段坏犹如微尘。尔时。杀者见此事已。怪未曾有。即以上事具白于王。其王闻已便生大怒。复勅杀者将此罪人送药叉窟。于彼窟中有众多药叉。令食此罪人。受王勅已即领罪人送药叉窟。才送窟中时。药叉众欢喜踊跃奔走向前。欲食罪人。以彼罪人带大随求威德力故。时众药叉见彼罪人身上有大光明炽盛晃曜。诸药叉众悉皆惊怖。各作是念。此火欲来烧我。彼药叉众见是事已甚大惊怖。送此罪人安窟门外旋绕礼拜。

尔时使者具以上事复白于王其王闻已倍更瞋怒。又勅使者缚彼罪人掷深河中。奉教往掷。才入河中河便枯竭犹如陆地。时彼罪人便住于岸。所被系缚绳索片片断绝。王闻此事极大惊怪。熙怡微笑生大奇特。唤彼罪人问其所缘。汝何所解。罪人白言大王我无所解。我于身上唯带大随求无能胜大明王陀罗尼。王即赞言甚大奇特。此大明微妙能摧死罚。说伽陀曰。

大明甚微妙。能摧于死罚。诸佛所加持。拔济诸有情。
