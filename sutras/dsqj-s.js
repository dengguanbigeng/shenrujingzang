佛告大梵。若有人以如来身明陀罗尼句作加持救济摄受加护。能作息灾作吉祥法。遮止谪罚成大加护。若人寿命欲尽。诵此真言复得延命增寿。久久命存常获安乐得大念持。若以金刚杵才念诵加持。或有非命患大疾者。皆得解脱。一切疾病皆得除灭。长患病者诵此真言。加持袈裟角拂彼病人便即除差。日日诵持者。得大聪慧威力大勤勇辩才成就。一切罪障定受业报悉皆消灭。一切佛菩萨并天龙药叉等。于受持陀罗尼者。当令精气入身增加威力。身心常得喜悦。大梵此大明王大护陀罗尼。若有乃至傍生禽兽耳根所闻。彼等悉皆于无上菩提永不退转。何况净信善男子善女人。苾刍苾刍尼邬波索迦邬波斯迦。国王王子婆罗门刹利及诸余类。一闻此大随求大护陀罗尼。闻已深心净信恭敬书写读诵。生殷重心修习。为他广演流布。大梵悉皆远离八种非命。彼人身中不生疾病。不被火毒刀杖蛊毒压祷咒诅诸恶药法之所损害。不被身痛头痛。及诸疟病一日二日三日四日乃至七日。及癫痫病悉不能为患。正念睡眠正念觉悟。证大涅槃。现世得大富贵自在。所生之处于彼彼处常得宿命。一切人天皆悉爱敬容仪端正。一切地狱饿鬼傍生皆得解脱。犹如日轮以光明照曜一切有情。譬如月轮以甘露灌洒一切有情身。得适悦其人。以法甘露遍入一切有情心相续中。皆令滋泽欢喜。一切诸恶药叉罗刹。步多。毕㘑多。毕舍遮。癫痫鬼。拏枳宁诸魅。毘那也迦等悉皆以此大随求大护威力不能侵恼。若来逼近。忆念此大护明王。则一切恶心之类。于持诵之人发生欢喜受教而去。由此大随求大护明王威力。终无怨敌怖畏。是诸怨敌不能凌突。或若有人于国王大臣婆罗门长者处。所犯愆过罪合当死杀者。持刀剑临刑之时。若才忆念此大护明王。其刀片片断坏犹如微尘。其人当彼之时。得悟一切法平等。获大念力。尔时如来说伽陀曰。

此大护加持。清净灭诸罪。能作慧吉祥。增长诸功德。
